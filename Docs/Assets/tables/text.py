"""The words of the README tables, in each README language.

`tables.py` draws them; `ALT` is the matching alt text for the README.
"""

REPO_PATHS = [
    ("core", ["`crates/bern`", "`crates/bern-macros` · `bern-syntax`", "`crates/bern-compiler` · `bern-ir`"]),
    ("runtime", ["`crates/bern-protocol` · `bern-command` · `bern-runtime`", "`crates/bern-ffi`",
                 "`crates/bern-transport-ipc` · `-ws`"]),
    ("targets", ["`crates/bern-backend-swiftui` · `-winui3` · `-gtk` · `-compose` · `-web`", "`crates/bern-gtk`",
                 "`crates/bern-theme`"]),
    ("entries", ["`crates/bern-adapter-cli` · `-mcp` · `-json`", "`crates/bern-cli`"]),
    ("examples", ["`examples/showcase`", "`examples/hello`", "`examples/planner`", "`Docs/`"]),
]


def repo(groups, descriptions):
    """Pair the shared paths with one language's group names and descriptions."""
    out, rest = [], list(descriptions)
    for (key, paths), label in zip(REPO_PATHS, groups):
        out.append((label, [(path, rest.pop(0)) for path in paths]))
    return out


STATS = [("macOS", ["39 MB", "{s04}", "2.7 MB"]), ("Windows", ["35 MB", "{s03}", "4.2 MB"]), ("Web", ["–", "–", "189 KB"])]


def stats(head, second):
    rows = [(name, [v.replace("{s04}", f"0.4 {second}").replace("{s03}", f"0.3 {second}") for v in values])
            for name, values in STATS]
    return ("stats", (head, rows))


def measured_values(second):
    return [[("0.41", second), ("39", "MB"), ("2.7", "MB")],
            [("0.32", second), ("35", "MB"), ("4.2", "MB")],
            [("–", ""), ("–", ""), ("189", "KB")]]


def measured(labels, second, notes):
    names = (("macOS", "SwiftUI"), ("Windows", "WinUI 3"), ("Web", "WebAssembly"))
    return dict(labels=labels, platforms=[dict(name=n, toolkit=k, values=v, note=note)
                                          for (n, k), v, note in zip(names, measured_values(second), notes)])


