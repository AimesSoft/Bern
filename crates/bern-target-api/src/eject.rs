//! Standalone native project ejection (`bern eject`).
//!
//! Each target can emit a self-contained native IDE project that no longer
//! depends on `bern-cli`: either carrying the complete Rust engine workspace
//! (`EjectEngine::Source`) or linking a prebuilt engine binary
//! (`EjectEngine::Prebuilt`).

use crate::{BuildContext, BuildStep, Diagnostic, GeneratedFile};
use bern_ir::Application;
use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

/// How the Rust engine is delivered inside an ejected native project.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EjectEngine {
    /// Ship a self-contained offline Rust workspace alongside the native IDE
    /// project and wire the native build system to invoke `cargo`.
    Source,
    /// Pre-compile the Rust engine binary and link it directly from the native
    /// IDE project so the ejected project builds without Rust installed.
    Prebuilt,
}

/// Options controlling how a target generates a standalone native project.
#[derive(Clone, Debug)]
pub struct EjectOptions {
    pub engine: EjectEngine,
    /// Keep the application CLI and IPC control channel when true.
    pub with_cli: bool,
    /// Build optimized binaries when prebuilding the engine.
    pub release: bool,
    /// Temporary directory for staging Rust glue crates during `Prebuilt`
    /// compilation (never copied into the ejected output directory).
    pub staging_dir: PathBuf,
}

/// Result of ejecting one target into a standalone native project.
#[derive(Clone, Debug, Default)]
pub struct EjectedProject {
    /// Files written into the ejected project root (`context.output_dir`).
    pub files: Vec<GeneratedFile>,
    /// Relative paths under `context.output_dir` that need the executable bit
    /// on Unix (for example `scripts/build-rust.sh`).
    pub executables: Vec<PathBuf>,
    /// Relative paths of generated Rust entry `Cargo.toml` manifests inside
    /// `context.output_dir` whose local and Bern dependencies must be vendored
    /// offline (used for `EjectEngine::Source` and optional `--with-cli` tools).
    pub rust_manifests: Vec<PathBuf>,
    /// Directory (relative to `context.output_dir`) where vendored Rust crates
    /// are placed (for example `rust` for Xcode/Gradle/VS, `.` for Cargo apps).
    pub rust_root: PathBuf,
    /// Temporary glue files written into `options.staging_dir` before running
    /// `prebuilt_steps`.
    pub prebuilt_staging: Vec<GeneratedFile>,
    /// Build steps that compile the Rust engine and copy the resulting binary
    /// artifacts into `context.output_dir` (used when `engine == Prebuilt`).
    pub prebuilt_steps: Vec<BuildStep>,
    /// Short next-step notes printed to the user after ejection completes.
    pub notes: Vec<String>,
}

/// Return a copy of `context` adjusted for ejection (`release`, and stripping
/// the `ipc` channel unless `--with-cli` was requested).
pub fn sanitized_context(context: &BuildContext, options: &EjectOptions) -> BuildContext {
    let mut cloned = context.clone();
    cloned.release = options.release;
    if !options.with_cli {
        cloned.target.channels.retain(|channel| channel != "ipc");
    }
    cloned
}

/// Read all declared application resources (`app.resources`) from disk and
/// return them as [`GeneratedFile`] entries below `dest_prefix`.
pub fn copy_declared_resources(
    app: &Application,
    context: &BuildContext,
    dest_prefix: &Path,
) -> Result<Vec<GeneratedFile>, Vec<Diagnostic>> {
    let mut files = Vec::new();
    let mut seen = BTreeSet::new();
    for resource in &app.resources {
        if !seen.insert(resource.name.clone()) {
            continue;
        }
        let source = crate::svg::resource_path(context, &resource.name);
        let contents = std::fs::read(&source).map_err(|error| {
            vec![Diagnostic::error(format!(
                "cannot read resource `{}` ({}): {error}",
                resource.name,
                source.display()
            ))]
        })?;
        files.push(GeneratedFile {
            path: dest_prefix.join(&resource.name),
            contents,
        });
    }
    Ok(files)
}

/// Remove `Do not edit` / generated banners from text files so ejected sources
/// read as user-owned code.
pub fn clean_source_text(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for line in text.split_inclusive('\n') {
        let trimmed = line.trim();
        let newline = if line.ends_with("\r\n") {
            "\r\n"
        } else if line.ends_with('\n') {
            "\n"
        } else {
            ""
        };
        if trimmed == "// Generated by Bern from the Rust declarations. Do not edit."
            || trimmed == "// Generated by Bern. Do not edit."
        {
            out.push_str("// Ejected from Bern — edit freely.");
            out.push_str(newline);
        } else if trimmed == "//! Generated by Bern. Do not edit." {
            out.push_str("//! Ejected from Bern — edit freely.");
            out.push_str(newline);
        } else if trimmed == "# Generated by Bern. Do not edit."
            || trimmed == "# Generated by Bern. No application engine is linked here."
        {
            out.push_str("# Ejected from Bern — edit freely.");
            out.push_str(newline);
        } else if trimmed == "rem Generated by Bern. Do not edit." {
            out.push_str("rem Ejected from Bern — edit freely.");
            out.push_str(newline);
        } else if trimmed.contains("Generated build input; do not edit.") {
            out.push_str(&line.replace(
                "Generated build input; do not edit.",
                "Ejected from Bern; edit freely.",
            ));
        } else if trimmed.contains("Generated build input; do") {
            out.push_str(&line.replace("Generated build input; do", "Ejected from Bern;"));
        } else if trimmed == "// not edit." {
            out.push_str("// edit freely.");
            out.push_str(newline);
        } else if trimmed.contains("Do not edit.") {
            out.push_str(&line.replace("Do not edit.", "Edit freely."));
        } else {
            out.push_str(line);
        }
    }
    out
}

/// Clean generated-banner comments from text files while leaving binaries
/// untouched.
pub fn clean_generated_file(mut file: GeneratedFile) -> GeneratedFile {
    let text_ext = file
        .path
        .extension()
        .and_then(|ext| ext.to_str())
        .is_some_and(|ext| {
            matches!(
                ext.to_ascii_lowercase().as_str(),
                "swift"
                    | "h"
                    | "m"
                    | "kt"
                    | "kts"
                    | "cpp"
                    | "cc"
                    | "c"
                    | "inl"
                    | "hpp"
                    | "rs"
                    | "js"
                    | "mjs"
                    | "css"
                    | "html"
                    | "toml"
                    | "xml"
                    | "properties"
                    | "sh"
                    | "cmd"
                    | "bat"
                    | "rc"
                    | "plist"
                    | "md"
                    | "txt"
                    | "manifest"
                    | "desktop"
            )
        });
    if text_ext && let Ok(text) = std::str::from_utf8(&file.contents) {
        file.contents = clean_source_text(text).into_bytes();
    }
    file
}

/// Convert an identifier (`home_page`, `settings-pane`) to a clean PascalCase
/// file stem (`HomePage`, `SettingsPane`).
pub fn pascal_filename(name: &str) -> String {
    let mut out = String::new();
    let mut upper = true;
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            if upper {
                out.push(ch.to_ascii_uppercase());
                upper = false;
            } else {
                out.push(ch);
            }
        } else {
            upper = true;
        }
    }
    if out.is_empty() || out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        out.insert_str(0, "Item");
    }
    out
}

/// Convert an identifier (`HomePage`, `settings-pane`) to a clean snake_case
/// file stem (`home_page`, `settings_pane`).
pub fn snake_filename(name: &str) -> String {
    let mut out = String::new();
    let mut prev_lower_or_digit = false;
    for ch in name.chars() {
        if ch.is_ascii_uppercase() {
            if prev_lower_or_digit && !out.ends_with('_') {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
            prev_lower_or_digit = true;
        } else if ch.is_ascii_alphanumeric() {
            out.push(ch);
            prev_lower_or_digit = true;
        } else if !out.is_empty() && !out.ends_with('_') {
            out.push('_');
            prev_lower_or_digit = false;
        }
    }
    while out.ends_with('_') {
        out.pop();
    }
    if out.is_empty() || out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        out.insert_str(0, "item_");
    }
    // Avoid Rust keywords as module filenames.
    if matches!(
        out.as_str(),
        "as" | "async"
            | "await"
            | "break"
            | "const"
            | "continue"
            | "crate"
            | "dyn"
            | "else"
            | "enum"
            | "extern"
            | "false"
            | "fn"
            | "for"
            | "if"
            | "impl"
            | "in"
            | "let"
            | "loop"
            | "match"
            | "mod"
            | "move"
            | "mut"
            | "pub"
            | "ref"
            | "return"
            | "self"
            | "static"
            | "struct"
            | "super"
            | "trait"
            | "true"
            | "type"
            | "unsafe"
            | "use"
            | "where"
            | "while"
    ) {
        out.push_str("_view");
    }
    out
}

/// Assign unique case-insensitive filenames from raw identifiers so case-
/// insensitive filesystems (macOS, Windows) never collide.
pub fn unique_stems<'a>(
    names: impl IntoIterator<Item = &'a str>,
    format: impl Fn(&str) -> String,
) -> Vec<String> {
    let mut used = BTreeSet::new();
    let mut result = Vec::new();
    for name in names {
        let base = format(name);
        let mut candidate = base.clone();
        let mut suffix = 2usize;
        while !used.insert(candidate.to_ascii_lowercase()) {
            candidate = format!("{base}{suffix}");
            suffix += 1;
        }
        result.push(candidate);
    }
    result
}

/// Produce a short, helpful `README.md` for an ejected standalone project.
pub fn readme(
    app_name: &str,
    platform_label: &str,
    engine: EjectEngine,
    sections: &[(&str, &str)],
) -> String {
    let mode = match engine {
        EjectEngine::Source => "Native project with self-contained Rust engine source",
        EjectEngine::Prebuilt => "Native project with prebuilt engine binary (no Rust required)",
    };
    let mut out = format!("# {app_name} ({platform_label})\n\n");
    out.push_str(&format!(
        "Ejected from Bern as a standalone native project ({mode}).\n\n"
    ));
    out.push_str("You own every file in this directory and can edit, sign, extend, and build it directly with native platform tools without `bern`.\n\n");
    for (heading, body) in sections {
        out.push_str(&format!("## {heading}\n\n{}\n\n", body.trim()));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cleans_generated_banners() {
        let input =
            "// Generated by Bern from the Rust declarations. Do not edit.\nimport SwiftUI\n";
        let cleaned = clean_source_text(input);
        assert!(!cleaned.contains("Do not edit"), "{cleaned}");
        assert!(cleaned.contains("Ejected from Bern"), "{cleaned}");
        assert!(cleaned.contains("import SwiftUI"), "{cleaned}");
    }

    #[test]
    fn unique_stems_handle_case_collisions() {
        let stems = unique_stems(["home", "Home", "settings-pane"], pascal_filename);
        assert_eq!(stems, vec!["Home", "Home2", "SettingsPane"]);
    }

    #[test]
    fn snake_filename_avoids_rust_keywords() {
        assert_eq!(snake_filename("match"), "match_view");
        assert_eq!(snake_filename("HomePage"), "home_page");
    }
}
