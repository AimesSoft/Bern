/// Check the parts of the IR every target must agree on: IR version,
/// supported components and window presentation requirements.
pub fn check_common(target: &dyn Target, app: &Application) -> Vec<Diagnostic> {
    let descriptor = target.descriptor();
    let mut diagnostics = Vec::new();
    if !descriptor.supports_ir() || app.ir_version != IR_VERSION {
        diagnostics.push(Diagnostic::error(format!(
            "target `{}` consumes IR versions {:?}, the application uses IR version {}",
            descriptor.id, descriptor.ir_versions, app.ir_version
        )));
    }
    let mut visit = |node: &bern_ir::Node| {
        if let bern_ir::Node::Element(element) = node
            && !descriptor.components.contains(&element.kind.as_str())
        {
            diagnostics.push(
                Diagnostic::error(format!(
                    "target `{}` does not support `{}`",
                    descriptor.id, element.kind
                ))
                .at(element.source.clone()),
            );
        }
    };
    for component in &app.components {
        component.body.walk(&mut visit);
    }
    diagnostics.extend(check_styles(&descriptor, app));
    let mut still = std::collections::BTreeSet::new();
    for component in &app.components {
        component.body.walk(&mut |node| {
            if let bern_ir::Node::Element(element) = node {
                for prop in bern_ir::spec::MOTION_PROPS {
                    if prop.name != "hero_key"
                        && prop.name != "reveal"
                        && prop.name != "appearance"
                        && element.props.contains_key(prop.name)
                        && !descriptor.motion.contains(&prop.name)
                    {
                        still.insert(prop.name);
                    }
                }
            }
        });
    }
    if !descriptor.dynamic_items {
        let mut dynamic = None;
        for component in &app.components {
            component.body.walk(&mut |node| {
                if let bern_ir::Node::Element(element) = node
                    && bern_ir::spec::DYNAMIC_ITEMS.contains(&element.kind.as_str())
                    && dynamic.is_none()
                    && has_dynamic_items(&element.children)
                {
                    dynamic = Some(element);
                }
            });
        }
        if let Some(element) = dynamic {
            diagnostics.push(
                Diagnostic::error(format!(
                    "target `{}` cannot build `{}` items that come and go with `if`, `match` or `ForEach`, including pages of modules that can be switched off",
                    descriptor.id, element.kind
                ))
                .at(element.source.clone()),
            );
        }
    }
    diagnostics.extend(check_features(&descriptor, app));
    if !descriptor.text_marks {
        let mut marked = false;
        for component in &app.components {
            component.body.walk(&mut |node| {
                if let bern_ir::Node::Element(element) = node
                    && element.kind == "Text"
                    && element.props.contains_key("mark")
                {
                    marked = true;
                }
            });
        }
        if marked {
            diagnostics.push(Diagnostic::warning(format!(
                "target `{}` shows `Text(mark:)` as plain text, without the highlight",
                descriptor.id
            )));
        }
    }
    if !descriptor.window_chrome {
        for window in &app.windows.windows {
            if window.chrome != bern_ir::WindowChrome::Standard
                || window.immersive.is_some()
                || window.idle_after.is_some()
            {
                diagnostics.push(Diagnostic::warning(format!(
                    "target `{}` keeps window `{}`'s standard title bar: `chrome`, `immersive` and `idle_after` have no effect there, and `window.idle` stays false",
                    descriptor.id, window.id
                )));
            }
        }
    }
    for prop in still {
        let message = if prop == "stagger" {
            format!(
                "target `{}` does not stagger: children appear together",
                descriptor.id
            )
        } else if prop == "nudge" {
            format!(
                "target `{}` does not nudge: the element stays still",
                descriptor.id
            )
        } else if prop.starts_with("scroll_") {
            format!(
                "target `{}` does not follow scrolling with `{prop}`: items keep their look",
                descriptor.id
            )
        } else {
            format!(
                "target `{}` shows `{prop}` without motion: the change happens at once",
                descriptor.id
            )
        };
        diagnostics.push(Diagnostic::warning(message));
    }
    if app.uses_media() {
        let mut video = None;
        let mut find = |node: &bern_ir::Node| {
            if let bern_ir::Node::Element(element) = node
                && element.kind == "Video"
                && video.is_none()
            {
                video = Some(element.source.clone());
            }
        };
        for component in &app.components {
            component.body.walk(&mut find);
        }
        let at = |diagnostic: Diagnostic| match &video {
            Some(location) => diagnostic.at(location.clone()),
            None => diagnostic,
        };
        match &descriptor.media {
            None => diagnostics.push(at(Diagnostic::error(format!(
                "target `{}` has no media backend; `Video` and application players cannot be built",
                descriptor.id
            )))),
            Some(media)
                if !media
                    .contract_versions
                    .contains(&bern_media::MEDIA_CONTRACT_VERSION) =>
            {
                diagnostics.push(at(Diagnostic::error(format!(
                    "target `{}` pairs media backend `{}` and presenter `{}` for media contract versions {:?}; this build uses version {}",
                    descriptor.id,
                    media.backend,
                    media.presenter,
                    media.contract_versions,
                    bern_media::MEDIA_CONTRACT_VERSION
                ))));
            }
            Some(_) => {}
        }
    }
    for window in &app.windows.windows {
        match window.presentation {
            bern_ir::Presentation::NativeRequired if !descriptor.windows.native => {
                diagnostics.push(Diagnostic::error(format!(
                    "window `{}` requires native windows, which target `{}` cannot provide",
                    window.id, descriptor.id
                )));
            }
            bern_ir::Presentation::Floating if !descriptor.windows.floating => {
                diagnostics.push(Diagnostic::error(format!(
                    "window `{}` requests floating presentation, which target `{}` cannot provide",
                    window.id, descriptor.id
                )));
            }
            bern_ir::Presentation::Virtual if !descriptor.windows.virtual_windows => {
                diagnostics.push(Diagnostic::error(format!(
                    "window `{}` requests virtual presentation, which target `{}` has not implemented",
                    window.id, descriptor.id
                )));
            }
            _ => {}
        }
    }
    diagnostics
}

/// Explicit registry of target modules, assembled by the build host.
#[derive(Default)]
pub struct Registry {
    targets: Vec<Box<dyn Target>>,
}

/// Default UI technology per platform.
pub fn default_ui(platform: &str) -> Option<&'static str> {
    match platform {
        "macos" | "ios" => Some("swiftui"),
        "linux" => Some("gtk"),
        "windows" => Some("winui3"),
        "android" => Some("compose"),
        "browser" => Some("web"),
        _ => None,
    }
}

impl Registry {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn register(&mut self, target: Box<dyn Target>) {
        self.targets.push(target);
    }

    pub fn descriptors(&self) -> Vec<TargetDescriptor> {
        self.targets
            .iter()
            .map(|target| target.descriptor())
            .collect()
    }

    /// Resolve the target for a configuration. A missing default backend is
    /// an error; there is never a silent switch to another UI technology.
    pub fn resolve(&self, config: &TargetConfig) -> Result<&dyn Target, Diagnostic> {
        let ui = match &config.ui {
            Some(ui) => ui.clone(),
            None => default_ui(&config.platform)
                .ok_or_else(|| {
                    Diagnostic::error(format!(
                        "target `{}`: unknown platform `{}`",
                        config.name, config.platform
                    ))
                })?
                .to_string(),
        };
        self.targets
            .iter()
            .map(AsRef::as_ref)
            .find(|target| {
                let descriptor = target.descriptor();
                descriptor.ui == ui && descriptor.platforms.contains(&config.platform.as_str())
            })
            .ok_or_else(|| {
                Diagnostic::error(format!(
                    "target `{}`: the `{ui} + {}` backend is not available in this build of Bern",
                    config.name, config.platform
                ))
            })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    struct Fake;

    impl Target for Fake {
        fn descriptor(&self) -> TargetDescriptor {
            TargetDescriptor {
                styles: &[],
                motion: &[],
                window_chrome: false,
                text_marks: false,
                dynamic_items: false,
                features: &[],
                id: "fake-macos",
                ui: "swiftui",
                platforms: &["macos"],
                version: "0",
                ir_versions: IR_VERSION..=IR_VERSION,
                color_source: ColorSource::Native,
                components: &[],
                windows: WindowCapabilities {
                    native: true,
                    virtual_windows: false,
                    floating: true,
                },
                channels: &[],
                media: None,
            }
        }
        fn check(&self, _: &Application, _: &TargetConfig) -> Vec<Diagnostic> {
            vec![]
        }
        fn generate(
            &self,
            _: &Application,
            _: &BuildContext,
        ) -> Result<Vec<GeneratedFile>, Vec<Diagnostic>> {
            Ok(vec![])
        }
        fn plan(&self, _: &Application, _: &BuildContext) -> Result<BuildPlan, Vec<Diagnostic>> {
            Ok(BuildPlan::default())
        }
    }

    fn config(platform: &str, ui: Option<&str>) -> TargetConfig {
        TargetConfig {
            name: "t".into(),
            platform: platform.into(),
            ui: ui.map(String::from),
            web_mode: None,
            channels: vec![],
            frontends: vec![],
        }
    }

    #[test]
    fn defaults_resolve_by_platform_and_missing_backends_fail() {
        let mut registry = Registry::new();
        registry.register(Box::new(Fake));
        assert_eq!(
            registry
                .resolve(&config("macos", None))
                .unwrap()
                .descriptor()
                .id,
            "fake-macos"
        );
        let error = registry.resolve(&config("linux", None)).err().unwrap();
        assert!(error.message.contains("gtk + linux"), "{}", error.message);
        assert!(registry.resolve(&config("macos", Some("flutter"))).is_err());
        assert!(registry.resolve(&config("amiga", None)).is_err());
    }

    #[test]
    fn generated_crates_name_bern_crates_like_the_project() {
        let path = Framework::Path(PathBuf::from("/src/Bern/crates"));
        assert_eq!(
            path.dependency("bern-ffi"),
            r#"path = "/src/Bern/crates/bern-ffi""#
        );
        let git = Framework::Git {
            url: "https://github.com/AimesSoft/Bern".into(),
            reference: Some(("branch".into(), "master".into())),
        };
        assert_eq!(
            git.dependency("bern-ffi"),
            r#"git = "https://github.com/AimesSoft/Bern", branch = "master""#
        );
        assert_eq!(
            Framework::Registry("0.1".into()).dependency("bern-ffi"),
            r#"version = "0.1""#
        );
        assert_eq!(toml_string(r#"C:\a "b""#), r#""C:\\a \"b\"""#);
    }

    #[test]
    fn archives_use_the_build_machine_s_own_tools() {
        let (step, out) = archive(
            std::path::Path::new("/stage/Hello"),
            std::path::Path::new("/dist/Hello-1.0"),
        );
        let BuildStep::Run { program, args, .. } = step else {
            panic!("a command");
        };
        match std::env::consts::OS {
            "macos" => {
                assert_eq!(
                    (program.as_str(), out),
                    ("ditto", PathBuf::from("/dist/Hello-1.0.zip"))
                );
                assert!(args.contains(&"--noextattr".to_string()));
            }
            "windows" => assert_eq!(program, "tar"),
            _ => assert_eq!(
                (program.as_str(), out),
                ("tar", PathBuf::from("/dist/Hello-1.0.tar.gz"))
            ),
        }
    }
}
