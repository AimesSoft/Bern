//! The interface every UI target module implements.
//!
//! A target describes itself and its capabilities, checks the shared IR,
//! generates code and resources, and returns a build plan that the build
//! driver executes. The compiler core only talks to this interface; it never
//! imports a concrete target, and disabling one target leaves the others
//! buildable.

