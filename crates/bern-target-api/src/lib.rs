//! The interface every UI target module implements.
//!
//! A target describes itself and its capabilities, checks the shared IR,
//! generates code and resources, and returns a build plan that the build
//! driver executes. The compiler core only talks to this interface; it never
//! imports a concrete target, and disabling one target leaves the others
//! buildable.

pub mod glue;

use bern_ir::{Application, IR_VERSION, SourceLocation};
use std::fmt;
use std::ops::RangeInclusive;
use std::path::PathBuf;

/// Where a target's colors come from.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ColorSource {
    /// The UI framework's own light/dark system and standard styles.
    Native,
    /// Colors generated by the Bern theme algorithm.
    BernTheme,
}

/// How a target can present `Window` declarations.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct WindowCapabilities {
    pub native: bool,
    pub virtual_windows: bool,
    /// Draggable, resizable windows: native windows, or floating panels.
    pub floating: bool,
}

/// The media backend and video presenter a target assembles for `Video`.
/// The two are versioned separately from the target and from each other.
#[derive(Clone, Debug)]
pub struct MediaSupport {
    /// Versions of the media contract both parts implement.
    pub contract_versions: RangeInclusive<u32>,
    /// Media backend that loads and plays, for example `avfoundation`.
    pub backend: &'static str,
    pub backend_version: &'static str,
    /// Presenter that attaches players to views, for example `avplayerview`.
    pub presenter: &'static str,
    pub presenter_version: &'static str,
    /// Players keep playing while no view is attached.
    pub background_playback: bool,
    /// Several views may show one player at the same time.
    pub multi_view: bool,
}

#[derive(Clone, Debug)]
pub struct TargetDescriptor {
    /// Stable target id, for example `swiftui-macos`.
    pub id: &'static str,
    /// UI technology, for example `swiftui`.
    pub ui: &'static str,
    pub platforms: &'static [&'static str],
    pub version: &'static str,
    /// IR versions this target consumes.
    pub ir_versions: RangeInclusive<u32>,
    pub color_source: ColorSource,
    /// Built-in components this target can realize.
    pub components: &'static [&'static str],
    pub windows: WindowCapabilities,
    /// Entry channels the target's host can assemble besides the UI.
    pub channels: &'static [&'static str],
    /// Media support for `Video` and application players, if any.
    pub media: Option<MediaSupport>,
}

impl TargetDescriptor {
    pub fn supports_ir(&self) -> bool {
        self.ir_versions.contains(&IR_VERSION)
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Severity {
    Error,
    Warning,
    /// Information a report must show, such as an exemption.
    Note,
}

/// A diagnostic pointing back to the developer's declaration.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Diagnostic {
    pub severity: Severity,
    pub code: Option<&'static str>,
    pub message: String,
    pub location: Option<SourceLocation>,
}

impl Diagnostic {
    pub fn error(message: impl Into<String>) -> Self {
        Self {
            severity: Severity::Error,
            code: None,
            message: message.into(),
            location: None,
        }
    }

    pub fn warning(message: impl Into<String>) -> Self {
        Self {
            severity: Severity::Warning,
            ..Self::error(message)
        }
    }

    pub fn note(message: impl Into<String>) -> Self {
        Self {
            severity: Severity::Note,
            ..Self::error(message)
        }
    }

    pub fn code(mut self, code: &'static str) -> Self {
        self.code = Some(code);
        self
    }

    pub fn at(mut self, location: SourceLocation) -> Self {
        self.location = Some(location);
        self
    }

    pub fn is_error(&self) -> bool {
        self.severity == Severity::Error
    }
}

impl fmt::Display for Diagnostic {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let level = match self.severity {
            Severity::Error => "error",
            Severity::Warning => "warning",
            Severity::Note => "note",
        };
        match self.code {
            Some(code) => write!(f, "{level}[{code}]: {}", self.message)?,
            None => write!(f, "{level}: {}", self.message)?,
        }
        if let Some(location) = &self.location {
            write!(
                f,
                "\n  --> {}:{}:{}",
                location.file, location.line, location.column
            )?;
        }
        Ok(())
    }
}

/// A feature contract report for one platform: the result of every
/// feature in every applicable size, and the diagnostics they raise.
#[derive(Clone, Debug, Default)]
pub struct FeatureReport {
    pub diagnostics: Vec<Diagnostic>,
    /// `(contract, feature, size, result)` rows, in declaration order.
    pub rows: Vec<(String, String, bern_ir::LayoutSize, bern_ir::FeatureResult)>,
}

impl FeatureReport {
    /// One line per row, for terminals.
    pub fn lines(&self) -> Vec<String> {
        self.rows
            .iter()
            .map(|(contract, feature, size, result)| {
                let outcome = match result {
                    bern_ir::FeatureResult::Covered { entries } => {
                        format!("covered by {}", entries.join(", "))
                    }
                    bern_ir::FeatureResult::Guaranteed { entries, reason } => format!(
                        "NOT PROVEN, manually guaranteed ({reason}); conditional entries {}",
                        entries.join(", ")
                    ),
                    bern_ir::FeatureResult::Exempt { reason } => format!("exempt: {reason}"),
                    bern_ir::FeatureResult::Missing => "MISSING".into(),
                    bern_ir::FeatureResult::Unproven { entries } => {
                        format!("UNPROVEN: only conditional entries {}", entries.join(", "))
                    }
                };
                format!("{contract}::{feature} [{}] {outcome}", size.name())
            })
            .collect()
    }
}

/// Evaluate every feature contract for `platform`: exemptions apply only
/// to their platform; missing and unproven features are errors (B201,
/// B203), manual guarantees warnings (B206) and exemptions notes (B205).
pub fn feature_report(app: &Application, platform: &str) -> FeatureReport {
    let mut report = FeatureReport::default();
    for contract in &app.contracts {
        for feature in &contract.features {
            for (size, result) in feature.results(platform) {
                let name = format!("{}::{}", contract.name, feature.name);
                let diagnostic = match &result {
                    bern_ir::FeatureResult::Covered { .. } => None,
                    bern_ir::FeatureResult::Missing => Some(
                        Diagnostic::error(format!(
                            "Feature missing in adaptive layout\nContract: {}\nFeature: {}\n{}: missing",
                            contract.name,
                            feature.name,
                            size.name()
                        ))
                        .code("B201"),
                    ),
                    bern_ir::FeatureResult::Unproven { entries } => Some(
                        Diagnostic::error(format!(
                            "`{name}` is reached in `{}` only under conditions the framework cannot prove ({}); add an unconditional entry, or `#[guaranteed(\"why\")]`",
                            size.name(),
                            entries.join(", ")
                        ))
                        .code("B203"),
                    ),
                    bern_ir::FeatureResult::Exempt { reason } => Some(
                        Diagnostic::note(format!(
                            "`{name}` is exempt in `{}` on {platform}: {reason}",
                            size.name()
                        ))
                        .code("B205"),
                    ),
                    bern_ir::FeatureResult::Guaranteed { reason, .. } => Some(
                        Diagnostic::warning(format!(
                            "`{name}` in `{}` is not proven; accepted by a manual guarantee: {reason}",
                            size.name()
                        ))
                        .code("B206"),
                    ),
                };
                if let Some(diagnostic) = diagnostic {
                    report
                        .diagnostics
                        .push(diagnostic.at(feature.source.clone()));
                }
                report
                    .rows
                    .push((contract.name.clone(), feature.name.clone(), size, result));
            }
        }
    }
    report
}

/// Target settings from `[targets.<name>]` in `Bern.toml`.
#[derive(Clone, Debug, Default)]
pub struct TargetConfig {
    pub name: String,
    pub platform: String,
    pub ui: Option<String>,
    /// Web build mode: `app` (engine in the page) or `ui` (separate engine).
    pub web_mode: Option<String>,
    pub channels: Vec<String>,
}

/// Paths and packages a target needs to plan its build.
#[derive(Clone, Debug)]
pub struct BuildContext {
    /// Directory containing `Bern.toml`.
    pub project_dir: PathBuf,
    /// Cargo workspace root.
    pub workspace_dir: PathBuf,
    /// `target/bern/<target-name>/`, owned by this target.
    pub output_dir: PathBuf,
    pub target: TargetConfig,
    pub protocol_package: String,
    pub protocol_path: PathBuf,
    /// Rust path of the protocol module, for example `showcase_protocol::showcase`.
    pub protocol_module: String,
    pub engine_package: String,
    pub engine_path: PathBuf,
    /// Rust path of the engine type, which implements `Default`.
    pub engine_type: String,
    pub release: bool,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneratedFile {
    /// Path relative to the output directory.
    pub path: PathBuf,
    pub contents: Vec<u8>,
}

impl GeneratedFile {
    pub fn text(path: impl Into<PathBuf>, contents: impl Into<String>) -> Self {
        Self {
            path: path.into(),
            contents: contents.into().into_bytes(),
        }
    }
}

/// One step the build driver executes for a target.
#[derive(Clone, Debug)]
pub enum BuildStep {
    Run {
        description: String,
        program: String,
        args: Vec<String>,
        cwd: PathBuf,
        env: Vec<(String, String)>,
    },
    CreateDir {
        path: PathBuf,
    },
    Copy {
        from: PathBuf,
        to: PathBuf,
    },
    RemoveIfExists {
        path: PathBuf,
    },
    /// Make `dir` hold exactly `files` plus the paths in `keep`, which
    /// other steps own (for example generated localizations). Files are
    /// copied by content, without extended attributes; a destination whose
    /// size and modification time match its source is left alone. Anything
    /// else below `dir` is removed, so files dropped from a declaration do
    /// not linger in the product.
    Mirror {
        dir: PathBuf,
        /// Source file and destination relative to `dir`.
        files: Vec<(PathBuf, PathBuf)>,
        /// Paths relative to `dir` to leave in place.
        keep: Vec<PathBuf>,
    },
}

#[derive(Clone, Debug, Default)]
pub struct BuildPlan {
    pub steps: Vec<BuildStep>,
    /// Final artifacts, for reporting.
    pub products: Vec<PathBuf>,
}

/// A UI target module.
pub trait Target: Send + Sync {
    fn descriptor(&self) -> TargetDescriptor;

    /// Report constructs this target cannot realize, with locations.
    fn check(&self, app: &Application, config: &TargetConfig) -> Vec<Diagnostic>;

    /// Generate sources and resources into the output directory.
    fn generate(
        &self,
        app: &Application,
        context: &BuildContext,
    ) -> Result<Vec<GeneratedFile>, Vec<Diagnostic>>;

    /// Steps that turn generated files into the final product.
    fn plan(&self, app: &Application, context: &BuildContext)
    -> Result<BuildPlan, Vec<Diagnostic>>;
}

/// Check the parts of the IR every target must agree on: IR version,
/// supported components and window presentation requirements.
pub fn check_common(target: &dyn Target, app: &Application) -> Vec<Diagnostic> {
    let descriptor = target.descriptor();
    let mut diagnostics = Vec::new();
    if !descriptor.supports_ir() || app.ir_version != IR_VERSION {
        diagnostics.push(Diagnostic::error(format!(
            "target `{}` consumes IR versions {:?}, the application uses IR version {}",
            descriptor.id, descriptor.ir_versions, app.ir_version
        )));
    }
    let mut visit = |node: &bern_ir::Node| {
        if let bern_ir::Node::Element(element) = node
            && !descriptor.components.contains(&element.kind.as_str())
        {
            diagnostics.push(
                Diagnostic::error(format!(
                    "target `{}` does not support `{}`",
                    descriptor.id, element.kind
                ))
                .at(element.source.clone()),
            );
        }
    };
    for component in &app.components {
        component.body.walk(&mut visit);
    }
    if app.uses_media() {
        let mut video = None;
        let mut find = |node: &bern_ir::Node| {
            if let bern_ir::Node::Element(element) = node
                && element.kind == "Video"
                && video.is_none()
            {
                video = Some(element.source.clone());
            }
        };
        for component in &app.components {
            component.body.walk(&mut find);
        }
        let at = |diagnostic: Diagnostic| match &video {
            Some(location) => diagnostic.at(location.clone()),
            None => diagnostic,
        };
        match &descriptor.media {
            None => diagnostics.push(at(Diagnostic::error(format!(
                "target `{}` has no media backend; `Video` and application players cannot be built",
                descriptor.id
            )))),
            Some(media)
                if !media
                    .contract_versions
                    .contains(&bern_media::MEDIA_CONTRACT_VERSION) =>
            {
                diagnostics.push(at(Diagnostic::error(format!(
                    "target `{}` pairs media backend `{}` and presenter `{}` for media contract versions {:?}; this build uses version {}",
                    descriptor.id,
                    media.backend,
                    media.presenter,
                    media.contract_versions,
                    bern_media::MEDIA_CONTRACT_VERSION
                ))));
            }
            Some(_) => {}
        }
    }
    for window in &app.windows.windows {
        match window.presentation {
            bern_ir::Presentation::NativeRequired if !descriptor.windows.native => {
                diagnostics.push(Diagnostic::error(format!(
                    "window `{}` requires native windows, which target `{}` cannot provide",
                    window.id, descriptor.id
                )));
            }
            bern_ir::Presentation::Floating if !descriptor.windows.floating => {
                diagnostics.push(Diagnostic::error(format!(
                    "window `{}` requests floating presentation, which target `{}` cannot provide",
                    window.id, descriptor.id
                )));
            }
            bern_ir::Presentation::Virtual if !descriptor.windows.virtual_windows => {
                diagnostics.push(Diagnostic::error(format!(
                    "window `{}` requests virtual presentation, which target `{}` has not implemented",
                    window.id, descriptor.id
                )));
            }
            _ => {}
        }
    }
    diagnostics
}

/// Explicit registry of target modules, assembled by the build host.
#[derive(Default)]
pub struct Registry {
    targets: Vec<Box<dyn Target>>,
}

/// Default UI technology per platform.
pub fn default_ui(platform: &str) -> Option<&'static str> {
    match platform {
        "macos" | "ios" => Some("swiftui"),
        "linux" => Some("gtk"),
        "windows" => Some("winui3"),
        "android" => Some("compose"),
        "browser" => Some("web"),
        _ => None,
    }
}

impl Registry {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn register(&mut self, target: Box<dyn Target>) {
        self.targets.push(target);
    }

    pub fn descriptors(&self) -> Vec<TargetDescriptor> {
        self.targets
            .iter()
            .map(|target| target.descriptor())
            .collect()
    }

    /// Resolve the target for a configuration. A missing default backend is
    /// an error; there is never a silent switch to another UI technology.
    pub fn resolve(&self, config: &TargetConfig) -> Result<&dyn Target, Diagnostic> {
        let ui = match &config.ui {
            Some(ui) => ui.clone(),
            None => default_ui(&config.platform)
                .ok_or_else(|| {
                    Diagnostic::error(format!(
                        "target `{}`: unknown platform `{}`",
                        config.name, config.platform
                    ))
                })?
                .to_string(),
        };
        self.targets
            .iter()
            .map(AsRef::as_ref)
            .find(|target| {
                let descriptor = target.descriptor();
                descriptor.ui == ui && descriptor.platforms.contains(&config.platform.as_str())
            })
            .ok_or_else(|| {
                Diagnostic::error(format!(
                    "target `{}`: the `{ui} + {}` backend is not available in this build of Bern",
                    config.name, config.platform
                ))
            })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    struct Fake;

    impl Target for Fake {
        fn descriptor(&self) -> TargetDescriptor {
            TargetDescriptor {
                id: "fake-macos",
                ui: "swiftui",
                platforms: &["macos"],
                version: "0",
                ir_versions: IR_VERSION..=IR_VERSION,
                color_source: ColorSource::Native,
                components: &[],
                windows: WindowCapabilities {
                    native: true,
                    virtual_windows: false,
                    floating: true,
                },
                channels: &[],
                media: None,
            }
        }
        fn check(&self, _: &Application, _: &TargetConfig) -> Vec<Diagnostic> {
            vec![]
        }
        fn generate(
            &self,
            _: &Application,
            _: &BuildContext,
        ) -> Result<Vec<GeneratedFile>, Vec<Diagnostic>> {
            Ok(vec![])
        }
        fn plan(&self, _: &Application, _: &BuildContext) -> Result<BuildPlan, Vec<Diagnostic>> {
            Ok(BuildPlan::default())
        }
    }

    fn config(platform: &str, ui: Option<&str>) -> TargetConfig {
        TargetConfig {
            name: "t".into(),
            platform: platform.into(),
            ui: ui.map(String::from),
            web_mode: None,
            channels: vec![],
        }
    }

    #[test]
    fn defaults_resolve_by_platform_and_missing_backends_fail() {
        let mut registry = Registry::new();
        registry.register(Box::new(Fake));
        assert_eq!(
            registry
                .resolve(&config("macos", None))
                .unwrap()
                .descriptor()
                .id,
            "fake-macos"
        );
        let error = registry.resolve(&config("linux", None)).err().unwrap();
        assert!(error.message.contains("gtk + linux"), "{}", error.message);
        assert!(registry.resolve(&config("macos", Some("flutter"))).is_err());
        assert!(registry.resolve(&config("amiga", None)).is_err());
    }
}
