/// The style effects a target shows for one control kind: outside any
/// state, and in each state.
#[derive(Clone, Copy, Debug)]
pub struct StyleSupport {
    pub component: &'static str,
    pub base: &'static [&'static str],
    pub states: &'static [(bern_ir::style::StyleState, &'static [&'static str])],
}

impl StyleSupport {
    fn shows(&self, state: Option<bern_ir::style::StyleState>, effect: &str) -> bool {
        match state {
            None => self.base.contains(&effect),
            Some(state) => self
                .states
                .iter()
                .any(|(supported, effects)| *supported == state && effects.contains(&effect)),
        }
    }
}

impl TargetDescriptor {
    pub fn supports_ir(&self) -> bool {
        self.ir_versions.contains(&IR_VERSION)
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Severity {
    Error,
    Warning,
    /// Information a report must show, such as an exemption.
    Note,
}

/// A diagnostic pointing back to the developer's declaration.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Diagnostic {
    pub severity: Severity,
    pub code: Option<&'static str>,
    pub message: String,
    pub location: Option<SourceLocation>,
}

impl Diagnostic {
    pub fn error(message: impl Into<String>) -> Self {
        Self {
            severity: Severity::Error,
            code: None,
            message: message.into(),
            location: None,
        }
    }

    pub fn warning(message: impl Into<String>) -> Self {
        Self {
            severity: Severity::Warning,
            ..Self::error(message)
        }
    }

    pub fn note(message: impl Into<String>) -> Self {
        Self {
            severity: Severity::Note,
            ..Self::error(message)
        }
    }

    pub fn code(mut self, code: &'static str) -> Self {
        self.code = Some(code);
        self
    }

    pub fn at(mut self, location: SourceLocation) -> Self {
        self.location = Some(location);
        self
    }

    pub fn is_error(&self) -> bool {
        self.severity == Severity::Error
    }
}

impl fmt::Display for Diagnostic {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let level = match self.severity {
            Severity::Error => "error",
            Severity::Warning => "warning",
            Severity::Note => "note",
        };
        match self.code {
            Some(code) => write!(f, "{level}[{code}]: {}", self.message)?,
            None => write!(f, "{level}: {}", self.message)?,
        }
        if let Some(location) = &self.location {
            write!(
                f,
                "\n  --> {}:{}:{}",
                location.file, location.line, location.column
            )?;
        }
        Ok(())
    }
}

