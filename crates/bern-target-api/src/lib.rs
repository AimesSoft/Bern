/// The build machine's architecture as packages name it: `arm64` or
/// `x64` (`x86_64` on macOS, where that is the usual name).
pub fn package_architecture() -> &'static str {
    match (std::env::consts::OS, std::env::consts::ARCH) {
        (_, "aarch64") => "arm64",
        ("macos", _) => "x86_64",
        _ => "x64",
    }
}

/// A step that archives `dir`, with `dir` itself as the top folder, into
/// `stem` plus the extension the build machine's own tools make: `.zip`
/// on macOS (`ditto`) and Windows (`tar`), `.tar.gz` on Linux (`tar`).
pub fn archive(dir: &std::path::Path, stem: &std::path::Path) -> (BuildStep, PathBuf) {
    let parent = dir.parent().unwrap_or(dir).to_path_buf();
    let name = dir
        .file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_default();
    let with = |extension: &str| {
        let mut file = stem.as_os_str().to_owned();
        file.push(extension);
        PathBuf::from(file)
    };
    let (program, args, out) = match std::env::consts::OS {
        "macos" => {
            let out = with(".zip");
            let args = vec![
                "-c".to_string(),
                "-k".into(),
                // Plain files: no resource forks, extended attributes or
                // quarantine flags (`__MACOSX/._*` entries elsewhere).
                "--norsrc".into(),
                "--noextattr".into(),
                "--noqtn".into(),
                "--keepParent".into(),
                dir.display().to_string(),
                out.display().to_string(),
            ];
            ("ditto", args, out)
        }
        "windows" => {
            let out = with(".zip");
            let args = vec![
                "-a".to_string(),
                "-c".into(),
                "-f".into(),
                out.display().to_string(),
                "-C".into(),
                parent.display().to_string(),
                name.clone(),
            ];
            ("tar", args, out)
        }
        _ => {
            let out = with(".tar.gz");
            let args = vec![
                "-czf".to_string(),
                out.display().to_string(),
                "-C".into(),
                parent.display().to_string(),
                name.clone(),
            ];
            ("tar", args, out)
        }
    };
    let step = BuildStep::Run {
        description: format!("Archive {name}"),
        program: program.into(),
        args,
        cwd: parent,
        env: vec![],
    };
    (step, out)
}

/// Every file below `dir`, as (path, path relative to `dir`), sorted.
pub fn files_below(dir: &std::path::Path) -> std::io::Result<Vec<(PathBuf, PathBuf)>> {
    fn walk(
        dir: &std::path::Path,
        relative: &std::path::Path,
        out: &mut Vec<(PathBuf, PathBuf)>,
    ) -> std::io::Result<()> {
        for entry in std::fs::read_dir(dir.join(relative))? {
            let entry = entry?;
            let path = relative.join(entry.file_name());
            if entry.file_type()?.is_dir() {
                walk(dir, &path, out)?;
            } else {
                out.push((dir.join(&path), path));
            }
        }
        Ok(())
    }
    let mut out = Vec::new();
    walk(dir, std::path::Path::new(""), &mut out)?;
    out.sort();
    Ok(out)
}

/// Whether navigation items sit in conditions or repetitions, also inside
/// a sidebar's sections.
fn has_dynamic_items(nodes: &[bern_ir::Node]) -> bool {
    nodes.iter().any(|node| match node {
        bern_ir::Node::Element(element) if element.kind == "ForEach" => true,
        bern_ir::Node::Element(element) if element.kind == "Section" => {
            has_dynamic_items(&element.children)
        }
        bern_ir::Node::Element(_) | bern_ir::Node::Component(_) => false,
        bern_ir::Node::If(_) | bern_ir::Node::IfLet(_) | bern_ir::Node::Match(_) => true,
    })
}

/// The first element of the application `found` picks.
fn first_element(
    app: &Application,
    found: impl Fn(&bern_ir::Element) -> bool,
) -> Option<&bern_ir::Element> {
    let mut first = None;
    for component in &app.components {
        component.body.walk(&mut |node| {
            if let bern_ir::Node::Element(element) = node
                && first.is_none()
                && found(element)
            {
                first = Some(element);
            }
        });
    }
    first
}

/// Features the application uses that the target does not list.
/// Whether an expression in `node` (a condition, or a prop of an element)
/// reads one of the window's size fields.
fn reads_window_size(node: &bern_ir::Node) -> bool {
    let mut found = false;
    let mut check = |expr: &bern_ir::Expr| {
        expr.walk(&mut |part| {
            if let bern_ir::ExprKind::Binding {
                binding: bern_ir::Binding::Window { field },
            } = &part.kind
                && field != "idle"
            {
                found = true;
            }
        });
    };
    match node {
        bern_ir::Node::Element(element) => {
            for prop in element.props.values() {
                if let bern_ir::Prop::Expr { expr } = prop {
                    check(expr);
                }
            }
        }
        bern_ir::Node::If(node) => {
            for (condition, _) in &node.branches {
                check(condition);
            }
        }
        _ => {}
    }
    found
}

