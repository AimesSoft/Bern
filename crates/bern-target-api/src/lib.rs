/// Where the Bern crates come from: the source of the project's own `bern`
/// dependency. Generated crates take every Bern crate from it, so the
/// application and the code generated around it share one copy of each.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Framework {
    /// A checkout whose `crates` directory holds every Bern crate.
    Path(PathBuf),
    /// A Git repository, at the reference the project names, if any:
    /// `("branch", …)`, `("tag", …)` or `("rev", …)`.
    Git {
        url: String,
        reference: Option<(String, String)>,
    },
    /// A release on crates.io, with the project's version requirement.
    Registry(String),
}

impl Framework {
    /// The dependency on the Bern crate `name`, as the inside of an inline
    /// table, for example `path = "/src/bern/crates/bern-ffi"`.
    pub fn dependency(&self, name: &str) -> String {
        match self {
            Framework::Path(crates) => {
                let path = crates.join(name).display().to_string();
                format!("path = {}", toml_string(&path.replace('\\', "/")))
            }
            Framework::Git { url, reference } => {
                let mut out = format!("git = {}", toml_string(url));
                if let Some((kind, value)) = reference {
                    out.push_str(&format!(", {kind} = {}", toml_string(value)));
                }
                out
            }
            Framework::Registry(version) => format!("version = {}", toml_string(version)),
        }
    }
}

/// A TOML basic string.
pub fn toml_string(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => out.push_str(&format!("\\u{:04X}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Paths and packages a target needs to plan its build.
#[derive(Clone, Debug)]
pub struct BuildContext {
    /// Directory containing `Bern.toml`.
    pub project_dir: PathBuf,
    /// Cargo workspace root.
    pub workspace_dir: PathBuf,
    /// `target/bern/<target-name>/`, owned by this target.
    pub output_dir: PathBuf,
    pub target: TargetConfig,
    pub protocol_package: String,
    pub protocol_path: PathBuf,
    /// Rust path of the protocol module, for example `showcase_protocol::showcase`.
    pub protocol_module: String,
    pub engine_package: String,
    pub engine_path: PathBuf,
    /// Rust path of the engine type, which implements `Default`.
    pub engine_type: String,
    /// Where generated crates take the Bern crates from.
    pub framework: Framework,
    pub release: bool,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneratedFile {
    /// Path relative to the output directory.
    pub path: PathBuf,
    pub contents: Vec<u8>,
}

impl GeneratedFile {
    pub fn text(path: impl Into<PathBuf>, contents: impl Into<String>) -> Self {
        Self {
            path: path.into(),
            contents: contents.into().into_bytes(),
        }
    }
}

/// One step the build driver executes for a target.
#[derive(Clone, Debug)]
pub enum BuildStep {
    Run {
        description: String,
        program: String,
        args: Vec<String>,
        cwd: PathBuf,
        env: Vec<(String, String)>,
    },
    CreateDir {
        path: PathBuf,
    },
    Copy {
        from: PathBuf,
        to: PathBuf,
    },
    RemoveIfExists {
        path: PathBuf,
    },
    /// Write a file, creating its directory.
    Write {
        path: PathBuf,
        contents: Vec<u8>,
    },
    /// Make `dir` hold exactly `files` plus the paths in `keep`, which
    /// other steps own (for example generated localizations). Files are
    /// copied by content, without extended attributes; a destination whose
    /// size and modification time match its source is left alone. Anything
    /// else below `dir` is removed, so files dropped from a declaration do
    /// not linger in the product.
    Mirror {
        dir: PathBuf,
        /// Source file and destination relative to `dir`.
        files: Vec<(PathBuf, PathBuf)>,
        /// Paths relative to `dir` to leave in place.
        keep: Vec<PathBuf>,
    },
}

#[derive(Clone, Debug, Default)]
pub struct BuildPlan {
    pub steps: Vec<BuildStep>,
    /// Final artifacts, for reporting.
    pub products: Vec<PathBuf>,
    /// How `bern run` starts the built application.
    pub run: Option<Run>,
    /// What the person building should know about the products, printed
    /// after the steps; for example that a package is not signed.
    pub notes: Vec<String>,
}

/// How `bern run` starts a built application.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Run {
    /// Start the program and wait until it exits.
    Program(PathBuf),
    /// Serve the directory on the loopback interface and open its
    /// `index.html` in the browser.
    Page(PathBuf),
    /// Start the program, which serves its own page and prints the address
    /// on a line `open <address>`; open that address in the browser and
    /// wait until the program exits.
    PageHost(PathBuf),
    /// Install the app bundle into the booted iOS simulator, start it there
    /// and wait until it exits.
    Simulator { app: PathBuf, bundle_id: String },
}

/// A UI target module.
pub trait Target: Send + Sync {
    fn descriptor(&self) -> TargetDescriptor;

    /// Operating systems that can build this target, as
    /// `std::env::consts::OS` names them; empty when any can.
    fn build_hosts(&self) -> &'static [&'static str] {
        &[]
    }

    /// Report constructs this target cannot realize, with locations.
    fn check(&self, app: &Application, config: &TargetConfig) -> Vec<Diagnostic>;

    /// Generate sources and resources into the output directory.
    fn generate(
        &self,
        app: &Application,
        context: &BuildContext,
    ) -> Result<Vec<GeneratedFile>, Vec<Diagnostic>>;

    /// Steps that turn generated files into the final product.
    fn plan(&self, app: &Application, context: &BuildContext)
    -> Result<BuildPlan, Vec<Diagnostic>>;

    /// Steps that turn a release build, which `plan` has made, into the
    /// packages people install, in [`dist_dir`].
    fn package(
        &self,
        _app: &Application,
        _context: &BuildContext,
        _signing: &Signing,
    ) -> Result<BuildPlan, Vec<Diagnostic>> {
        Err(vec![Diagnostic::error(format!(
            "target `{}` cannot make packages yet",
            self.descriptor().id
        ))])
    }
}

/// How packages are signed, from the environment of `bern package`.
/// Certificates stay with the person or the CI service that builds; none
/// of this goes into `Bern.toml`.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Signing {
    /// `BERN_MACOS_SIGNING_IDENTITY`: a signing identity in the keychain,
    /// for distribution a "Developer ID Application" one.
    pub macos_identity: Option<String>,
    /// `BERN_MACOS_NOTARY_PROFILE`: a keychain profile made with
    /// `xcrun notarytool store-credentials`.
    pub macos_notary_profile: Option<String>,
    /// `BERN_WINDOWS_CERTIFICATE`: the SHA-1 thumbprint of a code signing
    /// certificate in the user's store, or a `.pfx` file.
    pub windows_certificate: Option<String>,
    /// `BERN_WINDOWS_CERTIFICATE_PASSWORD`: the password of the `.pfx`.
    pub windows_certificate_password: Option<String>,
}

impl Signing {
    pub fn from_env() -> Signing {
        let var = |name: &str| {
            std::env::var(name)
                .ok()
                .filter(|value| !value.trim().is_empty())
        };
        Signing {
            macos_identity: var("BERN_MACOS_SIGNING_IDENTITY"),
            macos_notary_profile: var("BERN_MACOS_NOTARY_PROFILE"),
            windows_certificate: var("BERN_WINDOWS_CERTIFICATE"),
            windows_certificate_password: var("BERN_WINDOWS_CERTIFICATE_PASSWORD"),
        }
    }
}

/// Where packages go: `target/bern/dist/` of the workspace.
pub fn dist_dir(context: &BuildContext) -> PathBuf {
    context
        .workspace_dir
        .join("target")
        .join("bern")
        .join("dist")
}

/// The build machine's architecture as packages name it: `arm64` or
/// `x64` (`x86_64` on macOS, where that is the usual name).
pub fn package_architecture() -> &'static str {
    match (std::env::consts::OS, std::env::consts::ARCH) {
        (_, "aarch64") => "arm64",
        ("macos", _) => "x86_64",
        _ => "x64",
    }
}

/// A step that archives `dir`, with `dir` itself as the top folder, into
/// `stem` plus the extension the build machine's own tools make: `.zip`
/// on macOS (`ditto`) and Windows (`tar`), `.tar.gz` on Linux (`tar`).
pub fn archive(dir: &std::path::Path, stem: &std::path::Path) -> (BuildStep, PathBuf) {
    let parent = dir.parent().unwrap_or(dir).to_path_buf();
    let name = dir
        .file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_default();
    let with = |extension: &str| {
        let mut file = stem.as_os_str().to_owned();
        file.push(extension);
        PathBuf::from(file)
    };
    let (program, args, out) = match std::env::consts::OS {
        "macos" => {
            let out = with(".zip");
            let args = vec![
                "-c".to_string(),
                "-k".into(),
                // Plain files: no resource forks, extended attributes or
                // quarantine flags (`__MACOSX/._*` entries elsewhere).
                "--norsrc".into(),
                "--noextattr".into(),
                "--noqtn".into(),
                "--keepParent".into(),
                dir.display().to_string(),
                out.display().to_string(),
            ];
            ("ditto", args, out)
        }
        "windows" => {
            let out = with(".zip");
            let args = vec![
                "-a".to_string(),
                "-c".into(),
                "-f".into(),
                out.display().to_string(),
                "-C".into(),
                parent.display().to_string(),
                name.clone(),
            ];
            ("tar", args, out)
        }
        _ => {
            let out = with(".tar.gz");
            let args = vec![
                "-czf".to_string(),
                out.display().to_string(),
                "-C".into(),
                parent.display().to_string(),
                name.clone(),
            ];
            ("tar", args, out)
        }
    };
    let step = BuildStep::Run {
        description: format!("Archive {name}"),
        program: program.into(),
        args,
        cwd: parent,
        env: vec![],
    };
    (step, out)
}

/// Every file below `dir`, as (path, path relative to `dir`), sorted.
pub fn files_below(dir: &std::path::Path) -> std::io::Result<Vec<(PathBuf, PathBuf)>> {
    fn walk(
        dir: &std::path::Path,
        relative: &std::path::Path,
        out: &mut Vec<(PathBuf, PathBuf)>,
    ) -> std::io::Result<()> {
        for entry in std::fs::read_dir(dir.join(relative))? {
            let entry = entry?;
            let path = relative.join(entry.file_name());
            if entry.file_type()?.is_dir() {
                walk(dir, &path, out)?;
            } else {
                out.push((dir.join(&path), path));
            }
        }
        Ok(())
    }
    let mut out = Vec::new();
    walk(dir, std::path::Path::new(""), &mut out)?;
    out.sort();
    Ok(out)
}

/// Check the parts of the IR every target must agree on: IR version,
/// supported components and window presentation requirements.
pub fn check_common(target: &dyn Target, app: &Application) -> Vec<Diagnostic> {
    let descriptor = target.descriptor();
    let mut diagnostics = Vec::new();
    if !descriptor.supports_ir() || app.ir_version != IR_VERSION {
        diagnostics.push(Diagnostic::error(format!(
            "target `{}` consumes IR versions {:?}, the application uses IR version {}",
            descriptor.id, descriptor.ir_versions, app.ir_version
        )));
    }
    let mut visit = |node: &bern_ir::Node| {
        if let bern_ir::Node::Element(element) = node
            && !descriptor.components.contains(&element.kind.as_str())
        {
            diagnostics.push(
                Diagnostic::error(format!(
                    "target `{}` does not support `{}`",
                    descriptor.id, element.kind
                ))
                .at(element.source.clone()),
            );
        }
    };
    for component in &app.components {
        component.body.walk(&mut visit);
    }
    if app.uses_media() {
        let mut video = None;
        let mut find = |node: &bern_ir::Node| {
            if let bern_ir::Node::Element(element) = node
                && element.kind == "Video"
                && video.is_none()
            {
                video = Some(element.source.clone());
            }
        };
        for component in &app.components {
            component.body.walk(&mut find);
        }
        let at = |diagnostic: Diagnostic| match &video {
            Some(location) => diagnostic.at(location.clone()),
            None => diagnostic,
        };
        match &descriptor.media {
            None => diagnostics.push(at(Diagnostic::error(format!(
                "target `{}` has no media backend; `Video` and application players cannot be built",
                descriptor.id
            )))),
            Some(media)
                if !media
                    .contract_versions
                    .contains(&bern_media::MEDIA_CONTRACT_VERSION) =>
            {
                diagnostics.push(at(Diagnostic::error(format!(
                    "target `{}` pairs media backend `{}` and presenter `{}` for media contract versions {:?}; this build uses version {}",
                    descriptor.id,
                    media.backend,
                    media.presenter,
                    media.contract_versions,
                    bern_media::MEDIA_CONTRACT_VERSION
                ))));
            }
            Some(_) => {}
        }
    }
    for window in &app.windows.windows {
        match window.presentation {
            bern_ir::Presentation::NativeRequired if !descriptor.windows.native => {
                diagnostics.push(Diagnostic::error(format!(
                    "window `{}` requires native windows, which target `{}` cannot provide",
                    window.id, descriptor.id
                )));
            }
            bern_ir::Presentation::Floating if !descriptor.windows.floating => {
                diagnostics.push(Diagnostic::error(format!(
                    "window `{}` requests floating presentation, which target `{}` cannot provide",
                    window.id, descriptor.id
                )));
            }
            bern_ir::Presentation::Virtual if !descriptor.windows.virtual_windows => {
                diagnostics.push(Diagnostic::error(format!(
                    "window `{}` requests virtual presentation, which target `{}` has not implemented",
                    window.id, descriptor.id
                )));
            }
            _ => {}
        }
    }
    diagnostics
}

/// Explicit registry of target modules, assembled by the build host.
#[derive(Default)]
pub struct Registry {
    targets: Vec<Box<dyn Target>>,
}

/// Default UI technology per platform.
pub fn default_ui(platform: &str) -> Option<&'static str> {
    match platform {
        "macos" | "ios" => Some("swiftui"),
        "linux" => Some("gtk"),
        "windows" => Some("winui3"),
        "android" => Some("compose"),
        "browser" => Some("web"),
        _ => None,
    }
}

impl Registry {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn register(&mut self, target: Box<dyn Target>) {
        self.targets.push(target);
    }

    pub fn descriptors(&self) -> Vec<TargetDescriptor> {
        self.targets
            .iter()
            .map(|target| target.descriptor())
            .collect()
    }

    /// Resolve the target for a configuration. A missing default backend is
    /// an error; there is never a silent switch to another UI technology.
    pub fn resolve(&self, config: &TargetConfig) -> Result<&dyn Target, Diagnostic> {
        let ui = match &config.ui {
            Some(ui) => ui.clone(),
            None => default_ui(&config.platform)
                .ok_or_else(|| {
                    Diagnostic::error(format!(
                        "target `{}`: unknown platform `{}`",
                        config.name, config.platform
                    ))
                })?
                .to_string(),
        };
        self.targets
            .iter()
            .map(AsRef::as_ref)
            .find(|target| {
                let descriptor = target.descriptor();
                descriptor.ui == ui && descriptor.platforms.contains(&config.platform.as_str())
            })
            .ok_or_else(|| {
                Diagnostic::error(format!(
                    "target `{}`: the `{ui} + {}` backend is not available in this build of Bern",
                    config.name, config.platform
                ))
            })
    }
}

