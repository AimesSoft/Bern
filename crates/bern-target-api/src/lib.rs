#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneratedFile {
    /// Path relative to the output directory.
    pub path: PathBuf,
    pub contents: Vec<u8>,
}

impl GeneratedFile {
    pub fn text(path: impl Into<PathBuf>, contents: impl Into<String>) -> Self {
        Self {
            path: path.into(),
            contents: contents.into().into_bytes(),
        }
    }
}

/// A UI target module.
pub trait Target: Send + Sync {
    fn descriptor(&self) -> TargetDescriptor;

    /// Operating systems that can build this target, as
    /// `std::env::consts::OS` names them; empty when any can.
    fn build_hosts(&self) -> &'static [&'static str] {
        &[]
    }

    /// Report constructs this target cannot realize, with locations.
    fn check(&self, app: &Application, config: &TargetConfig) -> Vec<Diagnostic>;

    /// Generate sources and resources into the output directory.
    fn generate(
        &self,
        app: &Application,
        context: &BuildContext,
    ) -> Result<Vec<GeneratedFile>, Vec<Diagnostic>>;

    /// Steps that turn generated files into the final product.
    fn plan(&self, app: &Application, context: &BuildContext)
    -> Result<BuildPlan, Vec<Diagnostic>>;

    /// Steps that turn a release build, which `plan` has made, into the
    /// packages people install, in [`dist_dir`].
    fn package(
        &self,
        _app: &Application,
        _context: &BuildContext,
        _signing: &Signing,
    ) -> Result<BuildPlan, Vec<Diagnostic>> {
        Err(vec![Diagnostic::error(format!(
            "target `{}` cannot make packages yet",
            self.descriptor().id
        ))])
    }
}

/// How packages are signed, from the environment of `bern package`.
/// Certificates stay with the person or the CI service that builds; none
/// of this goes into `Bern.toml`.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Signing {
    /// `BERN_MACOS_SIGNING_IDENTITY`: a signing identity in the keychain,
    /// for distribution a "Developer ID Application" one.
    pub macos_identity: Option<String>,
    /// `BERN_MACOS_NOTARY_PROFILE`: a keychain profile made with
    /// `xcrun notarytool store-credentials`.
    pub macos_notary_profile: Option<String>,
    /// `BERN_WINDOWS_CERTIFICATE`: the SHA-1 thumbprint of a code signing
    /// certificate in the user's store, or a `.pfx` file.
    pub windows_certificate: Option<String>,
    /// `BERN_WINDOWS_CERTIFICATE_PASSWORD`: the password of the `.pfx`.
    pub windows_certificate_password: Option<String>,
    /// `BERN_ANDROID_KEYSTORE`: the keystore holding the upload or release
    /// key. Gradle reads it and the variables below from the environment;
    /// the passwords never go into a file.
    pub android_keystore: Option<String>,
    /// `BERN_ANDROID_KEYSTORE_PASSWORD`.
    pub android_keystore_password: Option<String>,
    /// `BERN_ANDROID_KEY_ALIAS`: the key in the keystore.
    pub android_key_alias: Option<String>,
}

impl Signing {
    pub fn from_env() -> Signing {
        let var = |name: &str| {
            std::env::var(name)
                .ok()
                .filter(|value| !value.trim().is_empty())
        };
        Signing {
            macos_identity: var("BERN_MACOS_SIGNING_IDENTITY"),
            macos_notary_profile: var("BERN_MACOS_NOTARY_PROFILE"),
            windows_certificate: var("BERN_WINDOWS_CERTIFICATE"),
            windows_certificate_password: var("BERN_WINDOWS_CERTIFICATE_PASSWORD"),
            android_keystore: var("BERN_ANDROID_KEYSTORE"),
            android_keystore_password: var("BERN_ANDROID_KEYSTORE_PASSWORD"),
            android_key_alias: var("BERN_ANDROID_KEY_ALIAS"),
        }
    }
}

/// Explicit registry of target modules, assembled by the build host.
#[derive(Default)]
pub struct Registry {
    targets: Vec<Box<dyn Target>>,
}

/// Default UI technology per platform.
pub fn default_ui(platform: &str) -> Option<&'static str> {
    match platform {
        "macos" | "ios" => Some("swiftui"),
        "linux" => Some("gtk"),
        "windows" => Some("winui3"),
        "android" => Some("compose"),
        "browser" => Some("web"),
        _ => None,
    }
}

impl Registry {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn register(&mut self, target: Box<dyn Target>) {
        self.targets.push(target);
    }

    pub fn descriptors(&self) -> Vec<TargetDescriptor> {
        self.targets
            .iter()
            .map(|target| target.descriptor())
            .collect()
    }

    /// Resolve the target for a configuration. A missing default backend is
    /// an error; there is never a silent switch to another UI technology.
    pub fn resolve(&self, config: &TargetConfig) -> Result<&dyn Target, Diagnostic> {
        let ui = match &config.ui {
            Some(ui) => ui.clone(),
            None => default_ui(&config.platform)
                .ok_or_else(|| {
                    Diagnostic::error(format!(
                        "target `{}`: unknown platform `{}`",
                        config.name, config.platform
                    ))
                })?
                .to_string(),
        };
        self.targets
            .iter()
            .map(AsRef::as_ref)
            .find(|target| {
                let descriptor = target.descriptor();
                descriptor.ui == ui && descriptor.platforms.contains(&config.platform.as_str())
            })
            .ok_or_else(|| {
                Diagnostic::error(format!(
                    "target `{}`: the `{ui} + {}` backend is not available in this build of Bern",
                    config.name, config.platform
                ))
            })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    struct Fake;

    impl Target for Fake {
        fn descriptor(&self) -> TargetDescriptor {
            TargetDescriptor {
                styles: &[],
                motion: &[],
                window_chrome: false,
                text_marks: false,
                dynamic_items: false,
                features: &[],
                id: "fake-macos",
                ui: "swiftui",
                platforms: &["macos"],
                version: "0",
                ir_versions: IR_VERSION..=IR_VERSION,
                color_source: ColorSource::Native,
                components: &[],
                windows: WindowCapabilities {
                    native: true,
                    virtual_windows: false,
                    floating: true,
                },
                channels: &[],
                media: None,
            }
        }
        fn check(&self, _: &Application, _: &TargetConfig) -> Vec<Diagnostic> {
            vec![]
        }
        fn generate(
            &self,
            _: &Application,
            _: &BuildContext,
        ) -> Result<Vec<GeneratedFile>, Vec<Diagnostic>> {
            Ok(vec![])
        }
        fn plan(&self, _: &Application, _: &BuildContext) -> Result<BuildPlan, Vec<Diagnostic>> {
            Ok(BuildPlan::default())
        }
    }

    fn config(platform: &str, ui: Option<&str>) -> TargetConfig {
        TargetConfig {
            name: "t".into(),
            platform: platform.into(),
            ui: ui.map(String::from),
            web_mode: None,
            channels: vec![],
            frontends: vec![],
        }
    }

    #[test]
    fn defaults_resolve_by_platform_and_missing_backends_fail() {
        let mut registry = Registry::new();
        registry.register(Box::new(Fake));
        assert_eq!(
            registry
                .resolve(&config("macos", None))
                .unwrap()
                .descriptor()
                .id,
            "fake-macos"
        );
        let error = registry.resolve(&config("linux", None)).err().unwrap();
        assert!(error.message.contains("gtk + linux"), "{}", error.message);
        assert!(registry.resolve(&config("macos", Some("flutter"))).is_err());
        assert!(registry.resolve(&config("amiga", None)).is_err());
    }

    #[test]
    fn generated_crates_name_bern_crates_like_the_project() {
        let path = Framework::Path(PathBuf::from("/src/Bern/crates"));
        assert_eq!(
            path.dependency("bern-ffi"),
            r#"path = "/src/Bern/crates/bern-ffi""#
        );
        let git = Framework::Git {
            url: "https://github.com/AimesSoft/Bern".into(),
            reference: Some(("branch".into(), "master".into())),
        };
        assert_eq!(
            git.dependency("bern-ffi"),
            r#"git = "https://github.com/AimesSoft/Bern", branch = "master""#
        );
        assert_eq!(
            Framework::Registry("0.1".into()).dependency("bern-ffi"),
            r#"version = "0.1""#
        );
        assert_eq!(toml_string(r#"C:\a "b""#), r#""C:\\a \"b\"""#);
    }
}
