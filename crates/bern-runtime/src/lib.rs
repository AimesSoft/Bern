//! UI session runtime shared by every target.
//!
//! A UI session owns window instances and the typed session drafts each
//! window carries. It validates every write against the declared schema and
//! gives each window instance a generation, so a reference to a closed
//! window is rejected instead of writing into a newer instance. It contains
//! no UI SDK code: targets report window facts and forward control input.

use bern_protocol::{CommandError, SessionCommand, Type, TypeTable, Value};
use std::collections::BTreeMap;
use std::sync::{Arc, Mutex};

/// One declared session state type.
#[derive(Clone, Debug)]
pub struct SessionType {
    pub name: String,
    /// Field name, type and initial value.
    pub fields: Vec<(String, Type, Value)>,
}

/// One declared window kind.
#[derive(Clone, Debug)]
pub struct WindowKind {
    pub id: String,
    /// Indices into [`SessionSpec::sessions`] instantiated per instance.
    pub sessions: Vec<usize>,
}

/// Static description of the session layer, generated by the build.
#[derive(Clone, Debug)]
pub struct SessionSpec {
    pub types: TypeTable,
    pub sessions: Vec<SessionType>,
    pub windows: Vec<WindowKind>,
}

#[derive(Clone, Debug, PartialEq)]
pub struct WindowInstance {
    pub kind: usize,
    pub generation: u64,
    /// External identity, `<kind id>#<generation>`.
    pub id: String,
    /// Draft values per session of the window, in [`WindowKind::sessions`] order.
    pub drafts: Vec<Vec<Value>>,
}

#[derive(Debug)]
struct WindowState {
    generation: u64,
    open: bool,
    drafts: Vec<Vec<Value>>,
}

/// Window instances and drafts of one UI session.
#[derive(Debug)]
pub struct UiSession {
    session_id: String,
    spec: Arc<SessionSpec>,
    windows: Vec<WindowState>,
    revision: u64,
}

fn stale() -> CommandError {
    CommandError::new(
        "stale_window",
        "the window instance was closed; use the current instance",
    )
}

impl UiSession {
    pub fn new(session_id: impl Into<String>, spec: Arc<SessionSpec>) -> Self {
        let windows = spec
            .windows
            .iter()
            .map(|_| WindowState {
                generation: 0,
                open: false,
                drafts: Vec::new(),
            })
            .collect();
        Self {
            session_id: session_id.into(),
            spec,
            windows,
            revision: 0,
        }
    }

    pub fn session_id(&self) -> &str {
        &self.session_id
    }

    pub fn spec(&self) -> &SessionSpec {
        &self.spec
    }

    /// Revision of the session state, bumped by every accepted write.
    pub fn revision(&self) -> u64 {
        self.revision
    }

    fn initial_drafts(&self, kind: usize) -> Vec<Vec<Value>> {
        self.spec.windows[kind]
            .sessions
            .iter()
            .map(|session| {
                self.spec.sessions[*session]
                    .fields
                    .iter()
                    .map(|(_, _, initial)| initial.clone())
                    .collect()
            })
            .collect()
    }

    fn instance(&self, kind: usize) -> WindowInstance {
        let state = &self.windows[kind];
        WindowInstance {
            kind,
            generation: state.generation,
            id: format!("{}#{}", self.spec.windows[kind].id, state.generation),
            drafts: state.drafts.clone(),
        }
    }

    /// The adapter observed that a window of `kind` is shown. Reporting an
    /// already open window returns the same instance; a reopened window
    /// starts a new generation with fresh drafts.
    pub fn window_opened(&mut self, kind: usize) -> Result<WindowInstance, CommandError> {
        if kind >= self.windows.len() {
            return Err(CommandError::new("target_not_found", "unknown window kind"));
        }
        if !self.windows[kind].open {
            let drafts = self.initial_drafts(kind);
            let state = &mut self.windows[kind];
            state.generation += 1;
            state.open = true;
            state.drafts = drafts;
            self.revision += 1;
        }
        Ok(self.instance(kind))
    }

    /// The adapter observed that a window instance closed. Window-scoped
    /// drafts are released; a stale generation is ignored.
    pub fn window_closed(&mut self, kind: usize, generation: u64) -> bool {
        match self.windows.get_mut(kind) {
            Some(state) if state.open && state.generation == generation => {
                state.open = false;
                state.drafts.clear();
                self.revision += 1;
                true
            }
            _ => false,
        }
    }

    pub fn open_windows(&self) -> Vec<WindowInstance> {
        (0..self.windows.len())
            .filter(|kind| self.windows[*kind].open)
            .map(|kind| self.instance(kind))
            .collect()
    }

    /// Find the open instance with an external id such as `settings#2`.
    pub fn find_window(&self, id: &str) -> Option<WindowInstance> {
        self.open_windows()
            .into_iter()
            .find(|window| window.id == id)
    }

    pub fn window_kind(&self, id: &str) -> Option<usize> {
        self.spec.windows.iter().position(|kind| kind.id == id)
    }

    fn slot(&self, kind: usize, generation: u64, session: usize) -> Result<usize, CommandError> {
        let state = self
            .windows
            .get(kind)
            .ok_or_else(|| CommandError::new("target_not_found", "unknown window kind"))?;
        if !state.open || state.generation != generation {
            return Err(stale());
        }
        self.spec.windows[kind]
            .sessions
            .iter()
            .position(|candidate| *candidate == session)
            .ok_or_else(|| {
                CommandError::new(
                    "target_not_found",
                    "this window does not own that session state",
                )
            })
    }

    /// Write one session field after checking it against the schema.
    pub fn set(
        &mut self,
        kind: usize,
        generation: u64,
        session: usize,
        field: usize,
        value: Value,
    ) -> Result<u64, CommandError> {
        let slot = self.slot(kind, generation, session)?;
        let session_type = &self.spec.sessions[session];
        let (name, ty, _) = session_type
            .fields
            .get(field)
            .ok_or_else(|| CommandError::new("target_not_found", "unknown session field"))?;
        value.check(ty, &self.spec.types).map_err(|error| {
            CommandError::invalid_params(format!("{}.{name}: {error}", session_type.name))
        })?;
        let current = &mut self.windows[kind].drafts[slot][field];
        if *current != value {
            *current = value;
            self.revision += 1;
        }
        Ok(self.revision)
    }

    pub fn get(
        &self,
        kind: usize,
        generation: u64,
        session: usize,
        field: usize,
    ) -> Result<Value, CommandError> {
        let slot = self.slot(kind, generation, session)?;
        self.windows[kind].drafts[slot]
            .get(field)
            .cloned()
            .ok_or_else(|| CommandError::new("target_not_found", "unknown session field"))
    }
}

/// Executes framework session commands for one live UI session. Targets
/// implement it so external entries reach the real control bindings.
pub trait SessionHandler: Send + Sync {
    fn session_id(&self) -> String;
    /// Open window instance ids, for discovery.
    fn windows(&self) -> Vec<String>;
    /// Run a session command and wait for its result.
    fn handle(&self, command: SessionCommand, params: Vec<Value>) -> Result<Value, CommandError>;
}

/// Live UI sessions that external entries may address by `session_id`.
#[derive(Clone, Default)]
pub struct Sessions {
    inner: Arc<Mutex<BTreeMap<String, Arc<dyn SessionHandler>>>>,
}

impl Sessions {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn register(&self, handler: Arc<dyn SessionHandler>) {
        self.inner
            .lock()
            .expect("sessions lock")
            .insert(handler.session_id(), handler);
    }

    pub fn unregister(&self, session_id: &str) {
        self.inner.lock().expect("sessions lock").remove(session_id);
    }

    pub fn list(&self) -> Vec<Arc<dyn SessionHandler>> {
        self.inner
            .lock()
            .expect("sessions lock")
            .values()
            .cloned()
            .collect()
    }

    /// Route a session command. Without a session id the command goes to
    /// the only live session; none or several sessions are explicit errors.
    pub fn handle(
        &self,
        session_id: Option<&str>,
        command: SessionCommand,
        params: Vec<Value>,
    ) -> Result<Value, CommandError> {
        let handler = {
            let sessions = self.inner.lock().expect("sessions lock");
            match session_id {
                Some(id) => sessions.get(id).cloned().ok_or_else(|| {
                    CommandError::new("session_not_found", format!("no live UI session `{id}`"))
                })?,
                None => match sessions.len() {
                    0 => {
                        return Err(CommandError::new(
                            "requires_ui_session",
                            format!("`{}` needs a live UI session", command.id()),
                        ));
                    }
                    1 => sessions.values().next().unwrap().clone(),
                    _ => {
                        return Err(CommandError::new(
                            "session_required",
                            "several UI sessions are live; name one with session_id",
                        ));
                    }
                },
            }
        };
        handler.handle(command, params)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec() -> Arc<SessionSpec> {
        Arc::new(SessionSpec {
            types: TypeTable::default(),
            sessions: vec![SessionType {
                name: "Draft".into(),
                fields: vec![
                    ("name".into(), Type::Text, Value::Text(String::new())),
                    ("volume".into(), Type::Float, Value::Float(50.0)),
                ],
            }],
            windows: vec![
                WindowKind {
                    id: "main".into(),
                    sessions: vec![0],
                },
                WindowKind {
                    id: "settings".into(),
                    sessions: vec![],
                },
            ],
        })
    }

    #[test]
    fn drafts_are_window_scoped_and_reset_on_reopen() {
        let mut session = UiSession::new("s", spec());
        let first = session.window_opened(0).unwrap();
        assert_eq!(first.id, "main#1");
        assert_eq!(first.drafts[0][1], Value::Float(50.0));
        session.set(0, 1, 0, 0, Value::Text("Ada".into())).unwrap();
        // Reporting the same open window keeps the instance and its drafts.
        assert_eq!(
            session.window_opened(0).unwrap().drafts[0][0],
            Value::Text("Ada".into())
        );
        assert!(session.window_closed(0, 1));
        let second = session.window_opened(0).unwrap();
        assert_eq!(second.id, "main#2");
        assert_eq!(second.drafts[0][0], Value::Text(String::new()));
    }

    #[test]
    fn writes_are_schema_checked_and_stale_windows_rejected() {
        let mut session = UiSession::new("s", spec());
        session.window_opened(0).unwrap();
        let error = session
            .set(0, 1, 0, 1, Value::Text("loud".into()))
            .unwrap_err();
        assert_eq!(error.code, "invalid_params");
        session.window_closed(0, 1);
        session.window_opened(0).unwrap();
        assert_eq!(
            session
                .set(0, 1, 0, 0, Value::Text("x".into()))
                .unwrap_err()
                .code,
            "stale_window"
        );
        assert!(!session.window_closed(0, 1));
        assert_eq!(
            session
                .set(1, 0, 0, 0, Value::Text("x".into()))
                .unwrap_err()
                .code,
            "stale_window"
        );
    }

    struct Echo(String);

    impl SessionHandler for Echo {
        fn session_id(&self) -> String {
            self.0.clone()
        }
        fn windows(&self) -> Vec<String> {
            vec![]
        }
        fn handle(&self, command: SessionCommand, _: Vec<Value>) -> Result<Value, CommandError> {
            Ok(Value::Text(format!("{}:{}", self.0, command.id())))
        }
    }

    #[test]
    fn routing_requires_an_unambiguous_live_session() {
        let sessions = Sessions::new();
        assert_eq!(
            sessions
                .handle(None, SessionCommand::Inspect, vec![])
                .unwrap_err()
                .code,
            "requires_ui_session"
        );
        sessions.register(Arc::new(Echo("a".into())));
        assert_eq!(
            sessions
                .handle(None, SessionCommand::Inspect, vec![])
                .unwrap(),
            Value::Text("a:ui.inspect".into())
        );
        sessions.register(Arc::new(Echo("b".into())));
        assert_eq!(
            sessions
                .handle(None, SessionCommand::Inspect, vec![])
                .unwrap_err()
                .code,
            "session_required"
        );
        assert!(
            sessions
                .handle(Some("b"), SessionCommand::Back, vec![])
                .is_ok()
        );
        assert_eq!(
            sessions
                .handle(Some("z"), SessionCommand::Back, vec![])
                .unwrap_err()
                .code,
            "session_not_found"
        );
    }
}
