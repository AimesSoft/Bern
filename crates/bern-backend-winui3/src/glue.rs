/// The MSVC architecture of the build machine.
pub fn architecture() -> &'static str {
    match std::env::consts::ARCH {
        "aarch64" => "arm64",
        "x86" => "x86",
        _ => "x64",
    }
}

/// The runtime identifier of the build machine's architecture.
pub fn runtime_identifier() -> String {
    format!("win-{}", architecture())
}

/// Numeric version parts from the application version: `1.2.3` stays,
/// anything after the numbers is dropped.
fn version_parts(version: &str) -> [u16; 3] {
    let mut parts = [0u16; 3];
    let numbers = version
        .split(['.', '-', '+'])
        .take(3)
        .map_while(|part| part.parse::<u16>().ok());
    let mut any = false;
    for (slot, number) in parts.iter_mut().zip(numbers) {
        *slot = number;
        any = true;
    }
    if !any {
        parts = [1, 0, 0];
    }
    parts
}

/// Paths in the build script, with Windows separators.
fn windows_path(path: &Path) -> String {
    path.display().to_string().replace('/', "\\")
}

/// Where the build script finds things.
pub struct Script<'a> {
    pub bundle: &'a Path,
    pub executable: &'a str,
    pub engine: &'a Path,
    pub cache: &'a Path,
    pub release: bool,
    /// What the precompiled header is made of that Bern knows: the runtime
    /// and the options. The script adds the compiler, the SDK and paths.
    pub precompiled: &'a str,
    pub frontends: Frontends,
}

/// The front ends a Windows build includes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Frontends {
    /// WinUI 3, on the Windows App Runtime.
    pub winui: bool,
    /// The system XAML through XAML Islands.
    pub islands: bool,
}

impl Frontends {
    /// The target's front ends; both when it names none.
    pub fn of(names: &[String]) -> Frontends {
        let named = |name: &str| names.is_empty() || names.iter().any(|named| named == name);
        Frontends {
            winui: named("winui3"),
            islands: named("xaml-islands"),
        }
    }

    pub fn names(self) -> Vec<&'static str> {
        [(self.winui, "winui3"), (self.islands, "xaml-islands")]
            .into_iter()
            .filter_map(|(on, name)| on.then_some(name))
            .collect()
    }
}

/// The compiler options of every source, the precompiled header's included.
pub fn compile_options(release: bool, frontends: Frontends) -> String {
    let opt = if release { "/O1 /DNDEBUG" } else { "/Od /Z7" };
    format!(
        "/nologo /c /std:c++20 /EHsc /MT {opt} /Gy /Gw /bigobj /permissive- /utf-8 /W3 /wd4505 /DUNICODE /D_UNICODE /DNOMINMAX /DWIN32_LEAN_AND_MEAN /DBERN_WITH_WINUI={} /DBERN_WITH_ISLANDS={}",
        u8::from(frontends.winui),
        u8::from(frontends.islands)
    )
}

/// The Windows App Runtime installer that a build with WinUI 3 alone offers
/// when the system has no runtime: the newest release, for this machine's
/// architecture.
pub fn runtime_installer() -> String {
    format!(
        "https://aka.ms/windowsappsdk/{WINDOWS_APP_SDK}/latest/windowsappruntimeinstall-{}.exe",
        architecture()
    )
}

/// The build script: the Visual Studio C++ tools, the Windows App SDK
/// packages (the NuGet cache, else nuget.org through the `curl` and `tar`
/// of Windows), C++/WinRT headers for the
/// Windows SDK and WinUI 3 (generated once per version and cached), a
/// precompiled header of C++/WinRT and the runtime (made once and kept
/// while its inputs stay the same), then one compile of the generated
/// sources and one link with the engine library. With WinUI 3 the Windows
/// App Runtime bootstrapper goes next to the executable. `build.bat
/// compile` only compiles.
pub fn build_script(script: &Script) -> String {
    let arch = architecture();
    let component = if arch == "arm64" {
        "Microsoft.VisualStudio.Component.VC.Tools.ARM64"
    } else {
        "Microsoft.VisualStudio.Component.VC.Tools.x86.x64"
    };
    let package = |id: &str| {
        PACKAGES
            .iter()
            .find(|(name, _)| *name == id)
            .map(|(_, version)| *version)
            .expect("package")
    };
    let frontends = script.frontends;
    let units: Vec<&str> = [
        ("bern_base", true),
        ("bern_main", true),
        ("bern_winui", frontends.winui),
        ("bern_islands", frontends.islands),
    ]
    .into_iter()
    .filter_map(|(name, wanted)| wanted.then_some(name))
    .collect();
    let objects = ["bern_pch"]
        .iter()
        .chain(&units)
        .chain(&["app_catalog"])
        .map(|name| format!("\"%OBJ%\\{name}.obj\""))
        .collect::<Vec<_>>()
        .join(" ");
    let sources = units
        .iter()
        .map(|name| format!("\"%APP%\\runtime\\{name}.cpp\""))
        .chain(["\"%APP%\\app_catalog.cpp\"".to_string()])
        .collect::<Vec<_>>()
        .join(" ");
    // WinUI 3 links the bootstrapper, which ships next to the executable;
    // the system XAML needs neither.
    let bootstrap_lib = if frontends.winui {
        r#" "%FOUNDATION%\lib\native\%ARCH%\Microsoft.WindowsAppRuntime.Bootstrap.lib""#
    } else {
        ""
    };
    let bootstrap_dll = if frontends.winui {
        r#"copy /y "%FOUNDATION%\runtimes\win-%ARCH%\native\Microsoft.WindowsAppRuntime.Bootstrap.dll" "%OUT%\" >nul || goto failed"#
    } else {
        r#"del /q "%OUT%\Microsoft.WindowsAppRuntime.Bootstrap.dll" 2>nul"#
    };
    format!(
        r#"@echo off
rem Generated by Bern. Do not edit.
rem Builds the Windows application: C++/WinRT headers (generated once and
rem cached), a precompiled header of them and the runtime (made once), the
rem generated sources, and one executable with the engine linked in.
setlocal EnableExtensions
set "APP=%~dp0"
set "APP=%APP:~0,-1%"
set "OUT={bundle}"
set "EXE={executable}"
set "ENGINE={engine}"
set "CACHE={cache}"
set "ARCH={arch}"
set "DEBUGINFO={debug}"

set "VSWHERE=%ProgramFiles(x86)%\Microsoft Visual Studio\Installer\vswhere.exe"
if not exist "%VSWHERE%" goto no_vs
set "VS="
for /f "usebackq delims=" %%i in (`"%VSWHERE%" -latest -products * -requires {component} -property installationPath`) do set "VS=%%i"
if not defined VS goto no_vs
call "%VS%\VC\Auxiliary\Build\vcvarsall.bat" {arch} >nul || goto failed
if not defined WindowsSDKVersion goto no_sdk

set "PACKAGES=%NUGET_PACKAGES%"
if not defined PACKAGES set "PACKAGES=%USERPROFILE%\.nuget\packages"
call :package microsoft.windowsappsdk.foundation {foundation} FOUNDATION || goto failed
call :package microsoft.windowsappsdk.winui {winui} WINUI || goto failed
call :package microsoft.windowsappsdk.interactiveexperiences {ix} IX || goto failed
call :package microsoft.web.webview2 {webview2} WEBVIEW2 || goto failed

set "SDK=%WindowsSDKVersion:~0,-1%"
set "WINRT=%CACHE%\winrt-%SDK%-{winui}"
if exist "%WINRT%\winrt\Microsoft.UI.Xaml.h" goto compile
set "CPPWINRT=%WindowsSdkVerBinPath%%VSCMD_ARG_HOST_ARCH%\cppwinrt.exe"
if not exist "%CPPWINRT%" set "CPPWINRT=%WindowsSdkVerBinPath%x86\cppwinrt.exe"
if not exist "%CPPWINRT%" goto no_sdk
echo Generating C++/WinRT headers for Windows SDK %SDK%
"%CPPWINRT%" -input %SDK%+ -input "%WINUI%\metadata" -input "%IX%\metadata\10.0.18362.0" -input "%FOUNDATION%\metadata" -input "%WEBVIEW2%\lib\Microsoft.Web.WebView2.Core.winmd" -output "%WINRT%" || goto failed

:compile
rem One directory per profile, so each keeps its precompiled header.
set "OBJ=%APP%\obj\{profile}"
if not exist "%OBJ%" mkdir "%OBJ%"
set CFLAGS={options} /I"%WINRT%" /I"%FOUNDATION%\include" /I"%WINUI%\include" /I"%IX%\include" /I"%APP%" /I"%APP%\runtime" /Fo"%OBJ%\\"
set PCH=/Fp"%OBJ%\bern.pch"
rem The precompiled header holds C++/WinRT and the runtime for both front
rem ends, and takes most of a build's time. It is made again only when the
rem runtime, the options, the compiler, the SDK or a path changes.
set "KEY={pch} %VCToolsVersion% %SDK% %WINRT% %FOUNDATION% %WINUI% %IX% %APP%"
set "MADE="
if exist "%OBJ%\bern.pch" if exist "%OBJ%\bern_pch.obj" if exist "%OBJ%\pch.key" set /p MADE=<"%OBJ%\pch.key"
if "%MADE%"=="%KEY%" goto precompiled
del /q "%OBJ%\pch.key" 2>nul
echo Precompiling the C++/WinRT and runtime headers; later builds reuse them
cl %CFLAGS% /Yc"bern_pch.h" %PCH% "%APP%\runtime\bern_pch.cpp" || goto failed
setlocal EnableDelayedExpansion
>"%OBJ%\pch.key" echo(!KEY!
endlocal
:precompiled
cl %CFLAGS% /MP /Yu"bern_pch.h" %PCH% {sources} || goto failed
rem `build.bat compile` stops here: a check of the generated sources.
if /i "%~1"=="compile" exit /b 0
rc /nologo /i "%APP%" /fo "%OBJ%\app.res" "%APP%\app.rc" || goto failed
if not exist "%OUT%" mkdir "%OUT%"
rem Symbols stay with the intermediate files, out of the application.
del /q "%OUT%\%EXE%.pdb" 2>nul
set "LINKOPT="
if "%DEBUGINFO%"=="1" set LINKOPT=/DEBUG /PDB:"%OBJ%\%EXE%.pdb"
link /nologo %LINKOPT% /OUT:"%OUT%\%EXE%.exe" /SUBSYSTEM:WINDOWS /OPT:REF /OPT:ICF /MANIFEST:EMBED /MANIFESTINPUT:"%APP%\app.manifest" {objects} "%OBJ%\app.res" "%ENGINE%"{bootstrap_lib} windowsapp.lib kernel32.lib user32.lib gdi32.lib ole32.lib oleaut32.lib advapi32.lib shell32.lib shlwapi.lib dwmapi.lib ntdll.lib userenv.lib ws2_32.lib bcrypt.lib dbghelp.lib secur32.lib crypt32.lib ncrypt.lib iphlpapi.lib synchronization.lib || goto failed
{bootstrap_dll}
exit /b 0

:package
if exist "%PACKAGES%\%1\%2\" goto package_nuget
if exist "%CACHE%\packages\%1.%2\" goto package_cached
rem Not in the NuGet cache: fetch the package with the curl and tar of
rem Windows into the build cache.
echo Fetching %1 %2 from nuget.org
set "PART=%CACHE%\packages\%1.%2.partial"
if exist "%PART%" rmdir /s /q "%PART%"
mkdir "%PART%" || exit /b 1
curl.exe --fail --location --silent --show-error --output "%PART%.nupkg" "https://api.nuget.org/v3-flatcontainer/%1/%2/%1.%2.nupkg" || exit /b 1
tar.exe -xf "%PART%.nupkg" -C "%PART%" || exit /b 1
del /q "%PART%.nupkg"
move "%PART%" "%CACHE%\packages\%1.%2" >nul || exit /b 1
:package_cached
set "%3=%CACHE%\packages\%1.%2"
exit /b 0
:package_nuget
set "%3=%PACKAGES%\%1\%2"
exit /b 0

:no_vs
echo bern: building for Windows needs the Visual Studio C++ build tools ^("Desktop development with C++"^).
exit /b 1
:no_sdk
echo bern: building for Windows needs a Windows 10 or 11 SDK with cppwinrt.exe.
exit /b 1
:failed
exit /b 1
"#,
        bundle = windows_path(script.bundle),
        executable = script.executable,
        engine = windows_path(script.engine),
        cache = windows_path(script.cache),
        profile = if script.release { "release" } else { "debug" },
        options = compile_options(script.release, frontends),
        pch = script.precompiled,
        debug = if script.release { "0" } else { "1" },
        foundation = package("microsoft.windowsappsdk.foundation"),
        winui = package("microsoft.windowsappsdk.winui"),
        ix = package("microsoft.windowsappsdk.interactiveexperiences"),
        webview2 = package("microsoft.web.webview2"),
    )
    .replace("\n", "\r\n")
}

/// Text in a resource script string.
fn rc_text(text: &str) -> String {
    text.replace('"', "\"\"")
}

/// The version resource, with the name Windows shows for the process, and
/// the application icon (`app.ico`, beside the script).
pub fn resource_script(app: &Application, executable: &str) -> String {
    let name = app
        .app
        .name
        .get(&app.languages.default)
        .unwrap_or(&app.app.id);
    let [major, minor, patch] = version_parts(&app.app.version);
    format!(
        r#"// Generated by Bern. Do not edit.
#pragma code_page(65001)
#include <winver.h>

// The application icon: the first icon resource is the one Windows shows
// for the executable, and the runtime gives it to every window.
1 ICON "app.ico"

1 VERSIONINFO
FILEVERSION {major},{minor},{patch},0
PRODUCTVERSION {major},{minor},{patch},0
FILEOS VOS_NT_WINDOWS32
FILETYPE VFT_APP
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904B0"
        BEGIN
            VALUE "FileDescription", "{name}"
            VALUE "FileVersion", "{version}"
            VALUE "InternalName", "{executable}"
            VALUE "OriginalFilename", "{executable}.exe"
            VALUE "ProductName", "{name}"
            VALUE "ProductVersion", "{version}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#,
        name = rc_text(name),
        version = rc_text(&app.app.version),
    )
}

/// Per-monitor DPI awareness, and the Windows versions the application was
/// tested on: XAML Islands needs the newest one declared.
pub fn manifest(app: &Application) -> String {
    format!(
        r#"<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Bern. Do not edit. -->
<assembly manifestVersion="1.0" xmlns="urn:schemas-microsoft-com:asm.v1">
  <assemblyIdentity version="1.0.0.0" name="{bundle}" />
  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">
    <application>
      <supportedOS Id="{{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}}" />
      <maxversiontested Id="10.0.26100.0" />
    </application>
  </compatibility>
  <application xmlns="urn:schemas-microsoft-com:asm.v3">
    <windowsSettings>
      <dpiAware xmlns="http://schemas.microsoft.com/SMI/2005/WindowsSettings">true/PM</dpiAware>
      <dpiAwareness xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">PerMonitorV2</dpiAwareness>
    </windowsSettings>
  </application>
</assembly>
"#,
        bundle = xml(&app.app.bundle_id),
    )
}

