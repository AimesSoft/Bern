use std::path::Path;

/// Windows App SDK release the runtime is written against: the newest. Its
/// headers and metadata are build inputs only; applications use any
/// Windows App Runtime 2 the system has, installed by another program or
/// the copy Windows 11 ships with, or the system XAML when there is none.
pub const WINDOWS_APP_SDK: &str = "2.5";
/// The Windows App SDK component packages the build reads, from the NuGet
/// cache or nuget.org: `(id, version)`, as Windows App SDK 2.5.1 has them.
pub const PACKAGES: &[(&str, &str)] = &[
    ("microsoft.windowsappsdk.foundation", "2.3.12"),
    ("microsoft.windowsappsdk.winui", "2.3.9"),
    ("microsoft.windowsappsdk.interactiveexperiences", "2.1.9"),
    ("microsoft.web.webview2", "1.0.3719.77"),
];
/// Oldest Windows the application runs on: Windows 10, version 2004.
pub const MINIMUM_WINDOWS: &str = "10.0.19041.0";

fn path(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}

/// Escape text for XML content and attributes.
fn xml(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

pub fn cargo_toml(context: &BuildContext, app: &Application) -> String {
    let bern = |name: &str| context.framework.dependency(name);
    let executable = app.app.id.replace('_', "-");
    format!(
        r#"# Generated by Bern. Do not edit.
[package]
name = "bern-glue-{executable}"
version = "{version}"
edition = "2024"
publish = false

[lib]
name = "bern_app"
crate-type = ["staticlib"]
path = "src/lib.rs"

[[bin]]
name = "{executable}"
path = "src/cli.rs"

[[bin]]
name = "{executable}-mcp"
path = "src/mcp.rs"

[dependencies]
bern-ffi = {{ {ffi}{ipc} }}
bern-adapter-cli = {{ {cli_adapter} }}
bern-adapter-mcp = {{ {mcp_adapter} }}
{protocol} = {{ path = "{protocol_path}" }}
{engine} = {{ path = "{engine_path}" }}

[workspace]

[profile.release]
panic = "unwind"
"#,
        version = app.app.version,
        ffi = bern("bern-ffi"),
        ipc = if context
            .target
            .channels
            .iter()
            .any(|channel| channel == "ipc")
        {
            ""
        } else {
            ", default-features = false"
        },
        cli_adapter = bern("bern-adapter-cli"),
        mcp_adapter = bern("bern-adapter-mcp"),
        protocol = context.protocol_package,
        protocol_path = path(&context.protocol_path),
        engine = context.engine_package,
        engine_path = path(&context.engine_path),
    )
}

pub fn lib_rs(context: &BuildContext, app: &Application) -> String {
    let ipc = context
        .target
        .channels
        .iter()
        .any(|channel| channel == "ipc");
    format!(
        r#"//! Generated by Bern. Do not edit.
//!
//! Links the `{namespace}` engine, the UI session runtime and the C ABI
//! into `bern_app.lib`, which the C++ frontend links and calls in-process.

pub use bern_ffi::{{BernApp, BernBuffer, BernCallbacks}};

/// Start the engine for the frontend generated from the same catalog.
/// `resources` is the directory holding the declared resources.
///
/// # Safety
/// `resources` must point to `resources_len` readable bytes or be null with
/// `resources_len == 0`; `error` must be null or point to writable memory
/// for one `BernBuffer`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_app_start(
    fingerprint: u64,
    resources: *const u8,
    resources_len: usize,
    callbacks: BernCallbacks,
    error: *mut BernBuffer,
) -> *mut BernApp {{
    // SAFETY: forwarded from the caller.
    unsafe {{
        bern_ffi::start_app(
            || {protocol}::Adapter(<{engine} as ::std::default::Default>::default()),
            spec(),
            fingerprint,
            resources,
            resources_len,
            callbacks,
            error,
        )
    }}
}}

fn spec() -> bern_ffi::AppSpec {{
    bern_ffi::AppSpec {{
        bundle_id: {bundle:?},
        ipc: {ipc},
        players: vec![{players}],
        resources: vec![{resources}],
        session: {session},
    }}
}}
"#,
        namespace = app.protocol.namespace,
        protocol = context.protocol_module,
        engine = context.engine_type,
        bundle = app.app.bundle_id,
        session = session_spec(app, WindowPresentation::Native),
        players = players_expr(app),
        resources = resources_expr(app),
    )
}

