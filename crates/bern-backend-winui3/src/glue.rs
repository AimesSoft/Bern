/// The .NET runtime identifier of the build machine's architecture.
pub fn runtime_identifier() -> &'static str {
    match std::env::consts::ARCH {
        "aarch64" => "win-arm64",
        "x86" => "win-x86",
        _ => "win-x64",
    }
}

/// A numeric assembly version from the application version: `1.2.3`
/// stays, anything after the numbers is dropped.
fn assembly_version(version: &str) -> String {
    let parts: Vec<&str> = version
        .split(['.', '-', '+'])
        .take(3)
        .take_while(|part| !part.is_empty() && part.chars().all(|c| c.is_ascii_digit()))
        .collect();
    if parts.is_empty() {
        "1.0.0".into()
    } else {
        parts.join(".")
    }
}

/// The application's .NET project: an unpackaged WinUI 3 application with
/// the Windows App SDK deployed next to it, and `bern_app.dll` copied
/// beside the executable.
pub fn csproj(app: &Application, executable: &str, library: &Path) -> String {
    let name = app
        .app
        .name
        .get(&app.languages.default)
        .unwrap_or(&app.app.id);
    format!(
        r#"<!-- Generated by Bern. Do not edit. -->
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <OutputType>WinExe</OutputType>
    <TargetFramework>{TARGET_FRAMEWORK}</TargetFramework>
    <TargetPlatformMinVersion>{MINIMUM_WINDOWS}</TargetPlatformMinVersion>
    <RuntimeIdentifier>{rid}</RuntimeIdentifier>
    <UseWinUI>true</UseWinUI>
    <WindowsPackageType>None</WindowsPackageType>
    <WindowsAppSDKSelfContained>true</WindowsAppSDKSelfContained>
    <DefineConstants>$(DefineConstants);DISABLE_XAML_GENERATED_MAIN</DefineConstants>
    <Nullable>enable</Nullable>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
    <AssemblyName>{executable}</AssemblyName>
    <RootNamespace>BernApp</RootNamespace>
    <Product>{product_name}</Product>
    <AssemblyTitle>{product_name}</AssemblyTitle>
    <Version>{version}</Version>
    <ApplicationManifest>app.manifest</ApplicationManifest>
    <SatelliteResourceLanguages>en</SatelliteResourceLanguages>
    <NoWarn>$(NoWarn);CS1591</NoWarn>
  </PropertyGroup>
  <ItemGroup>
    <PackageReference Include="Microsoft.WindowsAppSDK" Version="{WINDOWS_APP_SDK}" />
  </ItemGroup>
  <ItemGroup>
    <None Include="{library}" Link="bern_app.dll" CopyToOutputDirectory="PreserveNewest" Condition="Exists('{library}')" />
  </ItemGroup>
</Project>
"#,
        rid = runtime_identifier(),
        product_name = xml(name),
        version = assembly_version(&app.app.version),
        library = xml(&library.display().to_string()),
        executable = xml(executable),
    )
}

/// Per-monitor DPI awareness, as WinUI 3 applications declare it.
pub fn manifest(app: &Application) -> String {
    format!(
        r#"<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Bern. Do not edit. -->
<assembly manifestVersion="1.0" xmlns="urn:schemas-microsoft-com:asm.v1">
  <assemblyIdentity version="1.0.0.0" name="{bundle}" />
  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">
    <application>
      <supportedOS Id="{{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}}" />
    </application>
  </compatibility>
  <application xmlns="urn:schemas-microsoft-com:asm.v3">
    <windowsSettings>
      <dpiAware xmlns="http://schemas.microsoft.com/SMI/2005/WindowsSettings">true/PM</dpiAware>
      <dpiAwareness xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">PerMonitorV2</dpiAwareness>
    </windowsSettings>
  </application>
</assembly>
"#,
        bundle = xml(&app.app.bundle_id),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn assembly_versions_are_numeric() {
        assert_eq!(assembly_version("0.1.0"), "0.1.0");
        assert_eq!(assembly_version("2.0.0-beta.1"), "2.0.0");
        assert_eq!(assembly_version("nightly"), "1.0.0");
    }
}
