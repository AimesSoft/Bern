//! The generated build inputs around the C# frontend: the Rust glue crate
//! that links the engine, the session runtime and the C ABI into
//! `bern_app.dll`, the application CLI and MCP server from the same command
//! catalog, and the .NET project of the WinUI 3 application.

use bern_ir::Application;
use bern_target_api::BuildContext;
use bern_target_api::glue::{WindowPresentation, players_expr, resources_expr, session_spec};
use std::path::Path;

/// Windows App SDK release the runtime is written against.
pub const WINDOWS_APP_SDK: &str = "1.8.260921001";
/// .NET the application targets, with the Windows SDK projection.
pub const TARGET_FRAMEWORK: &str = "net10.0-windows10.0.26100.0";
/// Oldest Windows the application runs on: Windows 10, version 2004.
pub const MINIMUM_WINDOWS: &str = "10.0.19041.0";

fn path(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}

/// Escape text for XML content and attributes.
fn xml(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

pub fn cargo_toml(context: &BuildContext, app: &Application) -> String {
    let crates = context.workspace_dir.join("crates");
    let executable = app.app.id.replace('_', "-");
    format!(
        r#"# Generated by Bern. Do not edit.
[package]
name = "bern-glue-{executable}"
version = "{version}"
edition = "2024"
publish = false

[lib]
name = "bern_app"
crate-type = ["cdylib"]
path = "src/lib.rs"

[[bin]]
name = "{executable}"
path = "src/cli.rs"

[[bin]]
name = "{executable}-mcp"
path = "src/mcp.rs"

[dependencies]
bern-ffi = {{ path = "{ffi}"{ipc} }}
bern-adapter-cli = {{ path = "{cli_adapter}" }}
bern-adapter-mcp = {{ path = "{mcp_adapter}" }}
{protocol} = {{ path = "{protocol_path}" }}
{engine} = {{ path = "{engine_path}" }}

[workspace]

[profile.release]
panic = "unwind"
"#,
        version = app.app.version,
        ffi = path(&crates.join("bern-ffi")),
        ipc = if context
            .target
            .channels
            .iter()
            .any(|channel| channel == "ipc")
        {
            ""
        } else {
            ", default-features = false"
        },
        cli_adapter = path(&crates.join("bern-adapter-cli")),
        mcp_adapter = path(&crates.join("bern-adapter-mcp")),
        protocol = context.protocol_package,
        protocol_path = path(&context.protocol_path),
        engine = context.engine_package,
        engine_path = path(&context.engine_path),
    )
}

pub fn lib_rs(context: &BuildContext, app: &Application) -> String {
    let ipc = context
        .target
        .channels
        .iter()
        .any(|channel| channel == "ipc");
    format!(
        r#"//! Generated by Bern. Do not edit.
//!
//! Links the `{namespace}` engine, the UI session runtime and the C ABI
//! into `bern_app.dll`, which the WinUI 3 frontend calls in-process.

pub use bern_ffi::{{BernApp, BernBuffer, BernCallbacks}};

/// Start the engine for the frontend generated from the same catalog.
/// `resources` is the directory holding the declared resources.
///
/// # Safety
/// `resources` must point to `resources_len` readable bytes or be null with
/// `resources_len == 0`; `error` must be null or point to writable memory
/// for one `BernBuffer`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_app_start(
    fingerprint: u64,
    resources: *const u8,
    resources_len: usize,
    callbacks: BernCallbacks,
    error: *mut BernBuffer,
) -> *mut BernApp {{
    // SAFETY: forwarded from the caller.
    unsafe {{
        bern_ffi::start_app(
            || {protocol}::Adapter(<{engine} as ::std::default::Default>::default()),
            spec(),
            fingerprint,
            resources,
            resources_len,
            callbacks,
            error,
        )
    }}
}}

fn spec() -> bern_ffi::AppSpec {{
    bern_ffi::AppSpec {{
        bundle_id: {bundle:?},
        ipc: {ipc},
        players: vec![{players}],
        resources: vec![{resources}],
        session: {session},
    }}
}}
"#,
        namespace = app.protocol.namespace,
        protocol = context.protocol_module,
        engine = context.engine_type,
        bundle = app.app.bundle_id,
        session = session_spec(app, WindowPresentation::Native),
        players = players_expr(app),
        resources = resources_expr(app),
    )
}

pub fn cli_rs(context: &BuildContext, app: &Application) -> String {
    format!(
        r#"//! Generated by Bern. Application CLI derived from the command catalog.

fn main() {{
    std::process::exit(bern_adapter_cli::run(
        {protocol}::descriptor(),
        {bundle:?},
        {name:?},
    ));
}}
"#,
        protocol = context.protocol_module,
        bundle = app.app.bundle_id,
        name = app.app.id.replace('_', "-"),
    )
}

