//! The generated application crate around `bern-gpui`: the interface, the
//! engine and the session runtime in one program, with the command line
//! and the MCP server beside it.

use bern_ir::Application;
use bern_target_api::BuildContext;
use bern_target_api::glue::{
    RELEASE_PROFILE, WindowPresentation, engine_expr, module_dependencies, path, players_expr,
    resources_expr, session_spec,
};
pub use bern_target_api::glue::{cli_rs, mcp_rs};

fn listens(context: &BuildContext) -> bool {
    context
        .target
        .channels
        .iter()
        .any(|channel| channel == "ipc")
}

/// The application crate's manifest; `platform` names the system it is
/// built for, whose GPUI platform crate `bern-gpui` takes.
pub fn cargo_toml(context: &BuildContext, app: &Application, platform: &str) -> String {
    let bern = |name: &str| context.framework.dependency(name);
    let executable = bern_target_api::glue::program(app);
    format!(
        r#"# Generated by Bern. Do not edit.
[package]
name = "bern-app-{executable}"
version = "{version}"
edition = "2024"
publish = false

[[bin]]
name = "{executable}-ui"
path = "src/main.rs"

[[bin]]
name = "{executable}"
path = "src/cli.rs"

[[bin]]
name = "{executable}-mcp"
path = "src/mcp.rs"

[dependencies]
bern-gpui = {{ {gpui}, features = ["{platform}"] }}
bern-ffi = {{ {ffi}{ipc} }}
bern-adapter-cli = {{ {cli_adapter} }}
bern-adapter-mcp = {{ {mcp_adapter} }}
{protocol} = {{ path = "{protocol_path}" }}
{engine} = {{ path = "{engine_path}" }}
{modules}
[workspace]

[profile.release]
panic = "unwind"
{release}"#,
        version = app.app.version,
        gpui = bern("bern-gpui"),
        ffi = bern("bern-ffi"),
        ipc = if listens(context) {
            ""
        } else {
            ", default-features = false"
        },
        cli_adapter = bern("bern-adapter-cli"),
        mcp_adapter = bern("bern-adapter-mcp"),
        protocol = context.protocol_package,
        protocol_path = path(&context.protocol_path),
        engine = context.engine_package,
        engine_path = path(&context.engine_path),
        modules = module_dependencies(context, true),
        release = RELEASE_PROFILE,
    )
}

pub fn main_rs(context: &BuildContext, app: &Application) -> String {
    format!(
        r#"//! Generated by Bern. Do not edit.
//!
//! The `{namespace}` application on GPUI: the frontend, the engine and the
//! UI session runtime in one process.
{windows_subsystem}
mod ui;

fn main() {{
    bern_gpui::run(
        ui::app(),
        Box::new(|callbacks, resources, error| {{
            // SAFETY: the resource path is valid for this call; `error`
            // points to writable memory for one buffer.
            unsafe {{
                bern_ffi::start_app(
                    || {engine},
                    spec(),
                    0x{fingerprint:016x},
                    resources.as_ptr(),
                    resources.len(),
                    callbacks,
                    error,
                )
            }}
        }}),
    );
}}

fn spec() -> bern_ffi::AppSpec {{
    bern_ffi::AppSpec {{
        bundle_id: {bundle:?},
        ipc: {ipc},
        players: vec![{players}],
        resources: vec![{resources}],
        session: {session},
    }}
}}
"#,
        namespace = app.protocol.namespace,
        // A window application on Windows opens no console of its own.
        windows_subsystem = if context.target.platform == "windows" {
            "#![windows_subsystem = \"windows\"]\n"
        } else {
            ""
        },
        engine = engine_expr(context),
        fingerprint = app.protocol.fingerprint(),
        bundle = app.app.bundle_id,
        ipc = listens(context),
        players = players_expr(app),
        resources = resources_expr(app),
        session = session_spec(app, WindowPresentation::Native),
    )
}
