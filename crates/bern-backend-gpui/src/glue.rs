//! The generated application crate around `bern-gpui`: the interface, the
//! engine and the session runtime in one program, with the command line
//! and the MCP server beside it.

use bern_ir::Application;
use bern_target_api::BuildContext;
use bern_target_api::glue::{
    WindowPresentation, engine_expr, module_dependencies, path, players_expr, resources_expr,
    session_spec,
};
pub use bern_target_api::glue::{cli_rs, mcp_rs};

fn listens(context: &BuildContext) -> bool {
    context
        .target
        .channels
        .iter()
        .any(|channel| channel == "ipc")
}

/// The application crate's manifest; `platform` names the system it is
/// built for, whose GPUI platform crate `bern-gpui` takes.
pub fn cargo_toml(context: &BuildContext, app: &Application, platform: &str) -> String {
    let bern = |name: &str| context.framework.dependency(name);
    let executable = bern_target_api::glue::program(app);
    format!(
        r#"# Generated by Bern. Do not edit.
[package]
name = "bern-app-{executable}"
version = "{version}"
edition = "2024"
publish = false

[[bin]]
name = "{executable}-ui"
path = "src/main.rs"

[[bin]]
name = "{executable}"
path = "src/cli.rs"

[[bin]]
name = "{executable}-mcp"
path = "src/mcp.rs"

{build}
[dependencies]
bern-gpui = {{ {gpui}, features = ["{platform}"] }}
bern-ffi = {{ {ffi}{ipc} }}
bern-adapter-cli = {{ {cli_adapter} }}
bern-adapter-mcp = {{ {mcp_adapter} }}
{protocol} = {{ path = "{protocol_path}" }}
{engine} = {{ path = "{engine_path}" }}
{modules}
[workspace]

{profiles}"#,
        version = app.app.version,
        gpui = bern("bern-gpui"),
        ffi = bern("bern-ffi"),
        ipc = if listens(context) {
            ""
        } else {
            ", default-features = false"
        },
        cli_adapter = bern("bern-adapter-cli"),
        mcp_adapter = bern("bern-adapter-mcp"),
        protocol = context.protocol_package,
        protocol_path = path(&context.protocol_path),
        engine = context.engine_package,
        engine_path = path(&context.engine_path),
        modules = module_dependencies(context, true),
        profiles = bern_target_api::glue::profiles(context, "panic = \"unwind\"\n"),
        // Windows links the icon and the version into the programs.
        build = if platform == "windows" {
            "\n[build-dependencies]\nembed-resource = \"3\"\n"
        } else {
            ""
        },
    )
}

/// The build script of the application crate on Windows: it compiles the
/// resource script into every program.
pub const BUILD_RS: &str = r#"// Generated by Bern. Do not edit.
fn main() {
    embed_resource::compile("app.rc", embed_resource::NONE)
        .manifest_optional()
        .expect("the resource script compiles");
}
"#;

/// The resource script: the icon as resource 1, then the version with the
/// application's name in its default language.
pub fn resource_script(app: &Application) -> String {
    let name = app
        .app
        .name
        .get(&app.languages.default)
        .unwrap_or(&app.app.id);
    let name: String = name
        .chars()
        .filter(|c| !c.is_control())
        .flat_map(|c| match c {
            '"' => vec!['"', '"'],
            '\\' => vec!['\\', '\\'],
            c => vec![c],
        })
        .collect();
    let [major, minor, patch] = version_parts(&app.app.version);
    format!(
        r#"// Generated by Bern. Do not edit.
#pragma code_page(65001)
#include <winver.h>

1 ICON "app.ico"

1 VERSIONINFO
FILEVERSION {major},{minor},{patch},0
PRODUCTVERSION {major},{minor},{patch},0
FILEOS VOS_NT_WINDOWS32
FILETYPE VFT_APP
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904B0"
    BEGIN
      VALUE "FileDescription", "{name}"
      VALUE "ProductName", "{name}"
      VALUE "FileVersion", "{major}.{minor}.{patch}.0"
      VALUE "ProductVersion", "{version}"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
"#,
        version = app.app.version,
    )
}

/// The first three numbers of a version, as Windows' version resource
/// takes them; 1.0.0 when there are none.
fn version_parts(version: &str) -> [u16; 3] {
    let mut parts = [0u16; 3];
    let mut any = false;
    for (slot, number) in parts.iter_mut().zip(
        version
            .split(['.', '-', '+'])
            .take(3)
            .map_while(|part| part.parse::<u16>().ok()),
    ) {
        *slot = number;
        any = true;
    }
    if any { parts } else { [1, 0, 0] }
}

pub fn main_rs(context: &BuildContext, app: &Application) -> String {
    format!(
        r#"//! Generated by Bern. Do not edit.
//!
//! The `{namespace}` application on GPUI: the frontend, the engine and the
//! UI session runtime in one process.
{windows_subsystem}
mod ui;

fn main() {{
    bern_gpui::run(
        ui::app(),
        Box::new(|callbacks, resources, error| {{
            // SAFETY: the resource path is valid for this call; `error`
            // points to writable memory for one buffer.
            unsafe {{
                bern_ffi::start_app(
                    || {engine},
                    spec(),
                    0x{fingerprint:016x},
                    resources.as_ptr(),
                    resources.len(),
                    callbacks,
                    error,
                )
            }}
        }}),
    );
}}

fn spec() -> bern_ffi::AppSpec {{
    bern_ffi::AppSpec {{
        bundle_id: {bundle:?},
        ipc: {ipc},
        players: vec![{players}],
        resources: vec![{resources}],
        session: {session},
    }}
}}
"#,
        namespace = app.protocol.namespace,
        // A window application on Windows opens no console of its own.
        windows_subsystem = if context.target.platform == "windows" {
            "#![windows_subsystem = \"windows\"]\n"
        } else {
            ""
        },
        engine = engine_expr(context),
        fingerprint = app.protocol.fingerprint(),
        bundle = app.app.bundle_id,
        ipc = listens(context),
        players = players_expr(app),
        resources = resources_expr(app),
        session = session_spec(app, WindowPresentation::Native),
    )
}
