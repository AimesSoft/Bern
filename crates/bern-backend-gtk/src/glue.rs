//! The generated application crate: the GTK frontend with the engine and
//! the session runtime in one executable, and the application CLI and MCP
//! server from the same command catalog.

use bern_ir::Application;
use bern_target_api::BuildContext;
use bern_target_api::glue::{
    WindowPresentation, descriptor_expr, engine_expr, module_dependencies, players_expr,
    resources_expr, session_spec,
};
use std::path::{Path, PathBuf};

fn path(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}

pub fn cargo_toml(context: &BuildContext, app: &Application) -> String {
    let bern = |name: &str| context.framework.dependency(name);
    let executable = app.app.id.replace('_', "-");
    format!(
        r#"# Generated by Bern. Do not edit.
[package]
name = "bern-app-{executable}"
version = "{version}"
edition = "2024"
publish = false

[[bin]]
name = "{executable}-ui"
path = "src/main.rs"

[[bin]]
name = "{executable}"
path = "src/cli.rs"

[[bin]]
name = "{executable}-mcp"
path = "src/mcp.rs"

[dependencies]
bern-gtk = {{ {gtk}{svg} }}
bern-ffi = {{ {ffi}{ipc} }}
bern-adapter-cli = {{ {cli_adapter} }}
bern-adapter-mcp = {{ {mcp_adapter} }}
{protocol} = {{ path = "{protocol_path}" }}
{engine} = {{ path = "{engine_path}" }}
{modules}
[workspace]

[profile.release]
panic = "unwind"
"#,
        version = app.app.version,
        gtk = bern("bern-gtk"),
        svg = if bern_target_api::svg::used(app) {
            ", features = [\"svg\"]"
        } else {
            ""
        },
        ffi = bern("bern-ffi"),
        ipc = if context
            .target
            .channels
            .iter()
            .any(|channel| channel == "ipc")
        {
            ""
        } else {
            ", default-features = false"
        },
        cli_adapter = bern("bern-adapter-cli"),
        mcp_adapter = bern("bern-adapter-mcp"),
        protocol = context.protocol_package,
        protocol_path = path(&context.protocol_path),
        engine = context.engine_package,
        engine_path = path(&context.engine_path),
        modules = module_dependencies(context, true),
    )
}

pub fn main_rs(context: &BuildContext, app: &Application) -> String {
    let ipc = context
        .target
        .channels
        .iter()
        .any(|channel| channel == "ipc");
    format!(
        r#"//! Generated by Bern. Do not edit.
//!
//! The `{namespace}` application on GTK 4: the frontend, the engine and the
//! UI session runtime in one process.

mod ui;

fn main() -> bern_gtk::glib::ExitCode {{
    bern_gtk::run(
        ui::app(),
        Box::new(|callbacks, resources, error| {{
            // SAFETY: the resource path is valid for this call; `error`
            // points to writable memory for one buffer.
            unsafe {{
                bern_ffi::start_app(
                    || {engine},
                    spec(),
                    0x{fingerprint:016x},
                    resources.as_ptr(),
                    resources.len(),
                    callbacks,
                    error,
                )
            }}
        }}),
    )
}}

fn spec() -> bern_ffi::AppSpec {{
    bern_ffi::AppSpec {{
        bundle_id: {bundle:?},
        ipc: {ipc},
        players: vec![{players}],
        resources: vec![{resources}],
        session: {session},
    }}
}}
"#,
        namespace = app.protocol.namespace,
        engine = engine_expr(context),
        fingerprint = app.protocol.fingerprint(),
        bundle = app.app.bundle_id,
        session = session_spec(app, WindowPresentation::Native),
        players = players_expr(app),
        resources = resources_expr(app),
    )
}

pub fn cli_rs(context: &BuildContext, app: &Application) -> String {
    format!(
        r#"//! Generated by Bern. Application CLI derived from the command catalog.

fn main() {{
    std::process::exit(bern_adapter_cli::run(
        {descriptor},
        {bundle:?},
        {name:?},
    ));
}}
"#,
        descriptor = descriptor_expr(context),
        bundle = app.app.bundle_id,
        name = app.app.id.replace('_', "-"),
    )
}

pub fn mcp_rs(context: &BuildContext, app: &Application) -> String {
    format!(
        r#"//! Generated by Bern. MCP server derived from the command catalog.

fn main() {{
    std::process::exit(bern_adapter_mcp::run(
        {descriptor},
        {bundle:?},
        {name:?},
        {version:?},
    ));
}}
"#,
        descriptor = descriptor_expr(context),
        bundle = app.app.bundle_id,
        name = app.app.id.replace('_', "-"),
        version = app.app.version,
    )
}

/// `DEBIAN/control` of the Debian package: GTK and libadwaita as the
/// target needs them, and the GStreamer plugins when the app plays media.
pub fn debian_control(
    app: &Application,
    package: &str,
    architecture: &str,
    installed_kb: u64,
) -> String {
    let name = app
        .app
        .name
        .get(&app.languages.default)
        .unwrap_or(&app.app.id)
        .to_string();
    let maintainer = app
        .app
        .publisher
        .clone()
        .unwrap_or_else(|| format!("{name} maintainers"));
    let mut depends = vec!["libgtk-4-1 (>= 4.14)", "libadwaita-1-0 (>= 1.5)"];
    let mut extra = String::new();
    if bern_target_api::svg::used(app) {
        depends.push("libwebkitgtk-6.0-4");
    }
    if app.uses_media() {
        depends.extend(["libgtk-4-media-gstreamer", "gstreamer1.0-plugins-good"]);
        extra.push_str("Recommends: gstreamer1.0-libav\n");
    }
    format!(
        "Package: {package}\nVersion: {version}\nArchitecture: {architecture}\nMaintainer: {maintainer}\nInstalled-Size: {installed_kb}\nDepends: {depends}\n{extra}Section: misc\nPriority: optional\nDescription: {name}\n Built with Bern.\n",
        version = app.app.version,
        depends = depends.join(", "),
    )
}

/// A file the Debian package carries besides the application, relative to
/// the package root.
pub struct PackageFile {
    pub path: PathBuf,
    pub contents: String,
    /// Maintainer scripts, which dpkg runs as programs.
    pub program: bool,
}

/// What the Debian package adds for an application that shows `Svg`.
/// WebKitGTK sandboxes its web process with bubblewrap, which needs a user
/// namespace, and stops the whole application when the sandbox fails;
/// Ubuntu 24.04 and later let only programs whose AppArmor profile grants
/// `userns` create one. The package installs a profile for `executable`
/// as a configuration file and loads it where AppArmor is enabled. Like
/// the profiles Ubuntu ships for its own WebKitGTK applications, it
/// confines nothing else. Nothing without `Svg`.
pub fn apparmor_files(app: &Application, executable: &Path) -> Vec<PackageFile> {
    if !bern_target_api::svg::used(app) {
        return Vec::new();
    }
    let name = &app.app.bundle_id;
    let profile = format!("/etc/apparmor.d/{name}");
    vec![
        PackageFile {
            path: PathBuf::from(&profile[1..]),
            contents: format!(
                r#"# Generated by Bern. WebKitGTK sandboxes the web content of `Svg` with
# bubblewrap, which needs a user namespace; this profile allows that and
# confines nothing else.

abi <abi/4.0>,
include <tunables/global>

profile {name} {executable} flags=(unconfined) {{
  userns,

  # Site-specific additions and overrides. See local/README for details.
  include if exists <local/{name}>
}}
"#,
                executable = path(executable),
            ),
            program: false,
        },
        PackageFile {
            path: PathBuf::from("DEBIAN/conffiles"),
            contents: format!("{profile}\n"),
            program: false,
        },
        PackageFile {
            path: PathBuf::from("DEBIAN/postinst"),
            contents: format!(
                r#"#!/bin/sh
# Generated by Bern.
set -e

# Load the AppArmor profile that lets WebKitGTK sandbox its web content.
if [ "$1" = "configure" ] && aa-enabled --quiet 2>/dev/null; then
    apparmor_parser -r -T -W {profile} || true
fi
"#
            ),
            program: true,
        },
        PackageFile {
            path: PathBuf::from("DEBIAN/postrm"),
            contents: format!(
                r#"#!/bin/sh
# Generated by Bern.
set -e

# dpkg deletes the profile on purge; delete its compiled copy too.
if [ "$1" = "purge" ]; then
    rm -f /var/cache/apparmor/*/{name}
fi
"#
            ),
            program: true,
        },
    ]
}

/// A freedesktop desktop entry: the application's name in every declared
/// language, so the desktop shows it for the running windows. Install it
/// into `~/.local/share/applications` to launch the build from the
/// desktop.
pub fn desktop_entry(app: &Application, executable: &Path, icon: &Path) -> String {
    let mut entry = String::from("[Desktop Entry]\nType=Application\n");
    let default = app
        .app
        .name
        .get(&app.languages.default)
        .unwrap_or(&app.app.id);
    entry.push_str(&format!("Name={default}\n"));
    for language in &app.languages.supported {
        let Some(name) = app.app.name.get(language) else {
            continue;
        };
        // Desktop entries name locales as `lang_COUNTRY`.
        let locale = match language.as_str() {
            "zh-Hans" => "zh_CN".to_string(),
            "zh-Hant" => "zh_TW".to_string(),
            other => other.replace('-', "_"),
        };
        entry.push_str(&format!("Name[{locale}]={name}\n"));
    }
    let types = opened_types(app);
    if types.is_empty() {
        entry.push_str(&format!("Exec={}\n", path(executable)));
    } else {
        // A drop area with `opens: true` takes files the system hands the
        // application: it is offered as a way to open them, not made the
        // default.
        entry.push_str(&format!("Exec={} %U\n", path(executable)));
        entry.push_str(&format!("MimeType={};\n", types.join(";")));
    }
    entry.push_str(&format!("Icon={}\n", path(icon)));
    entry.push_str("Terminal=false\nCategories=Utility;\n");
    entry.push_str("StartupNotify=true\nDBusActivatable=false\n");
    entry
}

/// MIME types of the file kinds `Drop(opens: true)` areas take. Extensions
/// without a known type and `any` register nothing.
fn opened_types(app: &Application) -> Vec<&'static str> {
    const KINDS: &[(&str, &[&str])] = &[
        (
            "video",
            &[
                "video/mp4",
                "video/x-matroska",
                "video/webm",
                "video/quicktime",
                "video/x-msvideo",
                "video/x-flv",
                "video/mpeg",
                "video/ogg",
                "video/3gpp",
                "video/mp2t",
                "video/x-ms-wmv",
            ],
        ),
        (
            "audio",
            &[
                "audio/mpeg",
                "audio/mp4",
                "audio/aac",
                "audio/flac",
                "audio/ogg",
                "audio/x-wav",
                "audio/x-aiff",
                "audio/x-ms-wma",
                "audio/opus",
            ],
        ),
        (
            "picture",
            &[
                "image/png",
                "image/jpeg",
                "image/webp",
                "image/gif",
                "image/bmp",
                "image/tiff",
                "image/heif",
                "image/avif",
                "image/jxl",
            ],
        ),
    ];
    let mut types = Vec::new();
    let mut visit = |node: &bern_ir::Node| {
        if let bern_ir::Node::Element(element) = node
            && element.kind == "Drop"
            && element.keyword("opens") == Some("true")
        {
            for word in element
                .keyword("files")
                .unwrap_or("any")
                .split(|c: char| c.is_whitespace() || c == ',')
            {
                if let Some((_, mimes)) = KINDS.iter().find(|(kind, _)| *kind == word) {
                    for mime in *mimes {
                        if !types.contains(mime) {
                            types.push(*mime);
                        }
                    }
                }
            }
        }
    };
    for component in &app.components {
        component.body.walk(&mut visit);
    }
    types
}

#[cfg(test)]
mod tests {
    use super::*;

    fn app(example: &str) -> Application {
        let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../examples")
            .join(example)
            .join("Bern.toml");
        let config = bern_compiler::config::load(&manifest).unwrap();
        bern_compiler::compile(&config).unwrap().app
    }

    #[test]
    fn debian_packages_need_gtk_and_gstreamer_only_with_media() {
        let hello = debian_control(&app("hello"), "hello", "arm64", 4321);
        for expected in [
            "Package: hello\n",
            "Architecture: arm64\n",
            "Installed-Size: 4321\n",
            "Depends: libgtk-4-1 (>= 4.14), libadwaita-1-0 (>= 1.5)\n",
            "Maintainer: Hello maintainers\n",
        ] {
            assert!(hello.contains(expected), "{hello}");
        }
        assert!(!hello.contains("gstreamer"));
        let showcase = debian_control(&app("showcase"), "showcase", "amd64", 1);
        assert!(
            showcase.contains("libgtk-4-media-gstreamer, gstreamer1.0-plugins-good")
                && showcase.contains("Recommends: gstreamer1.0-libav"),
            "{showcase}"
        );
        // The gallery's drop area opens videos the system hands it.
        let gallery = desktop_entry(
            &app("gallery"),
            Path::new("/opt/gallery/gallery"),
            Path::new("dev.bern.gallery"),
        );
        assert!(
            gallery.contains("Exec=/opt/gallery/gallery %U\n"),
            "{gallery}"
        );
        assert!(
            gallery.contains("MimeType=video/mp4;video/x-matroska;"),
            "{gallery}"
        );
        assert!(
            !desktop_entry(&app("hello"), Path::new("/x"), Path::new("y")).contains("MimeType")
        );
        // The description's second line is indented, as Debian requires.
        assert!(
            showcase.contains("\nDescription: ") && showcase.ends_with("\n Built with Bern.\n")
        );
    }

    #[test]
    fn only_packages_with_svg_carry_an_apparmor_profile() {
        for example in ["hello", "showcase", "gallery", "planner"] {
            assert!(
                apparmor_files(&app(example), Path::new("/opt/x/x")).is_empty(),
                "{example}"
            );
        }
        let svg = app("svg-animation");
        let files = apparmor_files(&svg, Path::new("/opt/dev.bern.svgdemo/svg-demo"));
        let file = |name: &str| {
            files
                .iter()
                .find(|file| file.path == Path::new(name))
                .unwrap_or_else(|| panic!("{name}"))
        };
        let profile = file("etc/apparmor.d/dev.bern.svgdemo");
        for expected in [
            "abi <abi/4.0>,\n",
            "\nprofile dev.bern.svgdemo /opt/dev.bern.svgdemo/svg-demo flags=(unconfined) {\n  userns,\n",
            "include if exists <local/dev.bern.svgdemo>\n}\n",
        ] {
            assert!(profile.contents.contains(expected), "{}", profile.contents);
        }
        assert!(!profile.program);
        // A file in /etc stays the administrator's: dpkg keeps their edits.
        assert_eq!(
            file("DEBIAN/conffiles").contents,
            "/etc/apparmor.d/dev.bern.svgdemo\n"
        );
        // The profile is loaded at once only where AppArmor runs; a failed
        // load does not fail the installation.
        let postinst = file("DEBIAN/postinst");
        assert!(postinst.program && postinst.contents.starts_with("#!/bin/sh\n"));
        assert!(
            postinst.contents.contains(
                "if [ \"$1\" = \"configure\" ] && aa-enabled --quiet 2>/dev/null; then\n    apparmor_parser -r -T -W /etc/apparmor.d/dev.bern.svgdemo || true\n"
            ),
            "{}",
            postinst.contents
        );
        let postrm = file("DEBIAN/postrm");
        assert!(
            postrm.program
                && postrm
                    .contents
                    .contains("rm -f /var/cache/apparmor/*/dev.bern.svgdemo\n")
        );
        assert_eq!(files.len(), 4);
    }
}
