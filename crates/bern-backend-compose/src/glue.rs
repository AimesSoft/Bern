//! Generated Rust glue crate: links the engine, the session runtime and the
//! JNI bridge into `libbern_app.so`, which the Kotlin frontend loads.

use bern_ir::Application;
use bern_target_api::BuildContext;
use bern_target_api::glue::{
    WindowPresentation, engine_expr, module_dependencies, path, players_expr, resources_expr,
    session_spec,
};
pub use bern_target_api::glue::{cli_rs, mcp_rs};

pub fn cargo_toml(context: &BuildContext, app: &Application) -> String {
    format!(
        r#"# Generated by Bern. Do not edit.
[package]
name = "bern-glue-{id}"
version = "{version}"
edition = "2024"
publish = false

[lib]
name = "bern_app"
crate-type = ["cdylib"]
path = "src/lib.rs"

[dependencies]
bern-ffi = {{ {ffi}, default-features = false{ipc} }}
{protocol} = {{ path = "{protocol_path}" }}
{engine} = {{ path = "{engine_path}" }}
{modules}
[workspace]

[profile.release]
panic = "unwind"
{release}"#,
        id = app.app.id.replace('_', "-"),
        version = app.app.version,
        ffi = context.framework.dependency("bern-ffi"),
        ipc = if ipc(context) {
            ", features = [\"ipc\"]"
        } else {
            ""
        },
        protocol = context.protocol_package,
        protocol_path = path(&context.protocol_path),
        engine = context.engine_package,
        engine_path = path(&context.engine_path),
        modules = module_dependencies(context, true),
        release = bern_target_api::glue::RELEASE_PROFILE,
    )
}

/// Whether the target assembles the control channel.
pub fn ipc(context: &BuildContext) -> bool {
    context
        .target
        .channels
        .iter()
        .any(|channel| channel == "ipc")
}

/// The engine library. Every window of a phone app is virtual: the
/// primary fills the screen and the others open over it. The control
/// channel listens on an abstract socket, which `adb forward` reaches.
pub fn lib_rs(context: &BuildContext, app: &Application) -> String {
    format!(
        r#"//! Generated by Bern. Do not edit.
//!
//! Links the `{namespace}` engine, the UI session runtime and the JNI
//! bridge into the library the Kotlin frontend loads in-process.

use bern_ffi::android::jni_sys::{{JNIEnv, jbyteArray, jlong, jobject}};

/// `BernNative.start`: start the engine for the frontend generated from
/// the same catalog. `resources` is the UTF-8 path of the directory
/// holding the declared resources.
///
/// # Safety
/// Called by the Java VM with the arguments of the Kotlin declaration.
#[unsafe(no_mangle)]
pub unsafe extern "system" fn Java_dev_bern_runtime_BernNative_start(
    env: *mut JNIEnv,
    _this: jobject,
    fingerprint: jlong,
    resources: jbyteArray,
    bridge: jobject,
) -> jbyteArray {{
    // SAFETY: forwarded from the Java VM.
    unsafe {{
        bern_ffi::android::start(env, || {engine}, spec(), fingerprint, resources, bridge)
    }}
}}

fn spec() -> bern_ffi::AppSpec {{
    bern_ffi::AppSpec {{
        bundle_id: {bundle:?},
        ipc: {ipc},
        players: vec![{players}],
        resources: vec![{resources}],
        session: {session},
    }}
}}
"#,
        namespace = app.protocol.namespace,
        engine = engine_expr(context),
        bundle = app.app.bundle_id,
        players = players_expr(app),
        resources = resources_expr(app),
        session = session_spec(app, WindowPresentation::Virtual),
        ipc = ipc(context),
    )
}

/// The application's command line and MCP server for the developer's
/// computer: they reach the app on the device through `adb forward`.
pub fn tools_cargo_toml(context: &BuildContext, app: &Application) -> String {
    format!(
        r#"# Generated by Bern. Do not edit.
[package]
name = "bern-tools-{id}"
version = "{version}"
edition = "2024"
publish = false

[[bin]]
name = "{cli}"
path = "src/cli.rs"

[[bin]]
name = "{cli}-mcp"
path = "src/mcp.rs"

[dependencies]
bern-adapter-cli = {{ {cli_adapter} }}
bern-adapter-mcp = {{ {mcp_adapter} }}
{protocol} = {{ path = "{protocol_path}" }}
{modules}
[workspace]

[profile.release]
{release}"#,
        id = app.app.id.replace('_', "-"),
        version = app.app.version,
        cli = app.app.id.replace('_', "-"),
        cli_adapter = context.framework.dependency("bern-adapter-cli"),
        mcp_adapter = context.framework.dependency("bern-adapter-mcp"),
        protocol = context.protocol_package,
        protocol_path = path(&context.protocol_path),
        modules = module_dependencies(context, false),
        release = bern_target_api::glue::RELEASE_PROFILE,
    )
}
