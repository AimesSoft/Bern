/// The app's baseline profile, which the Android Gradle plugin compiles
/// into the APK and the bundle: the Bern runtime and the generated
/// interface are compiled ahead of time when a store installs the app, or
/// `bern run` with the profile beside the APK; elsewhere at the system's
/// next background compilation. Without it they run in the interpreter
/// and the JIT after each install, and the long frame of a page change
/// takes 1.3 to 2.5 times as long (Android Compose implementation record,
/// 2026-10-21).
pub fn baseline_profile(app: &Application) -> String {
    let generated = package(&app.app.bundle_id).replace('.', "/");
    format!(
        "# Generated by Bern. Do not edit.
Ldev/bern/runtime/**;
HSPLdev/bern/runtime/**->**(**)**
L{generated}/**;
HSPL{generated}/**->**(**)**
"
    )
}

/// `1.2.3` as 10203; parts beyond the third are ignored.
pub fn version_code(version: &str) -> u32 {
    let parts: Vec<u32> = version
        .split(['.', '-', '+'])
        .take(3)
        .map(|part| part.parse().unwrap_or(0))
        .collect();
    let part = |index: usize| parts.get(index).copied().unwrap_or(0).min(99);
    (part(0) * 10000 + part(1) * 100 + part(2)).max(1)
}

pub fn app_build(app: &Application) -> String {
    let namespace = package(&app.app.bundle_id);
    format!(
        r#"// Generated by Bern. Do not edit.
// The Android Gradle plugin compiles Kotlin itself; the Compose compiler
// plugin brings the Kotlin version.
plugins {{
    id("com.android.application")
    id("org.jetbrains.kotlin.plugin.compose")
}}

android {{
    namespace = "{namespace}"
    compileSdk = {COMPILE_SDK}

    defaultConfig {{
        applicationId = "{bundle}"
        minSdk = {MINIMUM_SDK}
        targetSdk = {TARGET_SDK}
        versionCode = {code}
        versionName = "{version}"
        ndk {{
            abiFilters += "arm64-v8a"
        }}
    }}

    signingConfigs {{
        // The release key from the environment of `bern package`; the
        // passwords never go into a file.
        val keystore = System.getenv("BERN_ANDROID_KEYSTORE")
        if (keystore != null) {{
            create("release") {{
                storeFile = file(keystore)
                storePassword = System.getenv("BERN_ANDROID_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("BERN_ANDROID_KEY_ALIAS")
                keyPassword = System.getenv("BERN_ANDROID_KEY_PASSWORD")
                    ?: System.getenv("BERN_ANDROID_KEYSTORE_PASSWORD")
            }}
        }}
    }}

    buildTypes {{
        release {{
            isMinifyEnabled = false
            // Without a release key, the debug key: installable for
            // testing, not for a store.
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }}
    }}

    compileOptions {{
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }}

    buildFeatures {{
        compose = true
    }}
}}

dependencies {{
    implementation(platform("androidx.compose:compose-bom:{COMPOSE_BOM}"))
    implementation("androidx.activity:activity-compose:{ACTIVITY_COMPOSE}")
    implementation("androidx.compose.foundation:foundation")
    implementation("androidx.compose.material3:material3")
    implementation("androidx.compose.material:material-icons-core")
    implementation("androidx.compose.ui:ui")
    implementation("androidx.media3:media3-exoplayer:{MEDIA3}")
    implementation("androidx.media3:media3-ui:{MEDIA3}")
}}
"#,
        bundle = app.app.bundle_id,
        code = version_code(&app.app.version),
        version = app.app.version,
    )
}

/// The kinds of file the application opens: those of every `Drop` with
/// `opens: true`, in components and in the content written directly in a
/// window.
fn opened_kinds(app: &bern_ir::Application) -> Vec<String> {
    let mut kinds = std::collections::BTreeSet::new();
    app.walk(&mut |node, _| {
        if let bern_ir::Node::Element(element) = node
            && element.kind == "Drop"
            && element.keyword("opens") == Some("true")
        {
            for word in element.keyword("files").unwrap_or("any").split(' ') {
                kinds.insert(word.to_string());
            }
        }
    });
    kinds.into_iter().collect()
}

/// Whether the application reads pictures or media from the network,
/// anywhere in its components or windows.
fn uses_network(app: &bern_ir::Application) -> bool {
    let mut uses = app.uses_media();
    app.walk(&mut |node, _| {
        if let bern_ir::Node::Element(element) = node
            && ((element.kind == "Image" && element.expr("source").is_some())
                || element.expr("fill_from").is_some())
        {
            uses = true;
        }
    });
    uses
}

/// The media type files with `ext` usually carry.
fn extension_type(ext: &str) -> Option<&'static str> {
    Some(match ext {
        "srt" => "application/x-subrip",
        "ass" | "ssa" => "text/x-ssa",
        "vtt" => "text/vtt",
        "xml" => "text/xml",
        "json" => "application/json",
        "txt" => "text/plain",
        "pdf" => "application/pdf",
        "mkv" => "video/x-matroska",
        "webm" => "video/webm",
        "mp4" | "m4v" => "video/mp4",
        "flac" => "audio/flac",
        "mp3" => "audio/mpeg",
        _ => return None,
    })
}

/// The application manifest: one activity that handles its own
/// configuration changes, so turning the phone or resizing keeps the
/// windows and their drafts; `round_icon` when the launcher icon has a
/// round form, `@mipmap/ic_launcher_round`.
pub fn manifest(app: &bern_ir::Application, round_icon: bool) -> String {
    let round = if round_icon {
        "\n        android:roundIcon=\"@mipmap/ic_launcher_round\""
    } else {
        ""
    };
    let internet = if uses_network(app) {
        "\n    <uses-permission android:name=\"android.permission.INTERNET\" />"
    } else {
        ""
    };
    // Other apps offer this one for the kinds it opens ("Open with"); a
    // file opened while it runs arrives in the running activity.
    let kinds = opened_kinds(app);
    let (launch_mode, opens) = if kinds.is_empty() {
        ("", String::new())
    } else {
        let mut types = std::collections::BTreeSet::new();
        for kind in &kinds {
            match kind.strip_prefix('.') {
                // Files other apps hand over carry a media type; an
                // extension without a known one is not offered.
                Some(ext) => {
                    if let Some(mime) = extension_type(ext) {
                        types.insert(mime.to_string());
                    }
                }
                None => {
                    types.insert(
                        match kind.as_str() {
                            "video" => "video/*",
                            "audio" => "audio/*",
                            "picture" => "image/*",
                            _ => "*/*",
                        }
                        .to_string(),
                    );
                }
            }
        }
        let data: String = types
            .iter()
            .map(|mime| format!("\n                <data android:mimeType=\"{mime}\" />"))
            .collect();
        (
            "\n            android:launchMode=\"singleTask\"",
            format!(
                r#"
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <data android:scheme="content" />
                <data android:scheme="file" />{data}
            </intent-filter>
            <intent-filter>
                <action android:name="android.intent.action.SEND" />
                <category android:name="android.intent.category.DEFAULT" />{data}
            </intent-filter>"#
            ),
        )
    };
    format!(
        r#"<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Bern. Do not edit. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android">{internet}
    <application
        android:label="@string/app_name"
        android:icon="@mipmap/ic_launcher"{round}
        android:theme="@style/BernTheme"
        android:supportsRtl="true"
        android:enableOnBackInvokedCallback="true">
        <activity
            android:name=".MainActivity"
            android:exported="true"
            android:configChanges="orientation|screenSize|screenLayout|smallestScreenSize|keyboard|keyboardHidden|navigation|uiMode|density|fontScale|layoutDirection|locale"{launch_mode}
            android:windowSoftInputMode="adjustResize">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>{opens}
        </activity>
    </application>
</manifest>
"#
    )
}

/// The window theme until Compose draws: light, and dark at night.
pub fn theme(night: bool) -> String {
    let parent = if night {
        "android:Theme.Material.NoActionBar"
    } else {
        "android:Theme.Material.Light.NoActionBar"
    };
    format!(
        r#"<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Bern. Do not edit. -->
<resources>
    <style name="BernTheme" parent="{parent}" />
</resources>
"#
    )
}

fn xml_text(value: &str) -> String {
    let mut out = String::new();
    for c in value.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("\\\""),
            '\'' => out.push_str("\\'"),
            '\\' => out.push_str("\\\\"),
            '@' if out.is_empty() => out.push_str("\\@"),
            '?' if out.is_empty() => out.push_str("\\?"),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out
}

/// The resource directory of a language: `values` for the default one,
/// `values-b+zh+Hans` and the like for the others.
pub fn values_dir(language: &str, default: &str) -> String {
    if language == default {
        "values".into()
    } else {
        format!("values-b+{}", language.replace('-', "+"))
    }
}

/// `strings.xml` per resource directory: the application's name, which
/// the launcher shows.
pub fn app_names(app: &Application) -> Vec<(String, String)> {
    let default = &app.languages.default;
    app.languages
        .supported
        .iter()
        .map(|language| {
            let name = translation(&app.app.name, language, default);
            (
                values_dir(language, default),
                format!(
                    "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by Bern. Do not edit. -->\n<resources>\n    <string name=\"app_name\">{}</string>\n</resources>\n",
                    xml_text(name)
                ),
            )
        })
        .collect()
}

/// The string tables the runtime reads, as JSON per language: declared
/// texts with Java format specifiers, and the runtime's own strings.
pub fn text_tables(app: &Application) -> BTreeMap<String, String> {
    let mut tables = BTreeMap::new();
    for language in &app.languages.supported {
        let mut table = serde_json::Map::new();
        for text in &app.texts {
            // A text with arguments keeps Bern's format, which the runtime
            // writes out; one without is shown as it is.
            let value = translation(text, language, &app.languages.default);
            let value = if text.params.is_empty() {
                positional(value, &[], |position| format!("%{position}$s"))
            } else {
                value.to_string()
            };
            table.insert(text.key.clone(), value.into());
        }
        for (key, translations) in bern_protocol::format::date_names() {
            let value = translations
                .iter()
                .find(|(candidate, _)| candidate == language)
                .or_else(|| {
                    translations
                        .iter()
                        .find(|(candidate, _)| *candidate == "en")
                })
                .map(|(_, value)| value.clone())
                .unwrap_or_default();
            table.insert(key, value.into());
        }
        for (key, translations) in FRAMEWORK_TEXTS {
            let value = framework(translations, language)
                .replace('%', "%%")
                .replace("%%@", "%s");
            table.insert((*key).into(), value.into());
        }
        tables.insert(
            language.clone(),
            serde_json::to_string_pretty(&table).expect("table"),
        );
    }
    tables
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn versions_and_directories() {
        assert_eq!(version_code("0.1.0"), 100);
        assert_eq!(version_code("1.2.3"), 10203);
        assert_eq!(version_code("0.0.0"), 1);
        assert_eq!(values_dir("en", "en"), "values");
        assert_eq!(values_dir("zh-Hans", "en"), "values-b+zh+Hans");
        assert_eq!(xml_text("A & B's"), "A &amp; B\\'s");
    }

    fn app(example: &str) -> Application {
        let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../examples")
            .join(example)
            .join("Bern.toml");
        let config = bern_compiler::config::load(&manifest).unwrap();
        bern_compiler::compile(&config).unwrap().app
    }

    /// The hello world with the first element of `example` that `pick`
    /// accepts as its window's content, outside any component.
    fn in_window(example: &str, pick: impl Fn(&bern_ir::Element) -> bool) -> Application {
        let source = app(example);
        let mut found = None;
        source.walk(&mut |node, _| {
            if let bern_ir::Node::Element(element) = node
                && found.is_none()
                && pick(element)
            {
                found = Some(node.clone());
            }
        });
        let mut hello = app("hello");
        hello.windows.windows[0].content = found.unwrap();
        hello
    }

    #[test]
    fn drop_areas_placed_directly_in_a_window_open_files() {
        let hello = manifest(&app("hello"), false);
        assert!(!hello.contains("android.intent.action.VIEW"), "{hello}");
        let drop = manifest(
            &in_window("gallery", |element| element.kind == "Drop"),
            false,
        );
        assert!(drop.contains("android:launchMode=\"singleTask\""), "{drop}");
        assert!(
            drop.contains("<data android:mimeType=\"video/*\" />"),
            "{drop}"
        );
    }

    #[test]
    fn pictures_placed_directly_in_a_window_read_the_network() {
        const INTERNET: &str = "android.permission.INTERNET";
        let hello = manifest(&app("hello"), false);
        assert!(!hello.contains(INTERNET), "{hello}");
        let image = in_window("gallery", |element| {
            element.kind == "Image" && element.expr("source").is_some()
        });
        let image = manifest(&image, false);
        assert!(image.contains(INTERNET), "{image}");
        let shape = in_window("gallery", |element| element.expr("fill_from").is_some());
        let shape = manifest(&shape, false);
        assert!(shape.contains(INTERNET), "{shape}");
    }
}
