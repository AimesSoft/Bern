/// Versions the generated project builds with; the build downloads them
/// from Google's and Maven Central's repositories the first time.
pub const ANDROID_GRADLE_PLUGIN: &str = "9.3.3";
pub const KOTLIN: &str = "2.4.21";
pub const COMPOSE_BOM: &str = "2026.09.00";
pub const ACTIVITY_COMPOSE: &str = "1.13.0";
pub const COMPILE_SDK: u32 = 37;
pub const TARGET_SDK: u32 = 36;
/// Android 8.0, chosen in the design discussion: Compose and the adaptive
/// libraries support it, and it covers nearly every phone in use.
pub const MINIMUM_SDK: u32 = 26;

