/// `1.2.3` as 10203; parts beyond the third are ignored.
pub fn version_code(version: &str) -> u32 {
    let parts: Vec<u32> = version
        .split(['.', '-', '+'])
        .take(3)
        .map(|part| part.parse().unwrap_or(0))
        .collect();
    let part = |index: usize| parts.get(index).copied().unwrap_or(0).min(99);
    (part(0) * 10000 + part(1) * 100 + part(2)).max(1)
}

pub fn app_build(app: &Application) -> String {
    let namespace = package(&app.app.bundle_id);
    format!(
        r#"// Generated by Bern. Do not edit.
// The Android Gradle plugin compiles Kotlin itself; the Compose compiler
// plugin brings the Kotlin version.
plugins {{
    id("com.android.application")
    id("org.jetbrains.kotlin.plugin.compose")
}}

android {{
    namespace = "{namespace}"
    compileSdk = {COMPILE_SDK}

    defaultConfig {{
        applicationId = "{bundle}"
        minSdk = {MINIMUM_SDK}
        targetSdk = {TARGET_SDK}
        versionCode = {code}
        versionName = "{version}"
        ndk {{
            abiFilters += "arm64-v8a"
        }}
    }}

    buildTypes {{
        release {{
            isMinifyEnabled = false
            // Signed with the debug key for local installs; `bern package`
            // signs for distribution.
            signingConfig = signingConfigs.getByName("debug")
        }}
    }}

    compileOptions {{
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }}

    buildFeatures {{
        compose = true
    }}
}}

dependencies {{
    implementation(platform("androidx.compose:compose-bom:{COMPOSE_BOM}"))
    implementation("androidx.activity:activity-compose:{ACTIVITY_COMPOSE}")
    implementation("androidx.compose.foundation:foundation")
    implementation("androidx.compose.material3:material3")
    implementation("androidx.compose.material:material-icons-core")
    implementation("androidx.compose.ui:ui")
}}
"#,
        bundle = app.app.bundle_id,
        code = version_code(&app.app.version),
        version = app.app.version,
    )
}

/// The manifest: one activity that handles its own configuration changes,
/// so turning the phone or resizing keeps the windows and their drafts.
pub fn manifest() -> String {
    r#"<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Bern. Do not edit. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
    <application
        android:label="@string/app_name"
        android:icon="@mipmap/ic_launcher"
        android:theme="@style/BernTheme"
        android:supportsRtl="true"
        android:enableOnBackInvokedCallback="true">
        <activity
            android:name=".MainActivity"
            android:exported="true"
            android:configChanges="orientation|screenSize|screenLayout|smallestScreenSize|keyboard|keyboardHidden|navigation|uiMode|density|fontScale|layoutDirection|locale"
            android:windowSoftInputMode="adjustResize">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity>
    </application>
</manifest>
"#
    .into()
}

/// The window theme until Compose draws: light, and dark at night.
pub fn theme(night: bool) -> String {
    let parent = if night {
        "android:Theme.Material.NoActionBar"
    } else {
        "android:Theme.Material.Light.NoActionBar"
    };
    format!(
        r#"<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Bern. Do not edit. -->
<resources>
    <style name="BernTheme" parent="{parent}" />
</resources>
"#
    )
}

fn xml_text(value: &str) -> String {
    let mut out = String::new();
    for c in value.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("\\\""),
            '\'' => out.push_str("\\'"),
            '\\' => out.push_str("\\\\"),
            '@' if out.is_empty() => out.push_str("\\@"),
            '?' if out.is_empty() => out.push_str("\\?"),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out
}

/// The resource directory of a language: `values` for the default one,
/// `values-b+zh+Hans` and the like for the others.
pub fn values_dir(language: &str, default: &str) -> String {
    if language == default {
        "values".into()
    } else {
        format!("values-b+{}", language.replace('-', "+"))
    }
}

/// `strings.xml` per resource directory: the application's name, which
/// the launcher shows.
pub fn app_names(app: &Application) -> Vec<(String, String)> {
    let default = &app.languages.default;
    app.languages
        .supported
        .iter()
        .map(|language| {
            let name = translation(&app.app.name, language, default);
            (
                values_dir(language, default),
                format!(
                    "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by Bern. Do not edit. -->\n<resources>\n    <string name=\"app_name\">{}</string>\n</resources>\n",
                    xml_text(name)
                ),
            )
        })
        .collect()
}

/// The string tables the runtime reads, as JSON per language: declared
/// texts with Java format specifiers, and the runtime's own strings.
pub fn text_tables(app: &Application) -> BTreeMap<String, String> {
    let mut tables = BTreeMap::new();
    for language in &app.languages.supported {
        let mut table = serde_json::Map::new();
        for text in &app.texts {
            let value = translation(text, language, &app.languages.default);
            table.insert(
                text.key.clone(),
                positional(value, &text.params, |position| format!("%{position}$s")).into(),
            );
        }
        for (key, translations) in FRAMEWORK_TEXTS {
            let value = framework(translations, language)
                .replace('%', "%%")
                .replace("%%@", "%s");
            table.insert((*key).into(), value.into());
        }
        tables.insert(
            language.clone(),
            serde_json::to_string_pretty(&table).expect("table"),
        );
    }
    tables
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn versions_and_directories() {
        assert_eq!(version_code("0.1.0"), 100);
        assert_eq!(version_code("1.2.3"), 10203);
        assert_eq!(version_code("0.0.0"), 1);
        assert_eq!(values_dir("en", "en"), "values");
        assert_eq!(values_dir("zh-Hans", "en"), "values-b+zh+Hans");
        assert_eq!(xml_text("A & B's"), "A &amp; B\\'s");
    }
}
