/// Owned byte buffer returned to the frontend; free with [`bern_buffer_free`].
#[repr(C)]
pub struct BernBuffer {
    pub ptr: *mut u8,
    pub len: usize,
    pub capacity: usize,
}

impl BernBuffer {
    fn from_vec(bytes: Vec<u8>) -> Self {
        let mut bytes = std::mem::ManuallyDrop::new(bytes);
        BernBuffer {
            ptr: bytes.as_mut_ptr(),
            len: bytes.len(),
            capacity: bytes.capacity(),
        }
    }

    fn empty() -> Self {
        Self::from_vec(Vec::new())
    }
}

/// Frontend callbacks. `context` is passed back unchanged.
#[repr(C)]
#[derive(Clone, Copy)]
pub struct BernCallbacks {
    pub context: *mut c_void,
    /// Engine state update: revision, then changed fields.
    pub on_state: extern "C" fn(*mut c_void, *const u8, usize),
    /// Outcome of an engine command started with a token.
    pub on_reply: extern "C" fn(*mut c_void, u64, *const u8, usize),
    /// A session command from an external entry for the live UI.
    pub on_session_request: extern "C" fn(*mut c_void, u64, *const u8, usize),
    /// A media request for the frontend's media executor.
    pub on_media_request: extern "C" fn(*mut c_void, *const u8, usize),
    /// Merged media state: revision, then every player.
    pub on_media_state: extern "C" fn(*mut c_void, *const u8, usize),
    /// New display state of a query subscription.
    pub on_query: extern "C" fn(*mut c_void, u64, *const u8, usize),
}

impl BernCallbacks {
    fn state(&self, bytes: &[u8]) {
        (self.on_state)(self.context, bytes.as_ptr(), bytes.len());
    }
    fn reply(&self, token: u64, bytes: &[u8]) {
        (self.on_reply)(self.context, token, bytes.as_ptr(), bytes.len());
    }
    fn session_request(&self, request: u64, bytes: &[u8]) {
        (self.on_session_request)(self.context, request, bytes.as_ptr(), bytes.len());
    }
    fn media_request(&self, bytes: &[u8]) {
        (self.on_media_request)(self.context, bytes.as_ptr(), bytes.len());
    }
    fn media_state(&self, bytes: &[u8]) {
        (self.on_media_state)(self.context, bytes.as_ptr(), bytes.len());
    }
    fn query(&self, subscription: u64, bytes: &[u8]) {
        (self.on_query)(self.context, subscription, bytes.as_ptr(), bytes.len());
    }
}

// SAFETY: the frontend guarantees the context stays valid until
// `bern_app_stop` and that its callbacks are safe to call from any thread.
unsafe impl Send for BernCallbacks {}
unsafe impl Sync for BernCallbacks {}

/// Static description of an application, generated by the build.
pub struct AppSpec {
    pub bundle_id: &'static str,
    /// Start the local control channel for CLI, JSON and MCP entries.
    pub ipc: bool,
    pub session: SessionSpec,
    /// Players owned by the application, from the `#[bern::players]` catalog.
    pub players: Vec<String>,
}

/// Forwards session commands from external entries to the frontend, which
/// runs them through the real control bindings.
struct UiBridge {
    session_id: String,
    callbacks: BernCallbacks,
    session: Arc<Mutex<UiSession>>,
    pending: Mutex<BTreeMap<u64, Sender<Result<Value, CommandError>>>>,
    next: AtomicU64,
}

fn write_error(writer: &mut Writer, error: &CommandError) {
    writer.text(&error.code);
    writer.text(&error.message);
}

fn read_error(reader: &mut Reader<'_>) -> CommandError {
    let code = reader.text().unwrap_or_else(|_| "ui_failed".into());
    let message = reader.text().unwrap_or_default();
    CommandError::new(code, message)
}

impl SessionHandler for UiBridge {
    fn session_id(&self) -> String {
        self.session_id.clone()
    }

    fn windows(&self) -> Vec<String> {
        self.session
            .lock()
            .map(|session| session.open_windows().into_iter().map(|w| w.id).collect())
            .unwrap_or_default()
    }

    fn handle(&self, command: SessionCommand, params: Vec<Value>) -> Result<Value, CommandError> {
        let (types, specs) = session_catalog();
        let index = SessionCommand::ALL
            .iter()
            .position(|candidate| *candidate == command)
            .expect("known command");
        let spec = specs
            .iter()
            .find(|spec| spec.id == command.id())
            .expect("catalog entry");
        let mut writer = Writer::new();
        writer.u32(index as u32);
        for (value, param) in params.iter().zip(&spec.params) {
            value.check(&param.ty, &types)?;
            encode(value, &param.ty, &types, &mut writer);
        }
        let request = self.next.fetch_add(1, Ordering::Relaxed);
        let (sender, receiver) = channel();
        self.pending
            .lock()
            .expect("pending lock")
            .insert(request, sender);
        self.callbacks.session_request(request, &writer.bytes);
        let result = receiver.recv_timeout(Duration::from_secs(10));
        self.pending.lock().expect("pending lock").remove(&request);
        match result {
            Ok(Ok(value)) => {
                value.check(&spec.result, &types).map_err(|error| {
                    CommandError::new("ui_failed", format!("invalid UI result: {error}"))
                })?;
                Ok(value)
            }
            Ok(Err(error)) => Err(error),
            Err(_) => Err(CommandError::new(
                "ui_timeout",
                "the UI did not answer in time; the outcome is unknown",
            )),
        }
    }
}

impl UiBridge {
    fn complete(&self, request: u64, bytes: &[u8]) {
        let Some(sender) = self.pending.lock().expect("pending lock").remove(&request) else {
            return;
        };
        let mut reader = Reader::new(bytes);
        let result = match reader.u8() {
            Ok(0) => {
                // Find the command to know the result type.
                let result_type = reader.u32().ok().and_then(|index| {
                    let command = SessionCommand::ALL.get(index as usize)?;
                    let (_, specs) = session_catalog();
                    specs
                        .into_iter()
                        .find(|spec| spec.id == command.id())
                        .map(|spec| spec.result)
                });
                let (types, _) = session_catalog();
                match result_type {
                    Some(ty) => decode(&ty, &types, &mut reader)
                        .map_err(|error| CommandError::new("ui_failed", error.0)),
                    None => Err(CommandError::new("ui_failed", "malformed UI reply")),
                }
            }
            _ => Err(read_error(&mut reader)),
        };
        let _ = sender.send(result);
    }
}

/// The running application behind the C handle.
pub struct BernApp {
    host: Host,
    callbacks: BernCallbacks,
    session: Arc<Mutex<UiSession>>,
    sessions: Sessions,
    bridge: Arc<UiBridge>,
    media: MediaHub,
    queries: query::Subscriptions,
    _subscription: Subscription,
    _media_subscription: MediaSubscription,
    channel: Option<bern_transport_ipc::Server>,
}

fn encode_changes(host: &Host, revision: u64, changes: &[(usize, Value)]) -> Vec<u8> {
    let descriptor = host.descriptor();
    let mut writer = Writer::new();
    writer.u64(revision);
    writer.u32(changes.len() as u32);
    for (field, value) in changes {
        writer.u32(*field as u32);
        encode(
            value,
            &descriptor.state[*field].ty,
            &descriptor.types,
            &mut writer,
        );
    }
    writer.bytes
}

/// Start an application. Called from the generated `bern_app_start`.
///
/// # Safety
/// `error` must be null or point to writable memory for one [`BernBuffer`].
pub unsafe fn start_app<E: EngineProtocol>(
    make_engine: impl FnOnce() -> E,
    spec: AppSpec,
    fingerprint: u64,
    callbacks: BernCallbacks,
    error: *mut BernBuffer,
) -> *mut BernApp {
    let fail = |message: String| {
        if !error.is_null() {
            // SAFETY: the caller provides writable memory for one buffer.
            unsafe { error.write(BernBuffer::from_vec(message.into_bytes())) };
        }
        std::ptr::null_mut()
    };
    let started = catch_unwind(AssertUnwindSafe(|| {
        let engine = make_engine();
        let actual = engine.descriptor().fingerprint();
        if actual != fingerprint {
            return Err(format!(
                "the frontend was generated for catalog {fingerprint:016x}, the engine has {actual:016x}; rebuild"
            ));
        }
        let host = Host::start(engine);
        let session_id = format!("{}-ui", host.engine_id());
        let session = Arc::new(Mutex::new(UiSession::new(
            session_id.clone(),
            Arc::new(spec.session),
        )));
        let bridge = Arc::new(UiBridge {
            session_id,
            callbacks,
            session: Arc::clone(&session),
            pending: Mutex::new(BTreeMap::new()),
            next: AtomicU64::new(1),
        });
        let sessions = Sessions::new();
        sessions.register(bridge.clone());
        let queries = query::Subscriptions::default();
        let updates = host.clone();
        let stale = Arc::clone(&queries);
        let subscription = host.subscribe(move |update| {
            let bytes = encode_changes(&updates, update.revision, &update.changes);
            callbacks.state(&bytes);
            // Answers of queries that read a changed field are stale.
            let changed: Vec<usize> = update.changes.iter().map(|(field, _)| *field).collect();
            query::refresh(&updates, &stale, callbacks, &changed);
        });
        let media = MediaHub::new(&spec.players);
        let media_subscription = media.subscribe(move |update| {
            callbacks.media_state(&media::state_bytes(update.revision, &update.players));
        });
        let channel = if spec.ipc {
            Some(
                bern_transport_ipc::Server::start(
                    host.clone(),
                    sessions.clone(),
                    media.clone(),
                    spec.bundle_id,
                )
                .map_err(|error| format!("cannot start the control channel: {error}"))?,
            )
        } else {
            None
        };
        Ok(BernApp {
            host,
            callbacks,
            session,
            sessions,
            bridge,
            media,
            queries,
            _subscription: subscription,
            _media_subscription: media_subscription,
            channel,
        })
    }));
    match started {
        Ok(Ok(app)) => Box::into_raw(Box::new(app)),
        Ok(Err(message)) => fail(message),
        Err(_) => fail("the engine panicked while starting".into()),
    }
}

fn with_app<T>(app: *mut BernApp, fallback: T, body: impl FnOnce(&BernApp) -> T) -> T {
    if app.is_null() {
        return fallback;
    }
    // SAFETY: non-null handles come from `start_app` and stay valid until
    // `bern_app_stop`, which the frontend calls last.
    let app = unsafe { &*app };
    catch_unwind(AssertUnwindSafe(|| body(app))).unwrap_or(fallback)
}

/// # Safety
/// `bytes` must point to `len` readable bytes or be null with `len == 0`.
unsafe fn slice<'a>(bytes: *const u8, len: usize) -> &'a [u8] {
    if bytes.is_null() || len == 0 {
        &[]
    } else {
        // SAFETY: guaranteed by the caller.
        unsafe { std::slice::from_raw_parts(bytes, len) }
    }
}

/// Stop the application: the control channel closes, the UI session is
/// unregistered and the engine thread ends after queued commands.
///
/// # Safety
/// `app` must be null or a live handle from `bern_app_start`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_app_stop(app: *mut BernApp) {
    if app.is_null() {
        return;
    }
    // SAFETY: `app` came from `start_app` and is not used afterwards.
    let app = unsafe { Box::from_raw(app) };
    let _ = catch_unwind(AssertUnwindSafe(|| {
        app.sessions.unregister(&app.bridge.session_id);
        app.media.detach_executor();
        app.host.stop();
        drop(app);
    }));
}

/// Current engine state: revision, then every field.
///
/// # Safety
/// `app` must be null or a live handle from `bern_app_start`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_app_snapshot(app: *mut BernApp) -> BernBuffer {
    with_app(app, BernBuffer::empty(), |app| {
        let (revision, values) = app.host.snapshot();
        let changes: Vec<(usize, Value)> = values.into_iter().enumerate().collect();
        BernBuffer::from_vec(encode_changes(&app.host, revision, &changes))
    })
}

