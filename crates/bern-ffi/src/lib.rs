/// Owned byte buffer returned to the frontend; free with [`bern_buffer_free`].
#[repr(C)]
pub struct BernBuffer {
    pub ptr: *mut u8,
    pub len: usize,
    pub capacity: usize,
}

impl BernBuffer {
    fn from_vec(bytes: Vec<u8>) -> Self {
        let mut bytes = std::mem::ManuallyDrop::new(bytes);
        BernBuffer {
            ptr: bytes.as_mut_ptr(),
            len: bytes.len(),
            capacity: bytes.capacity(),
        }
    }

    fn empty() -> Self {
        Self::from_vec(Vec::new())
    }
}

/// Frontend callbacks. `context` is passed back unchanged.
#[repr(C)]
#[derive(Clone, Copy)]
pub struct BernCallbacks {
    pub context: *mut c_void,
    /// Engine state update: revision, then changed fields.
    pub on_state: extern "C" fn(*mut c_void, *const u8, usize),
    /// Outcome of an engine command started with a token.
    pub on_reply: extern "C" fn(*mut c_void, u64, *const u8, usize),
    /// A session command from an external entry for the live UI.
    pub on_session_request: extern "C" fn(*mut c_void, u64, *const u8, usize),
    /// A media request for the frontend's media executor.
    pub on_media_request: extern "C" fn(*mut c_void, *const u8, usize),
    /// Merged media state: revision, then every player.
    pub on_media_state: extern "C" fn(*mut c_void, *const u8, usize),
    /// New display state of a query subscription.
    pub on_query: extern "C" fn(*mut c_void, u64, *const u8, usize),
}

impl BernCallbacks {
    fn state(&self, bytes: &[u8]) {
        (self.on_state)(self.context, bytes.as_ptr(), bytes.len());
    }
    fn reply(&self, token: u64, bytes: &[u8]) {
        (self.on_reply)(self.context, token, bytes.as_ptr(), bytes.len());
    }
    fn session_request(&self, request: u64, bytes: &[u8]) {
        (self.on_session_request)(self.context, request, bytes.as_ptr(), bytes.len());
    }
    fn media_request(&self, bytes: &[u8]) {
        (self.on_media_request)(self.context, bytes.as_ptr(), bytes.len());
    }
    fn media_state(&self, bytes: &[u8]) {
        (self.on_media_state)(self.context, bytes.as_ptr(), bytes.len());
    }
    fn query(&self, subscription: u64, bytes: &[u8]) {
        (self.on_query)(self.context, subscription, bytes.as_ptr(), bytes.len());
    }
}

// SAFETY: the frontend guarantees the context stays valid until
// `bern_app_stop` and that its callbacks are safe to call from any thread.
unsafe impl Send for BernCallbacks {}
unsafe impl Sync for BernCallbacks {}

