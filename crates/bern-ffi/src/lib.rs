//! In-process bridge between a native UI and the Bern runtime.
//!
//! The engine, the UI session runtime and the generated frontend share one
//! process. Values cross the boundary in the compact binary layout of
//! `bern_protocol::codec`, typed on both sides by generated code; there is
//! no helper process, no network listener and no JSON on this path. The
//! optional control channel is started only when the build assembles it.
//!
//! Callbacks may run on engine or channel threads; the frontend moves work
//! to its UI thread. All functions catch Rust panics at the boundary.

