/// Forwards session commands from external entries to the frontend, which
/// runs them through the real control bindings.
pub(crate) struct UiBridge {
    pub(crate) session_id: String,
    callbacks: BernCallbacks,
    session: Arc<Mutex<UiSession>>,
    pending: Mutex<BTreeMap<u64, PendingRequest>>,
    next: AtomicU64,
}

pub(crate) type SessionReply = Box<dyn FnOnce(Result<Value, CommandError>) + Send>;

/// A session command the frontend is running.
struct PendingRequest {
    command: SessionCommand,
    /// The window a presentation command acts on; its facts are the result.
    presented: Option<bern_runtime::WindowInstance>,
    reply: SessionReply,
}

fn write_error(writer: &mut Writer, error: &CommandError) {
    writer.text(&error.code);
    writer.text(&error.message);
}

fn read_error(reader: &mut Reader<'_>) -> CommandError {
    let code = reader.text().unwrap_or_else(|_| "ui_failed".into());
    let message = reader.text().unwrap_or_default();
    CommandError::new(code, message)
}

impl SessionHandler for UiBridge {
    fn session_id(&self) -> String {
        self.session_id.clone()
    }

    fn windows(&self) -> Vec<String> {
        self.session
            .lock()
            .map(|session| session.open_windows().into_iter().map(|w| w.id).collect())
            .unwrap_or_default()
    }

    fn handle(&self, command: SessionCommand, params: Vec<Value>) -> Result<Value, CommandError> {
        let (sender, receiver) = channel();
        let request = self.run(
            command,
            params,
            Box::new(move |result| {
                let _ = sender.send(result);
            }),
        );
        let result = receiver.recv_timeout(Duration::from_secs(10));
        if let Some(request) = request {
            self.pending.lock().expect("pending lock").remove(&request);
        }
        result.unwrap_or_else(|_| {
            Err(CommandError::new(
                "ui_timeout",
                "the UI did not answer in time; the outcome is unknown",
            ))
        })
    }
}

impl UiBridge {
    /// Run a session command. `reply` gets the result: at once when the
    /// session runtime answers from its own records or refuses the command,
    /// otherwise when the frontend completes it. Returns the request id
    /// while the frontend runs it.
    pub(crate) fn run(
        &self,
        command: SessionCommand,
        params: Vec<Value>,
        reply: SessionReply,
    ) -> Option<u64> {
        // The trace is the runtime's own; the frontend only records.
        if command.is_trace() {
            reply(trace::run(command, &params));
            return None;
        }
        let (types, specs) = session_catalog();
        let index = SessionCommand::ALL
            .iter()
            .position(|candidate| *candidate == command)
            .expect("known command");
        let spec = specs
            .iter()
            .find(|spec| spec.id == command.id())
            .expect("catalog entry");
        for (value, param) in params.iter().zip(&spec.params) {
            if let Err(error) = value.check(&param.ty, &types) {
                reply(Err(error.into()));
                return None;
            }
        }
        // The session runtime answers from the facts the frontend reported,
        // and refuses actions those facts do not offer before the frontend
        // runs them.
        let presented = {
            let session = self.session.lock().expect("session lock");
            if command == SessionCommand::WindowList {
                let infos = session.window_infos();
                drop(session);
                reply(Ok(Value::List(
                    infos.iter().map(WindowInfo::to_value).collect(),
                )));
                return None;
            }
            match (presentation_action(command), params.first()) {
                (Some(action), Some(Value::Text(window))) => {
                    match session.check_action(window, action) {
                        Ok(instance) => Some(instance),
                        Err(error) => {
                            drop(session);
                            reply(Err(error));
                            return None;
                        }
                    }
                }
                _ => None,
            }
        };
        let mut writer = Writer::new();
        writer.u32(index as u32);
        for (value, param) in params.iter().zip(&spec.params) {
            encode(value, &param.ty, &types, &mut writer);
        }
        let request = self.next.fetch_add(1, Ordering::Relaxed);
        self.pending.lock().expect("pending lock").insert(
            request,
            PendingRequest {
                command,
                presented,
                reply,
            },
        );
        self.callbacks.session_request(request, &writer.bytes);
        Some(request)
    }

    fn complete(&self, request: u64, bytes: &[u8]) {
        let Some(pending) = self.pending.lock().expect("pending lock").remove(&request) else {
            return;
        };
        let (types, specs) = session_catalog();
        let mut reader = Reader::new(bytes);
        let result = match reader.u8() {
            Ok(0) => {
                let answered = reader
                    .u32()
                    .ok()
                    .and_then(|index| SessionCommand::ALL.get(index as usize).copied());
                if answered != Some(pending.command) {
                    Err(CommandError::new("ui_failed", "malformed UI reply"))
                } else if let Some(instance) = pending.presented {
                    // Presentation commands answer once the platform
                    // reported the new facts; the result is the instance
                    // as the runtime now sees it.
                    self.session
                        .lock()
                        .expect("session lock")
                        .window_info(instance.kind)
                        .filter(|info| info.window == instance.id)
                        .map(|info| info.to_value())
                        .ok_or_else(|| {
                            CommandError::new(
                                "stale_window",
                                format!("`{}` closed while the command ran", instance.id),
                            )
                        })
                } else {
                    let ty = &specs
                        .iter()
                        .find(|spec| spec.id == pending.command.id())
                        .expect("catalog entry")
                        .result;
                    decode(ty, &types, &mut reader)
                        .map_err(|error| CommandError::new("ui_failed", error.0))
                        .and_then(|value| {
                            value.check(ty, &types).map_err(|error| {
                                CommandError::new(
                                    "ui_failed",
                                    format!("invalid UI result: {error}"),
                                )
                            })?;
                            Ok(value)
                        })
                }
            }
            _ => Err(read_error(&mut reader)),
        };
        (pending.reply)(result);
    }
}

/// The window action a presentation command performs.
fn presentation_action(command: SessionCommand) -> Option<WindowAction> {
    Some(match command {
        SessionCommand::WindowMinimize => WindowAction::Minimize,
        SessionCommand::WindowRestore => WindowAction::Restore,
        SessionCommand::WindowMaximize => WindowAction::Maximize,
        SessionCommand::WindowMove => WindowAction::Move,
        SessionCommand::WindowResize => WindowAction::Resize,
        _ => return None,
    })
}

/// The local control channel, when this build includes one.
#[cfg(feature = "ipc")]
type Channel = bern_transport_ipc::Server;

/// Builds without the `ipc` feature, such as WebAssembly, have no channel.
#[cfg(not(feature = "ipc"))]
enum Channel {}

#[cfg(feature = "ipc")]
fn start_channel(
    host: &Host,
    sessions: &Sessions,
    media: &MediaHub,
    bundle_id: &str,
) -> Result<Channel, String> {
    bern_transport_ipc::Server::start(host.clone(), sessions.clone(), media.clone(), bundle_id)
        .map_err(|error| format!("cannot start the control channel: {error}"))
}

#[cfg(not(feature = "ipc"))]
fn start_channel(_: &Host, _: &Sessions, _: &MediaHub, _: &str) -> Result<Channel, String> {
    Err(
        "this build of the runtime has no control channel; remove `ipc` from the target's channels"
            .into(),
    )
}

/// The running application behind the C handle.
pub struct BernApp {
    host: Arc<dyn EngineLink>,
    callbacks: BernCallbacks,
    session: Arc<Mutex<UiSession>>,
    sessions: Sessions,
    bridge: Arc<UiBridge>,
    media: Arc<dyn MediaLink>,
    /// The application's media kernel, once the frontend let it execute.
    kernel: Mutex<Option<Arc<dyn bern_media::kernel::MediaKernel>>>,
    queries: query::Subscriptions,
    _subscription: Guard,
    _media_subscription: Guard,
    channel: Option<Channel>,
    /// The engine host's channel, in the WebUI build.
    #[cfg(feature = "remote")]
    remote: Option<Arc<remote::Remote>>,
}

fn encode_changes(host: &dyn EngineLink, revision: u64, changes: &[(usize, Value)]) -> Vec<u8> {
    let descriptor = host.descriptor();
    // Inside a traced job, each field's encoding is recorded with its size.
    let traced = trace::current_job().is_some();
    let mut writer = Writer::new();
    writer.u64(revision);
    writer.u32(changes.len() as u32);
    for (field, value) in changes {
        writer.u32(*field as u32);
        let (started, before) = if traced {
            (trace::now_ns(), writer.bytes.len())
        } else {
            (0, 0)
        };
        encode(
            value,
            &descriptor.state[*field].ty,
            &descriptor.types,
            &mut writer,
        );
        if traced {
            let items = match value {
                Value::List(items) => items.len() as u32 + 1,
                _ => 0,
            };
            trace::job_record(
                trace::kind::ENCODE_FIELD,
                started,
                *field as u32,
                revision,
                (writer.bytes.len() - before) as u64,
                items,
            );
        }
    }
    writer.bytes
}

/// Text of a panic payload, for startup errors.
fn panic_message(payload: &(dyn std::any::Any + Send)) -> &str {
    payload
        .downcast_ref::<&str>()
        .copied()
        .or_else(|| payload.downcast_ref::<String>().map(String::as_str))
        .unwrap_or("no message")
}

/// Start an application. Called from the generated `bern_app_start`.
///
/// `resources` is the UTF-8 path of the directory where the product keeps
/// the declared resource files, or null when the host has none. The
/// declared names and that directory are installed as the process's
/// [`Resources`] before the engine is constructed.
///
/// # Safety
/// `resources` must point to `resources_len` readable bytes or be null with
/// `resources_len == 0`. `error` must be null or point to writable memory
/// for one [`BernBuffer`].
pub unsafe fn start_app<E: EngineProtocol>(
    make_engine: impl FnOnce() -> E,
    spec: AppSpec,
    fingerprint: u64,
    resources: *const u8,
    resources_len: usize,
    callbacks: BernCallbacks,
    error: *mut BernBuffer,
) -> *mut BernApp {
    // SAFETY: guaranteed by the caller.
    let resources = unsafe { slice(resources, resources_len) };
    let fail = |message: String| {
        if !error.is_null() {
            // SAFETY: the caller provides writable memory for one buffer.
            unsafe { error.write(BernBuffer::from_vec(message.into_bytes())) };
        }
        std::ptr::null_mut()
    };
    let started = catch_unwind(AssertUnwindSafe(|| {
        if !resources.is_empty() {
            let root = std::str::from_utf8(resources)
                .map_err(|_| "the resource directory path is not UTF-8".to_string())?;
            // A page has no files: there `resources` is the URL prefix the
            // declared resources are served from.
            let located = if cfg!(target_arch = "wasm32") {
                Resources::served(root, None, spec.resources.iter().cloned())
            } else {
                Resources::catalog(root, spec.resources.iter().cloned())
            };
            located
                .install()
                .map_err(|message| format!("cannot install the app's resources: {message}"))?;
            // Android's resources sit in the app's private files folder,
            // which holds its stored values and data too.
            if cfg!(target_os = "android")
                && let Some(files) = std::path::Path::new(root).parent()
            {
                bern_command::storage::Store::install_files_folder(files);
            }
        }
        bern_command::storage::Store::install_application(spec.bundle_id);
        let engine = make_engine();
        let actual = engine.descriptor().fingerprint();
        if actual != fingerprint {
            return Err(format!(
                "the frontend was generated for catalog {fingerprint:016x}, the engine has {actual:016x}; rebuild"
            ));
        }
        let host = Host::start(engine);
        let media = MediaHub::new(&spec.players);
        let sessions = Sessions::new();
        let channel = if spec.ipc {
            Some(start_channel(&host, &sessions, &media, spec.bundle_id)?)
        } else {
            None
        };
        let session_id = format!("{}-ui", host.engine_id());
        let app = assemble(
            Arc::new(host),
            Arc::new(media),
            sessions,
            session_id,
            spec.session,
            callbacks,
            channel,
        );
        app.sessions.register(app.bridge.clone());
        Ok(app)
    }));
    match started {
        Ok(Ok(app)) => Box::into_raw(Box::new(app)),
        Ok(Err(message)) => fail(message),
        Err(payload) => fail(format!(
            "the engine panicked while starting: {}",
            panic_message(payload.as_ref())
        )),
    }
}

/// The application around an engine link and a media link: the UI
/// session, its bridge for external session commands, query
/// subscriptions and the state and media listeners.
pub(crate) fn assemble(
    host: Arc<dyn EngineLink>,
    media: Arc<dyn MediaLink>,
    sessions: Sessions,
    session_id: String,
    spec: SessionSpec,
    callbacks: BernCallbacks,
    channel: Option<Channel>,
) -> BernApp {
    let session = Arc::new(Mutex::new(UiSession::new(
        session_id.clone(),
        Arc::new(spec),
    )));
    let bridge = Arc::new(UiBridge {
        session_id,
        callbacks,
        session: Arc::clone(&session),
        pending: Mutex::new(BTreeMap::new()),
        next: AtomicU64::new(1),
    });
    let queries = query::Subscriptions::default();
    let updates = Arc::clone(&host);
    let stale = Arc::clone(&queries);
    let subscription = host.subscribe(Box::new(move |update| {
        let bytes = encode_changes(updates.as_ref(), update.revision, &update.changes);
        if trace::on(trace::ENGINE) {
            trace::callback(trace::CALLBACK_STATE, update.revision, 0, bytes.len());
        }
        callbacks.state(&bytes);
        // Answers of queries that read a changed field are stale.
        let changed: Vec<usize> = update.changes.iter().map(|(field, _)| *field).collect();
        query::refresh(updates.as_ref(), &stale, callbacks, &changed);
    }));
    let media_subscription = media.subscribe(Box::new(move |update| {
        callbacks.media_state(&media::state_bytes(update.revision, &update.players));
    }));
    BernApp {
        host,
        callbacks,
        session,
        sessions,
        bridge,
        media,
        kernel: Mutex::new(None),
        queries,
        _subscription: subscription,
        _media_subscription: media_subscription,
        channel,
        #[cfg(feature = "remote")]
        remote: None,
    }
}

pub(crate) fn with_app<T>(app: *mut BernApp, fallback: T, body: impl FnOnce(&BernApp) -> T) -> T {
    if app.is_null() {
        return fallback;
    }
    // SAFETY: non-null handles come from `start_app` and stay valid until
    // `bern_app_stop`, which the frontend calls last.
    let app = unsafe { &*app };
    catch_unwind(AssertUnwindSafe(|| body(app))).unwrap_or(fallback)
}

/// # Safety
/// `bytes` must point to `len` readable bytes or be null with `len == 0`.
pub(crate) unsafe fn slice<'a>(bytes: *const u8, len: usize) -> &'a [u8] {
    if bytes.is_null() || len == 0 {
        &[]
    } else {
        // SAFETY: guaranteed by the caller.
        unsafe { std::slice::from_raw_parts(bytes, len) }
    }
}

/// Stop the application: the control channel closes, the UI session is
/// unregistered and the engine thread ends after queued commands.
///
/// # Safety
/// `app` must be null or a live handle from `bern_app_start`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_app_stop(app: *mut BernApp) {
    if app.is_null() {
        return;
    }
    // SAFETY: `app` came from `start_app` and is not used afterwards.
    let app = unsafe { Box::from_raw(app) };
    let _ = catch_unwind(AssertUnwindSafe(|| {
        app.sessions.unregister(&app.bridge.session_id);
        app.media.detach_executor();
        if let Some(kernel) = app.kernel.lock().expect("kernel lock").take() {
            kernel.detached();
        }
        app.host.stop();
        drop(app);
    }));
}

/// Current engine state: revision, then every field.
///
/// # Safety
/// `app` must be null or a live handle from `bern_app_start`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_app_snapshot(app: *mut BernApp) -> BernBuffer {
    with_app(app, BernBuffer::empty(), |app| {
        let (revision, values) = app.host.snapshot();
        let changes: Vec<(usize, Value)> = values.into_iter().enumerate().collect();
        BernBuffer::from_vec(encode_changes(app.host.as_ref(), revision, &changes))
    })
}

/// Engine instance id as UTF-8.
///
/// # Safety
/// `app` must be null or a live handle from `bern_app_start`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_app_engine_id(app: *mut BernApp) -> BernBuffer {
    with_app(app, BernBuffer::empty(), |app| {
        BernBuffer::from_vec(app.host.engine_id().into_bytes())
    })
}

/// Control channel socket path as UTF-8, empty when not assembled.
///
/// # Safety
/// `app` must be null or a live handle from `bern_app_start`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_app_channel(app: *mut BernApp) -> BernBuffer {
    with_app(app, BernBuffer::empty(), |app| {
        #[cfg(feature = "ipc")]
        let path = app
            .channel
            .as_ref()
            .map(|server| server.path().to_string_lossy().into_owned())
            .unwrap_or_default();
        #[cfg(not(feature = "ipc"))]
        let path = match &app.channel {
            Some(never) => match *never {},
            None => String::new(),
        };
        BernBuffer::from_vec(path.into_bytes())
    })
}

fn outcome_bytes(
    descriptor: &bern_protocol::ProtocolDescriptor,
    command: usize,
    outcome: &CommandOutcome,
) -> Vec<u8> {
    result_bytes(
        &outcome.result,
        outcome.revision,
        &descriptor.commands[command].result,
        &descriptor.types,
    )
}

/// `0, revision, result` or `1, revision, code, message`.
fn result_bytes(
    result: &Result<Value, CommandError>,
    revision: u64,
    ty: &Type,
    types: &bern_protocol::TypeTable,
) -> Vec<u8> {
    let mut writer = Writer::new();
    match result {
        Ok(value) => {
            writer.u8(0);
            writer.u64(revision);
            encode(value, ty, types, &mut writer);
        }
        Err(error) => {
            writer.u8(1);
            writer.u64(revision);
            write_error(&mut writer, error);
        }
    }
    writer.bytes
}

/// Dispatch engine command `command` with encoded parameters. The outcome
/// arrives through the `reply` callback with `token`.
///
/// # Safety
/// `params` must point to `len` readable bytes or be null with `len == 0`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_app_dispatch(
    app: *mut BernApp,
    command: u32,
    params: *const u8,
    len: usize,
    token: u64,
) {
    let started = if trace::on(trace::UI | trace::ENGINE) {
        trace::now_ns()
    } else {
        0
    };
    // SAFETY: guaranteed by the caller.
    let bytes = unsafe { slice(params, len) }.to_vec();
    with_app(app, (), |app| {
        let descriptor = app.host.descriptor();
        let callbacks = app.callbacks;
        let command = command as usize;
        let decoded = descriptor
            .commands
            .get(command)
            .ok_or_else(|| CommandError::new("unknown_command", "unknown command index"))
            .and_then(|spec| {
                let mut reader = Reader::new(&bytes);
                let params = spec
                    .params
                    .iter()
                    .map(|param| decode(&param.ty, &descriptor.types, &mut reader))
                    .collect::<Result<Vec<_>, _>>()
                    .map_err(|error| CommandError::invalid_params(error.0))?;
                if !reader.is_finished() {
                    return Err(CommandError::invalid_params("trailing parameter bytes"));
                }
                Ok(params)
            });
        if started != 0 {
            // Whether a job of it is traced here, so an interaction knows
            // whether to wait for one.
            let catalog = trace::register_catalog(descriptor);
            let traced = decoded.is_ok()
                && app.host.local()
                && trace::on(trace::ENGINE)
                && trace::traces_command(catalog, command);
            trace::record(trace::Record {
                t0: started,
                t1: trace::now_ns(),
                key: token,
                a: command as u64,
                b: traced as u64,
                kind: trace::kind::DECODE,
                catalog,
                ..trace::Record::default()
            });
        }
        match decoded {
            Ok(params) => {
                trace::with_origin(trace::Origin::Token(token), || {
                    app.host.dispatch(
                        Invocation { command, params },
                        CallContext {
                            entry: Entry::Ui,
                            request_id: token.to_string(),
                        },
                        bern_protocol::Cancellation::new(),
                        Box::new(move |outcome| {
                            let bytes = outcome_bytes(descriptor, command, &outcome);
                            if trace::on(trace::ENGINE) {
                                trace::callback(trace::CALLBACK_REPLY, token, 0, bytes.len());
                            }
                            callbacks.reply(token, &bytes);
                        }),
                    )
                });
            }
            Err(error) => {
                let mut writer = Writer::new();
                writer.u8(1);
                writer.u64(app.host.snapshot().0);
                write_error(&mut writer, &error);
                callbacks.reply(token, &writer.bytes);
            }
        }
    })
}

fn instance_bytes(app: &BernApp, instance: &bern_runtime::WindowInstance) -> Vec<u8> {
    let session = app.session.lock().expect("session lock");
    let spec = session.spec();
    let mut writer = Writer::new();
    writer.u8(0);
    writer.u64(instance.generation);
    writer.text(&instance.id);
    let kind = &spec.windows[instance.kind];
    writer.u32(kind.sessions.len() as u32);
    for (slot, session_index) in kind.sessions.iter().enumerate() {
        writer.u32(*session_index as u32);
        for ((_, ty, _), value) in spec.sessions[*session_index]
            .fields
            .iter()
            .zip(&instance.drafts[slot])
        {
            encode(value, ty, &spec.types, &mut writer);
        }
    }
    writer.bytes
}

fn error_bytes(error: &CommandError) -> Vec<u8> {
    let mut writer = Writer::new();
    writer.u8(1);
    write_error(&mut writer, error);
    writer.bytes
}

/// The frontend observed that a window of `kind` is shown. Returns the
/// instance generation, id and its session drafts.
///
/// # Safety
/// `app` must be null or a live handle from `bern_app_start`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_window_opened(app: *mut BernApp, kind: u32) -> BernBuffer {
    with_app(app, BernBuffer::empty(), |app| {
        let opened = app
            .session
            .lock()
            .expect("session lock")
            .window_opened(kind as usize);
        app.host.windows_changed(app.bridge.windows());
        BernBuffer::from_vec(match opened {
            Ok(instance) => instance_bytes(app, &instance),
            Err(error) => error_bytes(&error),
        })
    })
}

/// The frontend observed that a window instance closed.
///
/// # Safety
/// `app` must be null or a live handle from `bern_app_start`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_window_closed(app: *mut BernApp, kind: u32, generation: u64) {
    with_app(app, (), |app| {
        let closed = {
            let mut session = app.session.lock().expect("session lock");
            let id = session
                .spec()
                .windows
                .get(kind as usize)
                .map(|window| format!("{}#{generation}", window.id));
            session
                .window_closed(kind as usize, generation)
                .then_some(id)
                .flatten()
        };
        // Window-scoped media and queries go with the instance;
        // application players stay.
        if let Some(id) = closed {
            app.media.release_window(&id);
            app.queries.lock().expect("query lock").close_window(&id);
            app.host.windows_changed(app.bridge.windows());
        }
    })
}

/// The frontend reports what the platform shows for a window instance.
/// `visibility` indexes visible, minimized, hidden; `size` indexes normal,
/// maximized, full screen; `actions` sets bit `WindowAction::index()` for
/// each action available now; `source` is 0 when a window command caused
/// the change and 1 for the user or the system. The frame is in points
/// with the origin at the top-left of the main display. Returns the fact
/// version, or 0 when the facts are invalid or the instance is stale.
///
/// # Safety
/// `app` must be null or a live handle from `bern_app_start`.
#[unsafe(no_mangle)]
#[allow(clippy::too_many_arguments)]
pub unsafe extern "C" fn bern_window_facts(
    app: *mut BernApp,
    kind: u32,
    generation: u64,
    source: u8,
    visibility: u8,
    size: u8,
    x: f64,
    y: f64,
    width: f64,
    height: f64,
    focused: u8,
    actions: u32,
) -> u64 {
    with_app(app, 0, |app| {
        let visibility = match visibility {
            0 => Visibility::Visible,
            1 => Visibility::Minimized,
            2 => Visibility::Hidden,
            _ => return 0,
        };
        let size = match size {
            0 => SizeState::Normal,
            1 => SizeState::Maximized,
            2 => SizeState::FullScreen,
            _ => return 0,
        };
        let source = match source {
            0 => FactSource::Command,
            1 => FactSource::System,
            _ => return 0,
        };
        if ![x, y, width, height].iter().all(|value| value.is_finite()) {
            return 0;
        }
        let facts = WindowFacts {
            visibility,
            size,
            frame: Frame {
                x,
                y,
                width,
                height,
            },
            focused: focused != 0,
            actions: WindowAction::from_bits(actions),
        };
        app.session
            .lock()
            .expect("session lock")
            .window_facts(kind as usize, generation, facts, source)
            .unwrap_or(0)
    })
}

/// Request closing a window instance after the frontend evaluated the
/// window's declared close check. Returns `0, 0` to close now,
/// `0, 1, confirmation, draft revision` when a decision is needed, or
/// `1, code, message`.
///
/// # Safety
/// `app` must be null or a live handle from `bern_app_start`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_window_request_close(
    app: *mut BernApp,
    kind: u32,
    generation: u64,
    needs_confirmation: u8,
    can_save: u8,
) -> BernBuffer {
    with_app(app, BernBuffer::empty(), |app| {
        let step = app.session.lock().expect("session lock").request_close(
            kind as usize,
            generation,
            needs_confirmation != 0,
            can_save != 0,
        );
        let mut writer = Writer::new();
        match step {
            Ok(CloseStep::Close) => {
                writer.u8(0);
                writer.u8(0);
            }
            Ok(CloseStep::Confirm(confirmation)) => {
                writer.u8(0);
                writer.u8(1);
                writer.text(&confirmation.id);
                writer.u64(confirmation.draft_revision);
            }
            Err(error) => return BernBuffer::from_vec(error_bytes(&error)),
        }
        BernBuffer::from_vec(writer.bytes)
    })
}

/// Decide a pending close confirmation. Layout of `bytes`: confirmation
/// text, decision u32 (0 save, 1 discard, 2 cancel). Returns `0, step`
/// (0 close, 1 save, 2 cancel) or `1, code, message`; stale decisions fail
/// with `stale_confirmation` or `stale_window`.
///
/// # Safety
/// `bytes` must point to `len` readable bytes or be null with `len == 0`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_window_confirm_close(
    app: *mut BernApp,
    kind: u32,
    generation: u64,
    bytes: *const u8,
    len: usize,
) -> BernBuffer {
    // SAFETY: guaranteed by the caller.
    let bytes = unsafe { slice(bytes, len) };
    with_app(app, BernBuffer::empty(), |app| {
        let mut reader = Reader::new(bytes);
        let decided = (|| {
            let confirmation = reader
                .text()
                .map_err(|error| CommandError::invalid_params(error.0))?;
            let decision = reader
                .u32()
                .ok()
                .and_then(CloseDecision::from_index)
                .ok_or_else(|| CommandError::invalid_params("unknown close decision"))?;
            app.session.lock().expect("session lock").confirm_close(
                kind as usize,
                generation,
                &confirmation,
                decision,
            )
        })();
        BernBuffer::from_vec(match decided {
            Ok(step) => {
                let mut writer = Writer::new();
                writer.u8(0);
                writer.u8(match step {
                    DecisionStep::Close => 0,
                    DecisionStep::Save => 1,
                    DecisionStep::Cancel => 2,
                });
                writer.bytes
            }
            Err(error) => error_bytes(&error),
        })
    })
}

/// Write one session field of a window instance. Returns `0, revision` or
/// `1, code, message`.
///
/// # Safety
/// `value` must point to `len` readable bytes or be null with `len == 0`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_session_set(
    app: *mut BernApp,
    kind: u32,
    generation: u64,
    session: u32,
    field: u32,
    value: *const u8,
    len: usize,
) -> BernBuffer {
    // SAFETY: guaranteed by the caller.
    let bytes = unsafe { slice(value, len) };
    with_app(app, BernBuffer::empty(), |app| {
        let mut state = app.session.lock().expect("session lock");
        let result = (|| {
            let spec = state.spec();
            let ty: Type = spec
                .sessions
                .get(session as usize)
                .and_then(|session| session.fields.get(field as usize))
                .map(|(_, ty, _)| ty.clone())
                .ok_or_else(|| CommandError::new("target_not_found", "unknown session field"))?;
            let mut reader = Reader::new(bytes);
            let value = decode(&ty, &spec.types, &mut reader)
                .map_err(|error| CommandError::invalid_params(error.0))?;
            state.set(
                kind as usize,
                generation,
                session as usize,
                field as usize,
                value,
            )
        })();
        let mut writer = Writer::new();
        match result {
            Ok(revision) => {
                writer.u8(0);
                writer.u64(revision);
            }
            Err(error) => {
                writer.u8(1);
                write_error(&mut writer, &error);
            }
        }
        BernBuffer::from_vec(writer.bytes)
    })
}

/// Answer a session request: `0, command index, result` or `1, code, message`.
///
/// # Safety
/// `bytes` must point to `len` readable bytes or be null with `len == 0`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_session_complete(
    app: *mut BernApp,
    request: u64,
    bytes: *const u8,
    len: usize,
) {
    // SAFETY: guaranteed by the caller.
    let bytes = unsafe { slice(bytes, len) };
    with_app(app, (), |app| app.bridge.complete(request, bytes))
}

/// Memory for bytes a WebAssembly host passes in: `len` bytes, released
/// with [`bern_bytes_free`]. Native hosts pass their own memory instead.
#[cfg(target_arch = "wasm32")]
#[unsafe(no_mangle)]
pub extern "C" fn bern_bytes_alloc(len: usize) -> *mut u8 {
    let mut bytes = std::mem::ManuallyDrop::new(Vec::<u8>::with_capacity(len.max(1)));
    bytes.as_mut_ptr()
}

/// Release memory from [`bern_bytes_alloc`].
///
/// # Safety
/// `ptr` and `len` must come from one `bern_bytes_alloc` call.
#[cfg(target_arch = "wasm32")]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_bytes_free(ptr: *mut u8, len: usize) {
    if !ptr.is_null() {
        // SAFETY: allocated by `bern_bytes_alloc` with this capacity.
        drop(unsafe { Vec::from_raw_parts(ptr, 0, len.max(1)) });
    }
}

/// Release a buffer returned by this library.
///
/// # Safety
/// `buffer` must come from this library and be released only once.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_buffer_free(buffer: BernBuffer) {
    if buffer.ptr.is_null() {
        return;
    }
    // SAFETY: the buffer was created by `BernBuffer::from_vec`.
    drop(unsafe { Vec::from_raw_parts(buffer.ptr, buffer.len, buffer.capacity) });
}

