/// `InfoPlist.strings` contents per language, localizing the app name and,
/// with `[app].photos`, why it adds to the photo library.
pub fn info_plist_tables(app: &Application) -> BTreeMap<String, String> {
    app.languages
        .supported
        .iter()
        .map(|language| {
            let name = escape_strings(translation(&app.app.name, language, &app.languages.default));
            let mut table =
                format!("CFBundleName = \"{name}\";\nCFBundleDisplayName = \"{name}\";\n");
            if app.app.photos {
                let usage = escape_strings(framework(PHOTOS_USAGE, language));
                table.push_str(&format!(
                    "NSPhotoLibraryAddUsageDescription = \"{usage}\";\n"
                ));
            }
            (language.clone(), table)
        })
        .collect()
}

fn xml(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// The Info.plist of a macOS app. `catalog_icon`: the icon is compiled into
/// the bundle's asset catalog (from an Icon Composer document), which
/// `CFBundleIconName` names; `CFBundleIconFile` names the `.icns` either
/// way, for systems before macOS 26.
pub fn info_plist(
    app: &Application,
    executable: &str,
    minimum_system: &str,
    catalog_icon: bool,
) -> String {
    let name = translation(
        &app.app.name,
        &app.languages.default,
        &app.languages.default,
    );
    let localizations: String = app
        .languages
        .supported
        .iter()
        .map(|language| format!("\n        <string>{}</string>", xml(language)))
        .collect();
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key>
    <string>{region}</string>
    <key>CFBundleDisplayName</key>
    <string>{name}</string>
    <key>CFBundleExecutable</key>
    <string>{executable}</string>
    <key>CFBundleIconFile</key>
    <string>AppIcon</string>{icon_name}
    <key>CFBundleIdentifier</key>
    <string>{bundle}</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleLocalizations</key>
    <array>{localizations}
    </array>
    <key>CFBundleName</key>
    <string>{name}</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>{version}</string>
    <key>CFBundleVersion</key>
    <string>{version}</string>
    <key>LSMinimumSystemVersion</key>
    <string>{minimum_system}</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>NSSupportsAutomaticTermination</key>
    <false/>{documents}{services}
</dict>
</plist>
"#,
        region = xml(&app.languages.default),
        name = xml(name),
        executable = xml(executable),
        bundle = xml(&app.app.bundle_id),
        version = xml(&app.app.version),
        icon_name = if catalog_icon {
            "\n    <key>CFBundleIconName</key>\n    <string>AppIcon</string>"
        } else {
            ""
        },
        documents = document_types(app, false),
        services = services(app, executable),
    )
}

/// The system's content type of a file category.
fn system_type(kind: &str) -> &'static str {
    match kind {
        "video" => "public.movie",
        "audio" => "public.audio",
        "picture" => "public.image",
        "folder" => "public.folder",
        _ => "public.item",
    }
}

/// The content type declared for an extension the system may not know.
fn imported_type(bundle_id: &str, ext: &str) -> String {
    format!("{bundle_id}.file.{ext}")
}

/// The declaration of [`imported_type`], in `UTImportedTypeDeclarations`.
fn imported_declaration(bundle_id: &str, ext: &str, conforms: &str) -> String {
    format!(
        r#"
        <dict>
            <key>UTTypeIdentifier</key>
            <string>{}</string>
            <key>UTTypeDescription</key>
            <string>{}</string>
            <key>UTTypeConformsTo</key>
            <array>
                <string>{conforms}</string>
            </array>
            <key>UTTypeTagSpecification</key>
            <dict>
                <key>public.filename-extension</key>
                <array>
                    <string>{}</string>
                </array>
            </dict>
        </dict>"#,
        xml(&imported_type(bundle_id, ext)),
        xml(&ext.to_uppercase()),
        xml(ext)
    )
}

/// `NSServices`: the items of `[[app.opens]]`, which Finder's context menu
/// shows among its Quick Actions. A service names content types only, so
/// extensions the system may not know get a type of their own.
fn services(app: &Application, executable: &str) -> String {
    let bundle_id = &app.app.bundle_id;
    let default = &app.languages.default;
    let mut items = String::new();
    let mut imported = BTreeMap::new();
    for opens in &app.app.opens {
        let Some(title) = opens.menu_text(default, default) else {
            continue;
        };
        let mut types: Vec<String> = opens
            .kinds()
            .filter(|kind| !kind.starts_with('.'))
            .map(|kind| system_type(kind).to_string())
            .collect();
        for kind in opens.kinds() {
            let (extensions, conforms) = match kind.strip_prefix('.') {
                Some(ext) => (vec![ext], "public.data"),
                None => (
                    bern_ir::spec::file_kind_extensions(kind).to_vec(),
                    system_type(kind),
                ),
            };
            for ext in extensions {
                types.push(imported_type(bundle_id, ext));
                imported.insert(ext.to_string(), conforms);
            }
        }
        let types: String = types
            .iter()
            .map(|kind| format!("\n                <string>{}</string>", xml(kind)))
            .collect();
        items.push_str(&format!(
            r#"
        <dict>
            <key>NSMenuItem</key>
            <dict>
                <key>default</key>
                <string>{title}</string>
            </dict>
            <key>NSMessage</key>
            <string>bernOpenFiles</string>
            <key>NSPortName</key>
            <string>{executable}</string>
            <key>NSRequiredContext</key>
            <dict/>
            <key>NSSendFileTypes</key>
            <array>{types}
            </array>
        </dict>"#,
            title = xml(title),
            executable = xml(executable),
        ));
    }
    if items.is_empty() {
        return String::new();
    }
    let mut out = format!("\n    <key>NSServices</key>\n    <array>{items}\n    </array>");
    if !imported.is_empty() {
        let declarations: String = imported
            .iter()
            .map(|(ext, conforms)| imported_declaration(bundle_id, ext, conforms))
            .collect();
        out.push_str(&format!(
            "\n    <key>UTImportedTypeDeclarations</key>\n    <array>{declarations}\n    </array>"
        ));
    }
    out
}

/// `ServicesMenu.strings` per language, which translates the items of
/// [`services`]: macOS only, relative to `Contents/Resources`.
pub fn services_menu_files(app: &Application) -> Vec<(PathBuf, String)> {
    let default = &app.languages.default;
    let items: Vec<_> = app
        .app
        .opens
        .iter()
        .filter_map(|opens| Some((opens, opens.menu_text(default, default)?)))
        .collect();
    if items.is_empty() {
        return Vec::new();
    }
    app.languages
        .supported
        .iter()
        .map(|language| {
            let table: String = items
                .iter()
                .map(|(opens, title)| {
                    let text = opens.menu_text(language, default).unwrap_or(title);
                    format!(
                        "\"{}\" = \"{}\";\n",
                        escape_strings(title),
                        escape_strings(text)
                    )
                })
                .collect();
            (format!("{language}.lproj/ServicesMenu.strings").into(), table)
        })
        .collect()
}

/// `CFBundleDocumentTypes` for the kinds the application opens, so the
/// system offers it under "Open With" without making it the default. On
/// macOS extensions the system may not know are listed as extensions; iOS
/// only takes types, so it imports one for each and opens files in place.
fn document_types(app: &Application, ios: bool) -> String {
    document_entries(&app.opened_kinds(), &app.app.bundle_id, ios)
}

fn document_entries(kinds: &[String], bundle_id: &str, ios: bool) -> String {
    if kinds.is_empty() {
        return String::new();
    }
    // The names Finder shows in an app's document types.
    let title = |kind: &str| match kind.strip_prefix('.') {
        Some(ext) => format!("{} File", ext.to_uppercase()),
        None => match kind {
            "video" => "Video".into(),
            "audio" => "Audio".into(),
            "picture" => "Picture".into(),
            "folder" => "Folder".into(),
            _ => "File".into(),
        },
    };
    let strings = |values: &[String]| -> String {
        values
            .iter()
            .map(|value| format!("\n                <string>{}</string>", xml(value)))
            .collect()
    };
    let mut entries = Vec::new();
    let mut declarations = Vec::new();
    let mut entry = |name: &str, key: &str, values: &[String]| {
        entries.push(format!(
            r#"
        <dict>
            <key>CFBundleTypeName</key>
            <string>{name}</string>
            <key>CFBundleTypeRole</key>
            <string>Viewer</string>
            <key>LSHandlerRank</key>
            <string>Alternate</string>
            <key>{key}</key>
            <array>{}
            </array>
        </dict>"#,
            strings(values)
        ))
    };
    for kind in kinds {
        let (extensions, conforms): (Vec<String>, &str) = match kind.strip_prefix('.') {
            Some(ext) => (vec![ext.to_string()], "public.data"),
            None => (
                bern_ir::spec::file_kind_extensions(kind)
                    .iter()
                    .map(|ext| (*ext).to_string())
                    .collect(),
                system_type(kind),
            ),
        };
        let mut types = Vec::new();
        if !kind.starts_with('.') {
            types.push(system_type(kind).to_string());
        }
        if ios {
            for ext in &extensions {
                types.push(imported_type(bundle_id, ext));
                declarations.push(imported_declaration(bundle_id, ext, conforms));
            }
            entry(&title(kind), "LSItemContentTypes", &types);
        } else {
            if !types.is_empty() {
                entry(&title(kind), "LSItemContentTypes", &types);
            }
            if !extensions.is_empty() {
                entry(&title(kind), "CFBundleTypeExtensions", &extensions);
            }
        }
    }
    let mut out = format!(
        "\n    <key>CFBundleDocumentTypes</key>\n    <array>{}\n    </array>",
        entries.concat()
    );
    if ios {
        out.push_str(&format!(
            "\n    <key>UTImportedTypeDeclarations</key>\n    <array>{}\n    </array>\n    <key>LSSupportsOpeningDocumentsInPlace</key>\n    <true/>",
            declarations.concat()
        ));
    }
    out
}

