//! Bundle resources: Info.plist, per-language string tables and the rules
//! for declared resource files.

use crate::swift::Platform;
use bern_ir::Application;
use bern_target_api::Diagnostic;
use std::collections::BTreeMap;
use std::path::PathBuf;

pub use bern_target_api::texts::{FRAMEWORK_TEXTS, framework_languages};

fn escape_strings(value: &str) -> String {
    let mut out = String::new();
    for c in value.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out
}

/// Convert Bern placeholders to positional format specifiers. Texts without
/// parameters are returned unchanged because they are not formatted.
pub fn format_string(text: &str, params: &[String]) -> String {
    bern_target_api::texts::positional(text, params, |position| format!("%{position}$@"))
}

use bern_target_api::texts::{framework, translation};

/// `Localizable.strings` contents per language.
pub fn string_tables(app: &Application) -> BTreeMap<String, String> {
    let mut tables = BTreeMap::new();
    for language in &app.languages.supported {
        let mut lines = vec![format!(
            "/* Generated by Bern for {language}. Translations are declared in Rust. */"
        )];
        for text in &app.texts {
            // A text with arguments keeps Bern's format, which the runtime
            // writes out; one without is shown as it is.
            let value = translation(text, language, &app.languages.default);
            let value = if text.params.is_empty() {
                format_string(value, &[])
            } else {
                value.to_string()
            };
            lines.push(format!(
                "\"{}\" = \"{}\";",
                escape_strings(&text.key),
                escape_strings(&value)
            ));
        }
        for (key, translations) in bern_protocol::format::date_names() {
            let value = translations
                .iter()
                .find(|(candidate, _)| candidate == language)
                .or_else(|| {
                    translations
                        .iter()
                        .find(|(candidate, _)| *candidate == "en")
                })
                .map(|(_, value)| value.as_str())
                .unwrap_or("");
            lines.push(format!("\"{key}\" = \"{}\";", escape_strings(value)));
        }
        for (key, translations) in FRAMEWORK_TEXTS {
            let value = framework(translations, language);
            lines.push(format!("\"{key}\" = \"{}\";", escape_strings(value)));
        }
        lines.push(String::new());
        tables.insert(language.clone(), lines.join("\n"));
    }
    tables
}

/// Localization files generated into `Contents/Resources`, with paths
/// relative to that directory.
pub fn localization_files(app: &Application) -> Vec<(PathBuf, String)> {
    let mut files: Vec<(PathBuf, String)> = string_tables(app)
        .into_iter()
        .map(|(language, table)| {
            (
                format!("{language}.lproj/Localizable.strings").into(),
                table,
            )
        })
        .collect();
    files.extend(
        info_plist_tables(app)
            .into_iter()
            .map(|(language, table)| (format!("{language}.lproj/InfoPlist.strings").into(), table)),
    );
    files
}

/// Declared resources the bundle cannot hold. A resource `a/b.ext` ships
/// as `Contents/Resources/a/b.ext`: its directories may not contain `.`,
/// because code signing treats such directories as nested bundles, and no
/// part may end in `.lproj`, which holds the generated localizations.
/// What an iOS app bundle holds at its top besides the executable, the
/// icon images and the localizations.
const IOS_BUNDLE_FILES: &[&str] = &[
    "Info.plist",
    "PkgInfo",
    "Assets.car",
    "_CodeSignature",
    "embedded.mobileprovision",
    "Frameworks",
    "PlugIns",
    "SC_Info",
];

pub fn check_declared(app: &Application, platform: Platform) -> Vec<Diagnostic> {
    let system = match platform {
        Platform::Macos => "macOS",
        Platform::Ios => "iOS",
    };
    // An iOS bundle keeps its own files at the top, next to the resources.
    let product = crate::product_name(app);
    let reserved = |first: &str| -> bool {
        platform == Platform::Ios
            && (IOS_BUNDLE_FILES.contains(&first)
                || first == product
                || first.starts_with(crate::ios::ICON_NAME))
    };
    let mut diagnostics = Vec::new();
    for resource in &app.resources {
        let segments: Vec<&str> = resource.name.split('/').collect();
        let (_, directories) = segments.split_last().expect("names are not empty");
        let problem = if let Some(part) = segments.iter().find(|part| part.ends_with(".lproj")) {
            format!("`{part}` is where the {system} bundle keeps localizations")
        } else if platform == Platform::Macos && resource.name == crate::ICON_FILE {
            format!("`{}` is the application icon", crate::ICON_FILE)
        } else if reserved(segments[0]) {
            format!("`{}` is a file of the iOS bundle itself", segments[0])
        } else if let Some(directory) = directories.iter().find(|part| part.contains('.')) {
            format!(
                "the directory `{directory}` contains `.`, which code signing reads as a nested bundle"
            )
        } else {
            continue;
        };
        diagnostics.push(
            Diagnostic::error(format!(
                "resource `{}` cannot ship in the {system} app: {problem}; rename it",
                resource.name
            ))
            .at(resource.declared.clone()),
        );
    }
    diagnostics
}

/// `InfoPlist.strings` contents per language, localizing the app name.
pub fn info_plist_tables(app: &Application) -> BTreeMap<String, String> {
    app.languages
        .supported
        .iter()
        .map(|language| {
            let name = escape_strings(translation(&app.app.name, language, &app.languages.default));
            (
                language.clone(),
                format!("CFBundleName = \"{name}\";\nCFBundleDisplayName = \"{name}\";\n"),
            )
        })
        .collect()
}

fn xml(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

pub fn info_plist(app: &Application, executable: &str, minimum_system: &str) -> String {
    let name = translation(
        &app.app.name,
        &app.languages.default,
        &app.languages.default,
    );
    let localizations: String = app
        .languages
        .supported
        .iter()
        .map(|language| format!("\n        <string>{}</string>", xml(language)))
        .collect();
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key>
    <string>{region}</string>
    <key>CFBundleDisplayName</key>
    <string>{name}</string>
    <key>CFBundleExecutable</key>
    <string>{executable}</string>
    <key>CFBundleIconFile</key>
    <string>AppIcon</string>
    <key>CFBundleIdentifier</key>
    <string>{bundle}</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleLocalizations</key>
    <array>{localizations}
    </array>
    <key>CFBundleName</key>
    <string>{name}</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>{version}</string>
    <key>CFBundleVersion</key>
    <string>{version}</string>
    <key>LSMinimumSystemVersion</key>
    <string>{minimum_system}</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>NSSupportsAutomaticTermination</key>
    <false/>{documents}
</dict>
</plist>
"#,
        region = xml(&app.languages.default),
        name = xml(name),
        executable = xml(executable),
        bundle = xml(&app.app.bundle_id),
        version = xml(&app.app.version),
        documents = document_types(app, false),
    )
}

/// The kinds of file the application opens: those of every `Drop` with
/// `opens: true`, each once, in a stable order.
fn opened_kinds(app: &Application) -> Vec<String> {
    let mut kinds = std::collections::BTreeSet::new();
    for component in &app.components {
        component.body.walk(&mut |node| {
            if let bern_ir::Node::Element(element) = node
                && element.kind == "Drop"
                && element.keyword("opens") == Some("true")
            {
                for word in element.keyword("files").unwrap_or("any").split(' ') {
                    kinds.insert(word.to_string());
                }
            }
        });
    }
    kinds.into_iter().collect()
}

/// `CFBundleDocumentTypes` for the kinds the application opens, so the
/// system offers it under "Open With" without making it the default. On
/// macOS extensions the system may not know are listed as extensions; iOS
/// only takes types, so it imports one for each and opens files in place.
fn document_types(app: &Application, ios: bool) -> String {
    document_entries(&opened_kinds(app), &app.app.bundle_id, ios)
}

fn document_entries(kinds: &[String], bundle_id: &str, ios: bool) -> String {
    if kinds.is_empty() {
        return String::new();
    }
    let system_type = |kind: &str| match kind {
        "video" => "public.movie",
        "audio" => "public.audio",
        "picture" => "public.image",
        "folder" => "public.folder",
        _ => "public.item",
    };
    let imported = |ext: &str| format!("{bundle_id}.file.{ext}");
    // The names Finder shows in an app's document types.
    let title = |kind: &str| match kind.strip_prefix('.') {
        Some(ext) => format!("{} File", ext.to_uppercase()),
        None => match kind {
            "video" => "Video".into(),
            "audio" => "Audio".into(),
            "picture" => "Picture".into(),
            "folder" => "Folder".into(),
            _ => "File".into(),
        },
    };
    let strings = |values: &[String]| -> String {
        values
            .iter()
            .map(|value| format!("\n                <string>{}</string>", xml(value)))
            .collect()
    };
    let mut entries = Vec::new();
    let mut declarations = Vec::new();
    let mut entry = |name: &str, key: &str, values: &[String]| {
        entries.push(format!(
            r#"
        <dict>
            <key>CFBundleTypeName</key>
            <string>{name}</string>
            <key>CFBundleTypeRole</key>
            <string>Viewer</string>
            <key>LSHandlerRank</key>
            <string>Alternate</string>
            <key>{key}</key>
            <array>{}
            </array>
        </dict>"#,
            strings(values)
        ))
    };
    for kind in kinds {
        let (extensions, conforms): (Vec<String>, &str) = match kind.strip_prefix('.') {
            Some(ext) => (vec![ext.to_string()], "public.data"),
            None => (
                bern_ir::spec::file_kind_extensions(kind)
                    .iter()
                    .map(|ext| (*ext).to_string())
                    .collect(),
                system_type(kind),
            ),
        };
        let mut types = Vec::new();
        if !kind.starts_with('.') {
            types.push(system_type(kind).to_string());
        }
        if ios {
            for ext in &extensions {
                types.push(imported(ext));
                declarations.push(format!(
                    r#"
        <dict>
            <key>UTTypeIdentifier</key>
            <string>{}</string>
            <key>UTTypeDescription</key>
            <string>{}</string>
            <key>UTTypeConformsTo</key>
            <array>
                <string>{conforms}</string>
            </array>
            <key>UTTypeTagSpecification</key>
            <dict>
                <key>public.filename-extension</key>
                <array>
                    <string>{}</string>
                </array>
            </dict>
        </dict>"#,
                    xml(&imported(ext)),
                    xml(&ext.to_uppercase()),
                    xml(ext)
                ));
            }
            entry(&title(kind), "LSItemContentTypes", &types);
        } else {
            if !types.is_empty() {
                entry(&title(kind), "LSItemContentTypes", &types);
            }
            if !extensions.is_empty() {
                entry(&title(kind), "CFBundleTypeExtensions", &extensions);
            }
        }
    }
    let mut out = format!(
        "\n    <key>CFBundleDocumentTypes</key>\n    <array>{}\n    </array>",
        entries.concat()
    );
    if ios {
        out.push_str(&format!(
            "\n    <key>UTImportedTypeDeclarations</key>\n    <array>{}\n    </array>\n    <key>LSSupportsOpeningDocumentsInPlace</key>\n    <true/>",
            declarations.concat()
        ));
    }
    out
}

/// The Info.plist of an iOS app for the simulator: several scenes, which
/// iPad opens as windows (iPhone keeps one); a launch screen and every
/// orientation on iPad, as resizable iPad windows need; the icon from the
/// compiled asset catalog.
pub fn info_plist_ios(app: &Application, executable: &str, minimum_ios: &str) -> String {
    let name = translation(
        &app.app.name,
        &app.languages.default,
        &app.languages.default,
    );
    let localizations: String = app
        .languages
        .supported
        .iter()
        .map(|language| format!("\n        <string>{}</string>", xml(language)))
        .collect();
    let icons = format!(
        r#"<dict>
        <key>CFBundlePrimaryIcon</key>
        <dict>
            <key>CFBundleIconName</key>
            <string>{icon}</string>
        </dict>
    </dict>"#,
        icon = crate::ios::ICON_NAME
    );
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key>
    <string>{region}</string>
    <key>CFBundleDisplayName</key>
    <string>{name}</string>
    <key>CFBundleExecutable</key>
    <string>{executable}</string>
    <key>CFBundleIcons</key>
    {icons}
    <key>CFBundleIcons~ipad</key>
    {icons}
    <key>CFBundleIdentifier</key>
    <string>{bundle}</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleLocalizations</key>
    <array>{localizations}
    </array>
    <key>CFBundleName</key>
    <string>{name}</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>{version}</string>
    <key>CFBundleSupportedPlatforms</key>
    <array>
        <string>iPhoneSimulator</string>
    </array>
    <key>CFBundleVersion</key>
    <string>{version}</string>
    <key>LSRequiresIPhoneOS</key>
    <true/>
    <key>MinimumOSVersion</key>
    <string>{minimum_ios}</string>
    <key>UIApplicationSceneManifest</key>
    <dict>
        <key>UIApplicationSupportsMultipleScenes</key>
        <true/>
    </dict>
    <key>UIDeviceFamily</key>
    <array>
        <integer>1</integer>
        <integer>2</integer>
    </array>
    <key>UILaunchScreen</key>
    <dict/>
    <key>UISupportedInterfaceOrientations</key>
    <array>
        <string>UIInterfaceOrientationPortrait</string>
        <string>UIInterfaceOrientationLandscapeLeft</string>
        <string>UIInterfaceOrientationLandscapeRight</string>
    </array>
    <key>UISupportedInterfaceOrientations~ipad</key>
    <array>
        <string>UIInterfaceOrientationPortrait</string>
        <string>UIInterfaceOrientationPortraitUpsideDown</string>
        <string>UIInterfaceOrientationLandscapeLeft</string>
        <string>UIInterfaceOrientationLandscapeRight</string>
    </array>{documents}
</dict>
</plist>
"#,
        region = xml(&app.languages.default),
        name = xml(name),
        executable = xml(executable),
        bundle = xml(&app.app.bundle_id),
        version = xml(&app.app.version),
        documents = document_types(app, true),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn placeholders_become_positional_specifiers() {
        let params = vec!["count".to_string(), "name".to_string()];
        assert_eq!(
            format_string("{name} 已播放 {count} 集 100%", &params),
            "%2$@ 已播放 %1$@ 集 100%%"
        );
        assert_eq!(format_string("100% {{x}}", &[]), "100% {x}");
        assert_eq!(escape_strings("a\"b\n"), "a\\\"b\\n");
    }

    #[test]
    fn opened_kinds_become_document_types() {
        let kinds = vec!["video".to_string(), ".ass".to_string()];
        let mac = document_entries(&kinds, "dev.example", false);
        assert!(mac.contains("<string>public.movie</string>"), "{mac}");
        assert!(mac.contains("<key>CFBundleTypeExtensions</key>"), "{mac}");
        assert!(mac.contains("<string>mkv</string>"), "{mac}");
        assert!(mac.contains("<string>ASS File</string>"), "{mac}");
        assert!(mac.contains("<string>Alternate</string>"), "{mac}");
        assert!(!mac.contains("UTImportedTypeDeclarations"), "{mac}");
        let ios = document_entries(&kinds, "dev.example", true);
        assert!(!ios.contains("CFBundleTypeExtensions"), "{ios}");
        assert!(
            ios.contains("<string>dev.example.file.mkv</string>"),
            "{ios}"
        );
        assert!(
            ios.contains("<key>LSSupportsOpeningDocumentsInPlace</key>"),
            "{ios}"
        );
        assert_eq!(document_entries(&[], "dev.example", true), "");
    }

    #[test]
    fn the_runtime_takes_the_shared_extensions() {
        let runtime = crate::runtime_source(include_str!("../templates/BernRuntime.swift"));
        assert!(!runtime.contains("bern:file-extensions"));
        assert!(
            runtime.contains(r#""video": ["mp4", "m4v", "mov", "mkv""#),
            "{}",
            &runtime[..0]
        );
    }
}
