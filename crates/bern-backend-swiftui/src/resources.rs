pub use bern_target_api::texts::{FRAMEWORK_TEXTS, framework_languages};

fn escape_strings(value: &str) -> String {
    let mut out = String::new();
    for c in value.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out
}

/// Convert Bern placeholders to positional format specifiers. Texts without
/// parameters are returned unchanged because they are not formatted.
pub fn format_string(text: &str, params: &[String]) -> String {
    bern_target_api::texts::positional(text, params, |position| format!("%{position}$@"))
}

use bern_target_api::texts::{framework, translation};

/// `Localizable.strings` contents per language.
pub fn string_tables(app: &Application) -> BTreeMap<String, String> {
    let mut tables = BTreeMap::new();
    for language in &app.languages.supported {
        let mut lines = vec![format!(
            "/* Generated by Bern for {language}. Translations are declared in Rust. */"
        )];
        for text in &app.texts {
            // A text with arguments keeps Bern's format, which the runtime
            // writes out; one without is shown as it is.
            let value = translation(text, language, &app.languages.default);
            let value = if text.params.is_empty() {
                format_string(value, &[])
            } else {
                value.to_string()
            };
            lines.push(format!(
                "\"{}\" = \"{}\";",
                escape_strings(&text.key),
                escape_strings(&value)
            ));
        }
        for (key, translations) in bern_protocol::format::date_names() {
            let value = translations
                .iter()
                .find(|(candidate, _)| candidate == language)
                .or_else(|| {
                    translations
                        .iter()
                        .find(|(candidate, _)| *candidate == "en")
                })
                .map(|(_, value)| value.as_str())
                .unwrap_or("");
            lines.push(format!("\"{key}\" = \"{}\";", escape_strings(value)));
        }
        for (key, translations) in FRAMEWORK_TEXTS {
            let value = framework(translations, language);
            lines.push(format!("\"{key}\" = \"{}\";", escape_strings(value)));
        }
        lines.push(String::new());
        tables.insert(language.clone(), lines.join("\n"));
    }
    tables
}

/// Localization files generated into `Contents/Resources`, with paths
/// relative to that directory.
pub fn localization_files(app: &Application) -> Vec<(PathBuf, String)> {
    let mut files: Vec<(PathBuf, String)> = string_tables(app)
        .into_iter()
        .map(|(language, table)| {
            (
                format!("{language}.lproj/Localizable.strings").into(),
                table,
            )
        })
        .collect();
    files.extend(
        info_plist_tables(app)
            .into_iter()
            .map(|(language, table)| (format!("{language}.lproj/InfoPlist.strings").into(), table)),
    );
    files
}

/// Declared resources the bundle cannot hold. A resource `a/b.ext` ships
/// as `Contents/Resources/a/b.ext`: its directories may not contain `.`,
/// because code signing treats such directories as nested bundles, and no
/// part may end in `.lproj`, which holds the generated localizations.
/// What an iOS app bundle holds at its top besides the executable, the
/// icon images and the localizations.
const IOS_BUNDLE_FILES: &[&str] = &[
    "Info.plist",
    "PkgInfo",
    "Assets.car",
    "_CodeSignature",
    "embedded.mobileprovision",
    "Frameworks",
    "PlugIns",
    "SC_Info",
];

pub fn check_declared(app: &Application, platform: Platform) -> Vec<Diagnostic> {
    let system = platform.system();
    // An iOS or tvOS bundle keeps its own files at the top, next to the
    // resources.
    let product = crate::product_name(app);
    let reserved = |first: &str| -> bool {
        platform.uikit()
            && (IOS_BUNDLE_FILES.contains(&first)
                || first == product
                || first.starts_with(crate::ios::ICON_NAME)
                || first.starts_with(crate::tvos::ICON_NAME))
    };
    let mut diagnostics = Vec::new();
    for resource in &app.resources {
        let segments: Vec<&str> = resource.name.split('/').collect();
        let (_, directories) = segments.split_last().expect("names are not empty");
        let problem = if let Some(part) = segments.iter().find(|part| part.ends_with(".lproj")) {
            format!("`{part}` is where the {system} bundle keeps localizations")
        } else if platform == Platform::Macos
            && [crate::ICON_FILE, "Assets.car"].contains(&resource.name.as_str())
        {
            format!("`{}` is the application icon", resource.name)
        } else if platform == Platform::Macos
            && [crate::STATUS_IMAGE, crate::STATUS_IMAGE_2X].contains(&resource.name.as_str())
        {
            format!("`{}` is the status item's picture", resource.name)
        } else if reserved(segments[0]) {
            format!("`{}` is a file of the {system} bundle itself", segments[0])
        } else if let Some(directory) = directories.iter().find(|part| part.contains('.')) {
            format!(
                "the directory `{directory}` contains `.`, which code signing reads as a nested bundle"
            )
        } else {
            continue;
        };
        diagnostics.push(
            Diagnostic::error(format!(
                "resource `{}` cannot ship in the {system} app: {problem}; rename it",
                resource.name
            ))
            .at(resource.declared.clone()),
        );
    }
    diagnostics
}

