//! Generated Rust glue crate: links the engine, the session runtime and the
//! C ABI into one static library, and builds the application CLI and MCP
//! server from the same command catalog.

use bern_ir::Application;
use bern_protocol::{EnumDef, FieldDef, RecordDef, Type, TypeTable, Value};
use bern_target_api::BuildContext;
use std::path::Path;

const P: &str = "bern_ffi::protocol";

fn rust_type(ty: &Type) -> String {
    match ty {
        Type::Unit => format!("{P}::Type::Unit"),
        Type::Bool => format!("{P}::Type::Bool"),
        Type::Int => format!("{P}::Type::Int"),
        Type::Float => format!("{P}::Type::Float"),
        Type::Text => format!("{P}::Type::Text"),
        Type::Enum { name } => format!("{P}::Type::Enum {{ name: {name:?}.into() }}"),
        Type::Record { name } => format!("{P}::Type::Record {{ name: {name:?}.into() }}"),
        Type::Optional { inner } => format!("{P}::Type::optional({})", rust_type(inner)),
        Type::List { inner } => format!("{P}::Type::list({})", rust_type(inner)),
    }
}

fn rust_value(value: &Value) -> String {
    match value {
        Value::Unit => format!("{P}::Value::Unit"),
        Value::Bool(value) => format!("{P}::Value::Bool({value})"),
        Value::Int(value) => format!("{P}::Value::Int({value})"),
        Value::Float(value) => format!("{P}::Value::Float({value:?})"),
        Value::Text(value) => format!("{P}::Value::Text({value:?}.into())"),
        Value::Enum { variant, fields } => format!(
            "{P}::Value::Enum {{ variant: {variant}, fields: vec![{}] }}",
            fields.iter().map(rust_value).collect::<Vec<_>>().join(", ")
        ),
        Value::Optional(None) => format!("{P}::Value::Optional(None)"),
        Value::Optional(Some(value)) => format!("{P}::Value::some({})", rust_value(value)),
        Value::Record(values) => format!(
            "{P}::Value::Record(vec![{}])",
            values.iter().map(rust_value).collect::<Vec<_>>().join(", ")
        ),
        Value::List(values) => format!(
            "{P}::Value::List(vec![{}])",
            values.iter().map(rust_value).collect::<Vec<_>>().join(", ")
        ),
    }
}

fn rust_field(field: &FieldDef) -> String {
    format!(
        "{P}::FieldDef {{ name: {:?}.into(), ty: {}, doc: String::new() }}",
        field.name,
        rust_type(&field.ty)
    )
}

fn rust_enum(def: &EnumDef) -> String {
    let variants: Vec<_> = def
        .variants
        .iter()
        .map(|variant| {
            format!(
                "{P}::VariantDef {{ name: {:?}.into(), fields: vec![{}], label: None }}",
                variant.name,
                variant
                    .fields
                    .iter()
                    .map(rust_field)
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        })
        .collect();
    format!(
        "{P}::EnumDef {{ name: {:?}.into(), variants: vec![{}] }}",
        def.name,
        variants.join(", ")
    )
}

fn rust_record(def: &RecordDef) -> String {
    format!(
        "{P}::RecordDef {{ name: {:?}.into(), fields: vec![{}] }}",
        def.name,
        def.fields
            .iter()
            .map(rust_field)
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn rust_types(types: &TypeTable) -> String {
    format!(
        "{P}::TypeTable {{\n            enums: vec![{}],\n            records: vec![{}],\n        }}",
        types
            .enums
            .iter()
            .map(rust_enum)
            .collect::<Vec<_>>()
            .join(", "),
        types
            .records
            .iter()
            .map(rust_record)
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn path(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}

pub fn cargo_toml(context: &BuildContext, app: &Application) -> String {
    let crates = context.workspace_dir.join("crates");
    format!(
        r#"# Generated by Bern. Do not edit.
[package]
name = "bern-glue-{id}"
version = "{version}"
edition = "2024"
publish = false

[lib]
name = "bern_app"
crate-type = ["staticlib"]
path = "src/lib.rs"

[[bin]]
name = "{cli}"
path = "src/cli.rs"

[[bin]]
name = "{cli}-mcp"
path = "src/mcp.rs"

[dependencies]
bern-ffi = {{ path = "{ffi}" }}
bern-adapter-cli = {{ path = "{cli_adapter}" }}
bern-adapter-mcp = {{ path = "{mcp_adapter}" }}
{protocol} = {{ path = "{protocol_path}" }}
{engine} = {{ path = "{engine_path}" }}

[workspace]

[profile.release]
panic = "unwind"
"#,
        id = app.app.id.replace('_', "-"),
        version = app.app.version,
        cli = app.app.id.replace('_', "-"),
        ffi = path(&crates.join("bern-ffi")),
        cli_adapter = path(&crates.join("bern-adapter-cli")),
        mcp_adapter = path(&crates.join("bern-adapter-mcp")),
        protocol = context.protocol_package,
        protocol_path = path(&context.protocol_path),
        engine = context.engine_package,
        engine_path = path(&context.engine_path),
    )
}

pub fn lib_rs(context: &BuildContext, app: &Application) -> String {
    let sessions: Vec<String> = app
        .sessions
        .iter()
        .map(|session| {
            let fields: Vec<String> = session
                .fields
                .iter()
                .map(|field| {
                    format!(
                        "({:?}.into(), {}, {})",
                        field.name,
                        rust_type(&field.ty),
                        rust_value(&field.initial)
                    )
                })
                .collect();
            format!(
                "bern_ffi::SessionType {{\n                name: {:?}.into(),\n                fields: vec![{}],\n            }}",
                session.name,
                fields.join(", ")
            )
        })
        .collect();
    let windows: Vec<String> = app
        .windows
        .windows
        .iter()
        .map(|window| {
            let indices: Vec<String> = window
                .sessions
                .iter()
                .filter_map(|name| {
                    app.sessions
                        .iter()
                        .position(|session| session.name == *name)
                })
                .map(|index| index.to_string())
                .collect();
            format!(
                "bern_ffi::WindowKind {{ id: {:?}.into(), sessions: vec![{}] }}",
                window.id,
                indices.join(", ")
            )
        })
        .collect();
    let ipc = context
        .target
        .channels
        .iter()
        .any(|channel| channel == "ipc");
    format!(
        r#"//! Generated by Bern. Do not edit.
//!
//! Links the `{namespace}` engine, the UI session runtime and the C ABI
//! into the static library the native frontend calls in-process.

pub use bern_ffi::{{BernApp, BernBuffer, BernCallbacks}};

/// Start the engine for the frontend generated from the same catalog.
///
/// # Safety
/// `error` must be null or point to writable memory for one `BernBuffer`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_app_start(
    fingerprint: u64,
    callbacks: BernCallbacks,
    error: *mut BernBuffer,
) -> *mut BernApp {{
    // SAFETY: forwarded from the caller.
    unsafe {{
        bern_ffi::start_app(
            || {protocol}::Adapter(<{engine} as ::std::default::Default>::default()),
            spec(),
            fingerprint,
            callbacks,
            error,
        )
    }}
}}

fn spec() -> bern_ffi::AppSpec {{
    bern_ffi::AppSpec {{
        bundle_id: {bundle:?},
        ipc: {ipc},
        players: vec![{players}],
        session: bern_ffi::runtime::SessionSpec {{
        types: {types},
        sessions: vec![
            {sessions}
        ],
        windows: vec![
            {windows}
        ],
        }},
    }}
}}
"#,
        namespace = app.protocol.namespace,
        protocol = context.protocol_module,
        engine = context.engine_type,
        bundle = app.app.bundle_id,
        types = rust_types(&app.types),
        sessions = sessions.join(",\n            "),
        windows = windows.join(",\n            "),
        players = app
            .players
            .iter()
            .map(|player| format!("{:?}.into()", player.id))
            .collect::<Vec<_>>()
            .join(", "),
    )
}

pub fn cli_rs(context: &BuildContext, app: &Application) -> String {
    format!(
        r#"//! Generated by Bern. Application CLI derived from the command catalog.

fn main() {{
    std::process::exit(bern_adapter_cli::run(
        {protocol}::descriptor(),
        {bundle:?},
        {name:?},
    ));
}}
"#,
        protocol = context.protocol_module,
        bundle = app.app.bundle_id,
        name = app.app.id.replace('_', "-"),
    )
}

pub fn mcp_rs(context: &BuildContext, app: &Application) -> String {
    format!(
        r#"//! Generated by Bern. MCP server derived from the command catalog.

fn main() {{
    std::process::exit(bern_adapter_mcp::run(
        {protocol}::descriptor(),
        {bundle:?},
        {name:?},
        {version:?},
    ));
}}
"#,
        protocol = context.protocol_module,
        bundle = app.app.bundle_id,
        name = app.app.id.replace('_', "-"),
        version = app.app.version,
    )
}
