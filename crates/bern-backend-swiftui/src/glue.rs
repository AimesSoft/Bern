//! Generated Rust glue crate: links the engine, the session runtime and the
//! C ABI into one static library, and builds the application CLI and MCP
//! server from the same command catalog.

use crate::swift::Platform;
use bern_ir::Application;
use bern_ir::WindowRole;
use bern_target_api::BuildContext;
use bern_target_api::glue::{
    WindowPresentation, engine_expr, module_dependencies, path, players_expr, resources_expr,
    session_spec, session_spec_with,
};
pub use bern_target_api::glue::{cli_rs, mcp_rs};

/// The iOS engine library's switch for native windows, which the app sets
/// before it starts the engine.
const NATIVE_WINDOWS: &str = r#"
static NATIVE_WINDOWS: ::std::sync::atomic::AtomicBool = ::std::sync::atomic::AtomicBool::new(false);

/// Whether windows other than settings are native windows: the app runs
/// where it can open several windows, such as on iPad. Call before
/// `bern_app_start`.
#[unsafe(no_mangle)]
pub extern "C" fn bern_app_native_windows(native: u8) {
    NATIVE_WINDOWS.store(native != 0, ::std::sync::atomic::Ordering::Relaxed);
}
"#;

pub fn cargo_toml(context: &BuildContext, app: &Application) -> String {
    let bern = |name: &str| context.framework.dependency(name);
    format!(
        r#"# Generated by Bern. Do not edit.
[package]
name = "bern-glue-{id}"
version = "{version}"
edition = "2024"
publish = false

[lib]
name = "bern_app"
crate-type = ["staticlib"]
path = "src/lib.rs"

[[bin]]
name = "{cli}"
path = "src/cli.rs"

[[bin]]
name = "{cli}-mcp"
path = "src/mcp.rs"

[dependencies]
bern-ffi = {{ {ffi} }}
bern-adapter-cli = {{ {cli_adapter} }}
bern-adapter-mcp = {{ {mcp_adapter} }}
{protocol} = {{ path = "{protocol_path}" }}
{engine} = {{ path = "{engine_path}" }}
{modules}
[workspace]

[profile.release]
panic = "unwind"
"#,
        id = app.app.id.replace('_', "-"),
        version = app.app.version,
        cli = app.app.id.replace('_', "-"),
        ffi = bern("bern-ffi"),
        cli_adapter = bern("bern-adapter-cli"),
        mcp_adapter = bern("bern-adapter-mcp"),
        protocol = context.protocol_package,
        protocol_path = path(&context.protocol_path),
        engine = context.engine_package,
        engine_path = path(&context.engine_path),
        modules = module_dependencies(context, true),
    )
}

/// The engine library. On macOS every window is native. On iOS the app
/// says at start whether it can open several windows (iPad): then every
/// window but settings is native, otherwise all are virtual. On iOS the
/// IPC channel listens only where another process can reach it: in the
/// simulator, when `bern run` names the Mac's directory for it.
pub fn lib_rs(context: &BuildContext, app: &Application, platform: Platform) -> String {
    let declared = context
        .target
        .channels
        .iter()
        .any(|channel| channel == "ipc");
    let (ipc, session, native_windows) = match platform {
        Platform::Macos => (
            declared.to_string(),
            session_spec(app, WindowPresentation::Native),
            String::new(),
        ),
        Platform::Ios => (
            if declared {
                "::std::env::var_os(\"BERN_IPC_DIR\").is_some()".to_string()
            } else {
                "false".to_string()
            },
            session_spec_with(app, &|window| {
                if window.role == WindowRole::Settings {
                    "bern_ffi::runtime::Presentation::Virtual".into()
                } else {
                    "if NATIVE_WINDOWS.load(::std::sync::atomic::Ordering::Relaxed) { bern_ffi::runtime::Presentation::Native } else { bern_ffi::runtime::Presentation::Virtual }".into()
                }
            }),
            NATIVE_WINDOWS.to_string(),
        ),
    };
    format!(
        r#"//! Generated by Bern. Do not edit.
//!
//! Links the `{namespace}` engine, the UI session runtime and the C ABI
//! into the static library the native frontend calls in-process.

pub use bern_ffi::{{BernApp, BernBuffer, BernCallbacks}};

/// Start the engine for the frontend generated from the same catalog.
/// `resources` is the bundle directory holding the declared resources.
///
/// # Safety
/// `resources` must point to `resources_len` readable bytes or be null with
/// `resources_len == 0`; `error` must be null or point to writable memory
/// for one `BernBuffer`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_app_start(
    fingerprint: u64,
    resources: *const u8,
    resources_len: usize,
    callbacks: BernCallbacks,
    error: *mut BernBuffer,
) -> *mut BernApp {{
    // SAFETY: forwarded from the caller.
    unsafe {{
        bern_ffi::start_app(
            || {engine},
            spec(),
            fingerprint,
            resources,
            resources_len,
            callbacks,
            error,
        )
    }}
}}

fn spec() -> bern_ffi::AppSpec {{
    bern_ffi::AppSpec {{
        bundle_id: {bundle:?},
        ipc: {ipc},
        players: vec![{players}],
        resources: vec![{resources}],
        session: {session},
    }}
}}
{native_windows}"#,
        namespace = app.protocol.namespace,
        engine = engine_expr(context),
        bundle = app.app.bundle_id,
        players = players_expr(app),
        resources = resources_expr(app),
    )
}
