//! Generated Rust glue crates.
//!
//! * The page module (both builds): a WebAssembly module with the UI
//!   session runtime and the C ABI. Callbacks become imports from the
//!   page's `bern` module; the exports are the same C ABI the native
//!   frontends call. The `app` build links the engine into it; the `ui`
//!   build links only the protocol crate and reaches the engine through
//!   the engine host's channel.
//! * The engine host (`ui` build): a native program running the engine,
//!   the local IPC channel for the CLI, JSON and MCP entries, and the
//!   page's HTTP and WebSocket channel; plus the CLI and MCP programs.

use bern_ir::Application;
use bern_target_api::BuildContext;
use bern_target_api::glue::{WindowPresentation, players_expr, resources_expr, session_spec};
use std::path::Path;

fn path(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}

/// Name stem of the generated programs, for example `showcase`.
pub fn program(app: &Application) -> String {
    app.app.id.replace('_', "-")
}

pub fn page_cargo_toml(context: &BuildContext, app: &Application, remote: bool) -> String {
    let crates = context.workspace_dir.join("crates");
    let ffi = if remote {
        format!(
            "bern-ffi = {{ path = \"{}\", default-features = false, features = [\"remote\"] }}",
            path(&crates.join("bern-ffi"))
        )
    } else {
        format!(
            "bern-ffi = {{ path = \"{}\", default-features = false }}",
            path(&crates.join("bern-ffi"))
        )
    };
    // The WebUI page carries the protocol description only, never the
    // engine and its dependencies.
    let engine = if remote {
        String::new()
    } else {
        format!(
            "{} = {{ path = \"{}\" }}\n",
            context.engine_package,
            path(&context.engine_path)
        )
    };
    format!(
        r#"# Generated by Bern. Do not edit.
[package]
name = "bern-web-page-{id}"
version = "{version}"
edition = "2024"
publish = false

[lib]
name = "bern_web_app"
crate-type = ["cdylib"]
path = "src/lib.rs"

[dependencies]
{ffi}
{protocol} = {{ path = "{protocol_path}" }}
{engine}
[workspace]

[profile.release]
opt-level = "s"
lto = true
"#,
        id = app.app.id.replace('_', "-"),
        version = app.app.version,
        protocol = context.protocol_package,
        protocol_path = path(&context.protocol_path),
    )
}

const CALLBACKS: &str = r#"#[link(wasm_import_module = "bern")]
unsafe extern "C" {
    fn on_state(bytes: *const u8, len: usize);
    fn on_reply(token: u64, bytes: *const u8, len: usize);
    fn on_session_request(request: u64, bytes: *const u8, len: usize);
    fn on_media_request(bytes: *const u8, len: usize);
    fn on_media_state(bytes: *const u8, len: usize);
    fn on_query(subscription: u64, bytes: *const u8, len: usize);
}

// SAFETY (all callbacks): the page provides these imports, and the bytes
// stay valid for the duration of the call.
extern "C" fn state(_: *mut c_void, bytes: *const u8, len: usize) {
    unsafe { on_state(bytes, len) }
}
extern "C" fn reply(_: *mut c_void, token: u64, bytes: *const u8, len: usize) {
    unsafe { on_reply(token, bytes, len) }
}
extern "C" fn session_request(_: *mut c_void, request: u64, bytes: *const u8, len: usize) {
    unsafe { on_session_request(request, bytes, len) }
}
extern "C" fn media_request(_: *mut c_void, bytes: *const u8, len: usize) {
    unsafe { on_media_request(bytes, len) }
}
extern "C" fn media_state(_: *mut c_void, bytes: *const u8, len: usize) {
    unsafe { on_media_state(bytes, len) }
}
extern "C" fn query(_: *mut c_void, subscription: u64, bytes: *const u8, len: usize) {
    unsafe { on_query(subscription, bytes, len) }
}

fn callbacks() -> BernCallbacks {
    BernCallbacks {
        context: std::ptr::null_mut(),
        on_state: state,
        on_reply: reply,
        on_session_request: session_request,
        on_media_request: media_request,
        on_media_state: media_state,
        on_query: query,
    }
}
"#;

fn spec_fn(app: &Application) -> String {
    format!(
        r#"fn spec() -> bern_ffi::AppSpec {{
    bern_ffi::AppSpec {{
        bundle_id: {bundle:?},
        ipc: false,
        players: vec![{players}],
        resources: vec![{resources}],
        session: {session},
    }}
}}
"#,
        bundle = app.app.bundle_id,
        session = session_spec(app, WindowPresentation::Virtual),
        players = players_expr(app),
        resources = resources_expr(app),
    )
}

pub fn page_lib_rs(context: &BuildContext, app: &Application, remote: bool) -> String {
    let start = if remote {
        format!(
            r#"#[link(wasm_import_module = "bern")]
unsafe extern "C" {{
    fn link_send(bytes: *const u8, len: usize);
    fn link_status(bytes: *const u8, len: usize);
}}

/// Start the page's runtime for an engine in a separate engine host.
/// `token` is the channel credential from the page address. Messages leave
/// through `bern.link_send`; incoming ones go to `bern_remote_receive`.
///
/// # Safety
/// `token` must point to `token_len` readable bytes.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_webui_start(token: *const u8, token_len: usize) -> *mut BernApp {{
    // SAFETY: guaranteed by the caller.
    let token = unsafe {{ std::slice::from_raw_parts(token, token_len) }};
    let token = String::from_utf8_lossy(token).into_owned();
    bern_ffi::remote::start(
        spec(),
        {protocol}::descriptor(),
        (!token.is_empty()).then_some(token),
        callbacks(),
        // SAFETY: the page provides these imports.
        Box::new(|text: &str| unsafe {{ link_send(text.as_ptr(), text.len()) }}),
        Box::new(|text: &str| unsafe {{ link_status(text.as_ptr(), text.len()) }}),
    )
}}
"#,
            protocol = context.protocol_module,
        )
    } else {
        format!(
            r#"/// Start the engine in the page for the frontend generated from the same
/// catalog. `resources` is the URL prefix the declared resources are
/// served from.
///
/// # Safety
/// `resources` must point to `resources_len` readable bytes; `error` must
/// point to writable memory for one `BernBuffer`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_web_start(
    fingerprint: u64,
    resources: *const u8,
    resources_len: usize,
    error: *mut BernBuffer,
) -> *mut BernApp {{
    // SAFETY: forwarded from the caller.
    unsafe {{
        bern_ffi::start_app(
            || {protocol}::Adapter(<{engine} as ::std::default::Default>::default()),
            spec(),
            fingerprint,
            resources,
            resources_len,
            callbacks(),
            error,
        )
    }}
}}
"#,
            protocol = context.protocol_module,
            engine = context.engine_type,
        )
    };
    let doc = if remote {
        "The page runtime of the WebUI build: the UI session runtime and the C ABI,\n//! reaching the engine in a separate engine host. Every `bern_*` export of\n//! `bern-ffi` is part of it."
    } else {
        "The engine, the UI session runtime and the C ABI as one WebAssembly\n//! module. Every `bern_*` export of `bern-ffi` is part of it."
    };
    let imports = if remote {
        "use bern_ffi::{BernApp, BernCallbacks};"
    } else {
        "use bern_ffi::{BernApp, BernBuffer, BernCallbacks};"
    };
    format!(
        "//! Generated by Bern. Do not edit.\n//!\n//! {doc}\n\n{imports}\nuse std::ffi::c_void;\n\n{CALLBACKS}\n{start}\n{}",
        spec_fn(app)
    )
}

