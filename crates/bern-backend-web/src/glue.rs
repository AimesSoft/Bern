//! Generated Rust glue crate of the `app` build: links the engine, the UI
//! session runtime and the C ABI into one WebAssembly module the page
//! loads. Callbacks become imports from the page's `bern` module; the
//! exports are the same C ABI the native frontends call.

use bern_ir::Application;
use bern_target_api::BuildContext;
use bern_target_api::glue::{WindowPresentation, players_expr, resources_expr, session_spec};
use std::path::Path;

fn path(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}

pub fn cargo_toml(context: &BuildContext, app: &Application) -> String {
    let crates = context.workspace_dir.join("crates");
    format!(
        r#"# Generated by Bern. Do not edit.
[package]
name = "bern-web-glue-{id}"
version = "{version}"
edition = "2024"
publish = false

[lib]
name = "bern_web_app"
crate-type = ["cdylib"]
path = "src/lib.rs"

[dependencies]
bern-ffi = {{ path = "{ffi}", default-features = false }}
{protocol} = {{ path = "{protocol_path}" }}
{engine} = {{ path = "{engine_path}" }}

[workspace]

[profile.release]
opt-level = "s"
lto = true
"#,
        id = app.app.id.replace('_', "-"),
        version = app.app.version,
        ffi = path(&crates.join("bern-ffi")),
        protocol = context.protocol_package,
        protocol_path = path(&context.protocol_path),
        engine = context.engine_package,
        engine_path = path(&context.engine_path),
    )
}

pub fn lib_rs(context: &BuildContext, app: &Application) -> String {
    format!(
        r#"//! Generated by Bern. Do not edit.
//!
//! The `{namespace}` engine, the UI session runtime and the C ABI as one
//! WebAssembly module. Every `bern_*` export of `bern-ffi` is part of it.

use bern_ffi::{{BernApp, BernBuffer, BernCallbacks}};
use std::ffi::c_void;

#[link(wasm_import_module = "bern")]
unsafe extern "C" {{
    fn on_state(bytes: *const u8, len: usize);
    fn on_reply(token: u64, bytes: *const u8, len: usize);
    fn on_session_request(request: u64, bytes: *const u8, len: usize);
    fn on_media_request(bytes: *const u8, len: usize);
    fn on_media_state(bytes: *const u8, len: usize);
    fn on_query(subscription: u64, bytes: *const u8, len: usize);
}}

// SAFETY (all callbacks): the page provides these imports, and the bytes
// stay valid for the duration of the call.
extern "C" fn state(_: *mut c_void, bytes: *const u8, len: usize) {{
    unsafe {{ on_state(bytes, len) }}
}}
extern "C" fn reply(_: *mut c_void, token: u64, bytes: *const u8, len: usize) {{
    unsafe {{ on_reply(token, bytes, len) }}
}}
extern "C" fn session_request(_: *mut c_void, request: u64, bytes: *const u8, len: usize) {{
    unsafe {{ on_session_request(request, bytes, len) }}
}}
extern "C" fn media_request(_: *mut c_void, bytes: *const u8, len: usize) {{
    unsafe {{ on_media_request(bytes, len) }}
}}
extern "C" fn media_state(_: *mut c_void, bytes: *const u8, len: usize) {{
    unsafe {{ on_media_state(bytes, len) }}
}}
extern "C" fn query(_: *mut c_void, subscription: u64, bytes: *const u8, len: usize) {{
    unsafe {{ on_query(subscription, bytes, len) }}
}}

/// Start the engine in the page for the frontend generated from the same
/// catalog. `resources` is the URL prefix the declared resources are
/// served from.
///
/// # Safety
/// `resources` must point to `resources_len` readable bytes; `error` must
/// point to writable memory for one `BernBuffer`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn bern_web_start(
    fingerprint: u64,
    resources: *const u8,
    resources_len: usize,
    error: *mut BernBuffer,
) -> *mut BernApp {{
    let callbacks = BernCallbacks {{
        context: std::ptr::null_mut(),
        on_state: state,
        on_reply: reply,
        on_session_request: session_request,
        on_media_request: media_request,
        on_media_state: media_state,
        on_query: query,
    }};
    // SAFETY: forwarded from the caller.
    unsafe {{
        bern_ffi::start_app(
            || {protocol}::Adapter(<{engine} as ::std::default::Default>::default()),
            spec(),
            fingerprint,
            resources,
            resources_len,
            callbacks,
            error,
        )
    }}
}}

fn spec() -> bern_ffi::AppSpec {{
    bern_ffi::AppSpec {{
        bundle_id: {bundle:?},
        ipc: false,
        players: vec![{players}],
        resources: vec![{resources}],
        session: {session},
    }}
}}
"#,
        namespace = app.protocol.namespace,
        protocol = context.protocol_module,
        engine = context.engine_type,
        bundle = app.app.bundle_id,
        session = session_spec(app, WindowPresentation::Virtual),
        players = players_expr(app),
        resources = resources_expr(app),
    )
}
